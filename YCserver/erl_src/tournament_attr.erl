login(Role = #role{classes = Classes,
                   m_achieve_shop = #m_achieve_shop{shops = ShopList},
                   m_tournament = MTournament = #m_tournament{},
                   lev = Level})
    when Level > 69 ->
    HoldList = case lists:keyfind(3, 1, ShopList) of
                   {_Type, GoodsList} ->
                       [BadgeId
                        || #ashop_goods_info{id = BadgeId} <- GoodsList];
                   false -> []
               end,
    AllKingBgList = [Bid
                     || {Bid, Weight} <- tournament_data:get_bglist(),
                        Weight > 0],
    KingBadgeList = [calc_badge(KbgId, HoldList, Classes)
                     || KbgId <- AllKingBgList],
    HList = [BadgeId
             || #king_badge{id = BadgeId, status = Status}
                    <- KingBadgeList,
                Status =:= 1],
    HoldNum = length(HList),
    NMTournament = MTournament#m_tournament{kingbadgenum =
                                                HoldNum,
                                            kingbadge = KingBadgeList},
    NRole2 = Role#role{m_tournament = NMTournament},
    {ok, NRole2};
login(Role) -> {ok, Role}.

calc_badge(BadgeId, HoldList, Classes) ->
    case lists:member(BadgeId, HoldList) of
        true ->
            case tournament_data:get_badges_info(BadgeId) of
                #{active_effect_type := ActiveType, fc := Fc} ->
                    case tournament_data:get_bg_attr({BadgeId, Classes}) of
                        false ->
                            logger:debug("徽章~w数据配置出错,没有配徽章属性",
                                         [BadgeId],
                                         tournament_attr,
                                         66),
                            #king_badge{};
                        ActiveAttr ->
                            #king_badge{id = BadgeId, status = 1,
                                        active_effect_type = ActiveType,
                                        active_attr = ActiveAttr, fc = Fc}
                    end;
                _ ->
                    logger:debug("徽章~w数据配置出错",
                                 [BadgeId],
                                 tournament_attr,
                                 72),
                    #king_badge{}
            end;
        _ ->
            case tournament_data:get_badges_info(BadgeId) of
                #{active_effect_type := ActiveType, fc := Fc} ->
                    case tournament_data:get_bg_attr({BadgeId, Classes}) of
                        false ->
                            logger:debug("徽章~w数据配置出错,没有配徽章属性",
                                         [BadgeId],
                                         tournament_attr,
                                         80),
                            #king_badge{};
                        ActiveAttr ->
                            #king_badge{id = BadgeId, status = 0,
                                        active_effect_type = ActiveType,
                                        active_attr = ActiveAttr, fc = Fc}
                    end;
                _ ->
                    logger:debug("徽章~w数据配置出错",
                                 [BadgeId],
                                 tournament_attr,
                                 86),
                    #king_badge{}
            end
    end.

revise_kingbadge(BadgeId, BadgeList) ->
    case lists:keytake(BadgeId, #king_badge.id, BadgeList)
        of
        {value, Record, RestList} ->
            NewRecord = Record#king_badge{status = 1},
            [NewRecord | RestList];
        _ ->
            logger:debug("徽章数据配置出错", [], tournament_attr, 99),
            BadgeList
    end.

calc_attr(Ac = #attr_calc{},
          _Role = #role{m_tournament =
                            #m_tournament{kingbadge = Kingbadge},
                        lev = Level, classes = Classes}) ->
    Ac1 = calc_role_attr(Ac, Kingbadge),
    SetList = get_activeset(Kingbadge),
    Ac2 = calc_set_attr(Ac1, SetList, Level, Classes),
    Ac2.

calc_role_attr(Ac, []) -> Ac;
calc_role_attr(Ac,
               [#king_badge{id = _BadgeId, status = 1,
                            active_effect_type = 3,
                            active_attr = Attr = [_ | _]}
                | T]) ->
    Attr1 = attr_type:to_attr(fixed, Attr),
    NewAc = case attr_type:do_attr(Attr1, Ac) of
                {false, _Reason} ->
                    logger:debug("徽章[~w]属性计算失败",
                                 [_BadgeId, _Reason],
                                 tournament_attr,
                                 120),
                    Ac;
                {ok, Ac1} -> Ac1
            end,
    calc_role_attr(NewAc, T);
calc_role_attr(Ac, [_ | T]) -> calc_role_attr(Ac, T).

calc_set_attr(Ac, SetList, Level, Classes) ->
    SetAttrList = get_set_attr([], SetList, Level, Classes),
    SetAttr = attr_type:to_attr(fixed, SetAttrList),
    case attr_type:do_attr(SetAttr, Ac) of
        {false, Reason} ->
            logger:error("徽章组合属性计算失败:~w",
                         [Reason],
                         tournament_attr,
                         136),
            Ac;
        {ok, NewAc} -> NewAc
    end.

get_set_attr(Ac, [], _Level, _Classes) -> Ac;
get_set_attr(Ac, [Sid | T], Level, Classes) ->
    AttrList = case tournament_data:get_bg_attr({Sid,
                                                 Classes})
                   of
                   false ->
                       logger:debug("徽章组合~w数据配置出错,没有配属性",
                                    [Sid],
                                    tournament_attr,
                                    146),
                       Ac;
                   ActiveAttr ->
                       logger:debug("===~w", [Sid], tournament_attr, 149),
                       ActiveAttr ++ Ac
               end,
    get_set_attr(AttrList, T, Level, Classes).

get_activeset(Kingbadge) ->
    get_activeset(Kingbadge, []).

get_activeset([], SetList) ->
    Fun = fun ({Sid, Num}, AllSet) ->
                  case tournament_data:get_bg_set(Sid) of
                      #{max_num := MaxNum} when Num >= MaxNum ->
                          logger:debug("激活套装:~w", [Sid], tournament_attr, 216),
                          [Sid | AllSet];
                      _ -> AllSet
                  end
          end,
    lists:foldl(Fun, [], SetList);
get_activeset([#king_badge{status = 1, id = BadgeId}
               | T],
              AllSetList) ->
    case tournament_data:get_badges_info(BadgeId) of
        #{set_id := SetIds} ->
            Fun = fun (Sid, SetList) ->
                          case lists:keytake(Sid, 1, SetList) of
                              {value, {_, Num}, RestSetList} ->
                                  [{Sid, Num + 1} | RestSetList];
                              _ -> [{Sid, 1} | SetList]
                          end
                  end,
            NewAllSetList = lists:foldl(Fun, AllSetList, SetIds),
            get_activeset(T, NewAllSetList);
        _ -> get_activeset(T, AllSetList)
    end;
get_activeset([_ | T], SetList) ->
    get_activeset(T, SetList).

