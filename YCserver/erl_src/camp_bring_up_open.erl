reload() ->
    case get_day() of
        0 -> ok;
        Day ->
            role_group:apply(world,
                             {camp_bring_up_open, zero_flush, [Day]})
    end.

login(Role) ->
    case get_day() of
        0 -> ok;
        Day ->
            {_, NRole} = role_trigger:add([#trigger{label =
                                                        evt_activity,
                                                    a = [],
                                                    m = camp_bring_up_open,
                                                    f = apply_evt}],
                                          Role),
            zero_flush(NRole, Day),
            {ok, NRole}
    end.

push(Role) ->
    case get_day() of
        0 -> ok;
        Day -> zero_flush(Role, Day)
    end.

make_buy_info(_Times, Type, RtnL) when Type < 0 -> RtnL;
make_buy_info(Times, Type, RtnL) ->
    Num = case catch lists:keyfind(Type, 1, Times) of
              {Type, _Num} -> _Num;
              _ -> 0
          end,
    make_buy_info(Times, Type - 1, [{Type, Num} | RtnL]).

zero_flush(Role = #role{lev = Lev, sex = Sex,
                        classes = Classes},
           Day) ->
    GourpNum = case catch
                        lists:max(camp_bring_up_open_data:list_all_type())
                   of
                   Num when is_integer(Num) -> Num;
                   _ -> -1
               end,
    TimesL = var:get_var(Role, other, 2144, []),
    BuyList = case lists:keyfind(Day, 1, TimesL) of
                  {Day, Times} -> make_buy_info(Times, GourpNum, []);
                  _ -> make_buy_info([], GourpNum, [])
              end,
    logger:debug("~w", [BuyList], camp_bring_up_open, 87),
    CampInfo = make_data(GourpNum,
                         [],
                         #{lev => Lev, sex => Sex, classes => Classes,
                           day => Day, buy_list => BuyList}),
    {BringLev, BringVal} = var:get_var(Role,
                                       other,
                                       2143,
                                       {1, 0}),
    {BringInfo, LevupPoint} = make_bring_info(BringLev),
    BringGift = make_bring_gift(),
    Activity = var:get_var(Role, day, 631, 0),
    Data = {CampInfo,
            BringInfo,
            BringGift,
            LevupPoint,
            BringLev,
            BringVal,
            Activity},
    logger:debug("~w", [Data], camp_bring_up_open, 94),
    role:pack_send(Role, 20473, Data),
    ok.

active_reward(Role = #role{m_agenda = #m_agenda{}}) ->
    case get_day() of
        0 -> {false, lang:get("活动已结束，不能领取")};
        Day ->
            Activity = var:get_var(Role, day, 631, 0),
            case camp_bring_up_open_data:get_gift({Day, 0}) of
                #{need_val := NeedVal, times := ATimes}
                    when Activity >= NeedVal ->
                    Buy = get_already_buy(Role, Day, 0),
                    case Buy >= ATimes of
                        true -> {false, lang:get("今日礼包已经领取，请明天再来")};
                        _ -> get_reward(Role, Day, 0, normal)
                    end;
                #{need_val := NeedVal} when Activity < NeedVal ->
                    {false, lang:get("活跃不够，不能领取")};
                _ -> {false, lang:get("配置有误")}
            end
    end.

check_can_recharge_reward(Role = #role{name = _Name},
                          Gold) ->
    logger:debug("~w", [Gold], camp_bring_up_open, 124),
    case get_day() of
        0 -> {false, lang:get("活动已经结束不能购买")};
        Day ->
            case camp_bring_up_open_data:get_recharge_gift(Day,
                                                           Gold)
                of
                false ->
                    logger:error("~ts购买~w金额的直购礼包失败",
                                 [_Name, Gold],
                                 camp_bring_up_open,
                                 131),
                    {false, lang:get("礼包不存在或支付金额不对，购买失败")};
                {Type, ATimes} ->
                    Buy = get_already_buy(Role, Day, Type),
                    case Buy >= ATimes of
                        true -> {false, lang:get("该礼包已经售罄，请明天再来")};
                        _ -> {true, Day, Type}
                    end
            end
    end.

get_reward(Role = #role{lev = RLev, sex = RSex,
                        classes = RClasses},
           Day, Type, Flag)
    when Day > 0 ->
    Role1 = case Flag of
                gm -> Role;
                _ ->
                    TimesL = var:get_var(Role, other, 2144, []),
                    NTimesL = case lists:keyfind(Day, 1, TimesL) of
                                  {Day, Times} ->
                                      NTimes = case lists:keyfind(Type,
                                                                  1,
                                                                  Times)
                                                   of
                                                   {Type, Num} ->
                                                       lists:keystore(Type,
                                                                      1,
                                                                      Times,
                                                                      {Type,
                                                                       Num +
                                                                           1});
                                                   _ -> [{Type, 1} | Times]
                                               end,
                                      lists:keystore(Day,
                                                     1,
                                                     TimesL,
                                                     {Day, NTimes});
                                  _ -> [{Day, [{Type, 1}]} | TimesL]
                              end,
                    var:set_var(Role, other, 2144, NTimesL)
            end,
    {Title1, Content1, Title2, Content2} = case
                                               camp_bring_up_open_data:get_extra_cfg()
                                               of
                                               [#{buy_mail_title := _Title1,
                                                  buy_mail_content := _Content1,
                                                  bring_mail_title := _Title2,
                                                  bring_mail_content :=
                                                      _Content2}] ->
                                                   {_Title1,
                                                    _Content1,
                                                    _Title2,
                                                    _Content2};
                                               _ ->
                                                   {lang:get("开服直购礼包"),
                                                    lang:get("由于购买时背包已满，奖励通过邮件发放"),
                                                    lang:get("亲密等级礼包"),
                                                    lang:get("亲密等级提升，奖励通过邮件发放")}
                                           end,
    case camp_bring_up_open_data:get_gift({Day, Type}) of
        #{reward := Reward, add_val := AddVal} ->
            NReward = lists:foldl(fun ({ItemId, Bind, Num}, Acc) ->
                                          [{ItemId, Bind, Num} | Acc];
                                      ({ItemId, Bind, Num, LevMin, LevMax}, Acc)
                                          when LevMin =< RLev andalso
                                                   RLev =< LevMax ->
                                          [{ItemId, Bind, Num} | Acc];
                                      ({ItemId,
                                        Bind,
                                        Num,
                                        LevMin,
                                        LevMax,
                                        Sex,
                                        _},
                                       Acc)
                                          when LevMin =< RLev andalso
                                                   RLev =< LevMax andalso
                                                       (Sex =:= RSex orelse
                                                            Sex =:= 2) ->
                                          [{ItemId, Bind, Num} | Acc];
                                      ({ItemId,
                                        Bind,
                                        Num,
                                        LevMin,
                                        LevMax,
                                        Sex,
                                        Classes,
                                        _},
                                       Acc)
                                          when LevMin =< RLev andalso
                                                   RLev =< LevMax andalso
                                                       (Sex =:= RSex orelse
                                                            Sex =:= 2)
                                                           andalso
                                                           (Classes =:= RClasses
                                                                orelse
                                                                Classes =:=
                                                                    0) ->
                                          [{ItemId, Bind, Num} | Acc];
                                      (_, Acc) -> Acc
                                  end,
                                  [],
                                  Reward),
            Gain = format:val_to_gain(NReward),
            role:send_buff_begin(),
            Role3 = case role_gain:do_notice(Gain, Role1) of
                        {ok, Role2} ->
                            role:send_buff_flush(),
                            Role2;
                        {false, _} ->
                            role:send_buff_clean(),
                            mail:send(Role1, Title1, Content1, NReward),
                            Role1;
                        _ ->
                            role:send_buff_clean(),
                            mail:send(Role1, Title1, Content1, NReward),
                            Role1
                    end,
            {Lev, BaseVal} = var:get_var(Role3,
                                         other,
                                         2143,
                                         {1, 0}),
            BaseVal1 = BaseVal + AddVal,
            {NLev, NBaseVal} = case
                                   camp_bring_up_open_data:get_bring_gift(Lev)
                                   of
                                   {_, BringVal, _, BringReward} ->
                                       case BaseVal1 >= BringVal of
                                           true ->
                                               mail:send(Role3,
                                                         Title2,
                                                         Content2,
                                                         BringReward),
                                               {Lev + 1, BaseVal1 - BringVal};
                                           _ -> {Lev, BaseVal1}
                                       end;
                                   _ ->
                                       logger:debug("已经到最高等级，不会再变动",
                                                    [],
                                                    camp_bring_up_open,
                                                    210),
                                       {Lev, BaseVal1}
                               end,
            Role4 = var:set_var(Role3,
                                other,
                                2143,
                                {NLev, NBaseVal}),
            push(Role4),
            {ok, Role4};
        _ -> {false, lang:get("配置出错")}
    end;
get_reward(_, _, _, _) -> {false, lang:get("活动已结束")}.

apply_evt(#evt_activity{}, Role) ->
    case get_day() of
        Day when Day > 0 ->
            Val = var:get_var(Role, day, 631, 0),
            case camp_bring_up_open_data:get_gift({Day, 0}) of
                #{need_val := NeedVal} when Val >= NeedVal ->
                    TimesL = var:get_var(Role, other, 2144, []),
                    case lists:keyfind(Day, 1, TimesL) of
                        {Day, Times} ->
                            case lists:keyfind(0, 1, Times) of
                                {0, Num} when Num >= 1 -> ok;
                                _ -> zero_flush(Role, Day)
                            end;
                        _ -> zero_flush(Role, Day)
                    end;
                _ -> ok
            end;
        _ -> ok
    end;
apply_evt(_, _Role) -> ok.

get_camp() ->
    case campaign_mgr:get_camp_info(60058) of
        #camp_cache{id = Id, start_time = St, end_time = ET} ->
            {Id, St, ET};
        _ -> {0, -1, -1}
    end.

get_day() ->
    Now = date:unixtime2(),
    case get_camp() of
        {_Id, ST, ET} when ST =< Now andalso ET >= Now ->
            date:day_diff(ST, Now) + 1;
        _ -> 0
    end.

make_data(Type, Rtn, _) when Type < 0 -> Rtn;
