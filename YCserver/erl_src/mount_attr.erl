calc_appearance_score([], _Classes, TotalScore) ->
    TotalScore;
calc_appearance_score([{AppearanceId, Expire} | Rest],
                      Classes, TotalScore) ->
    Now = date:unixtime(),
    case Expire > Now orelse Expire =:= 0 of
        true ->
            Score = mount_data:get_appearance_score({AppearanceId,
                                                     Classes}),
            CommonScore =
                mount_data:get_appearance_score({AppearanceId, 0}),
            calc_appearance_score(Rest,
                                  Classes,
                                  TotalScore + Score + CommonScore);
        _ -> calc_appearance_score(Rest, Classes, TotalScore)
    end.

