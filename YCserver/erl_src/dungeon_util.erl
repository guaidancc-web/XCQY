            ValList = [{ItemId, 0, ItemNum}],
            GainList = format:val_to_gain(ValList),
            NewCards = [{Loss,
                         lists:keydelete(1, #dungeon_card.selected, [H | T])}
                        | LeftCards],
            Role1 = Role#role{m_dungeon =
                                  Mdun#m_dungeon{cards = NewCards}},
            case role_gain:do_notice(GainList, Role1) of
                {ok, Role2} -> {ok, Role2};
                {false, #gain{reason = bag_full}} ->
                    Title = lang:get("副本结算"),
                    Content = lang:get("副本结算时，背包已满"),
                    mail:send(Role,
                              #{title => Title, content => Content,
                                items => ValList}),
                    {ok, Role1};
                {false, #gain{msg = Msg}} -> {false, Msg}
            end;
        _ -> {false, lang:get("翻牌已领取过")}
    end;
open_card(_) -> {false, lang:get("没有翻牌哦")}.

buy_cards(Role = #role{m_dungeon =
                           Mdun = #m_dungeon{cards =
                                                 [{Loss, Cards}
                                                  | LeftCards]}}) ->
    Cost = format:val_to_loss(Loss),
    G1 = [{Item, 0, Num}
          || #dungeon_card{item_id = Item, item_num = Num}
                 <- Cards],
    Gain = format:val_to_gain(G1),
    Role1 = Role#role{m_dungeon =
                          Mdun#m_dungeon{cards = LeftCards}},
    case role_gain:do_notice(Cost ++ Gain, Role1) of
        {ok, Role2} -> {ok, Role2};
        {false, #gain{reason = bag_full}} ->
            case role_gain:do_notice(Cost, Role1) of
                {ok, Role2} ->
                    Title = lang:get("副本结算"),
                    Content = lang:get("副本结算时，背包已满"),
                    mail:send(Role,
                              #{title => Title, content => Content,
                                items => G1}),
                    {ok, Role2};
                {false, #loss{msg = Msg}} -> {false, Msg}
            end;
        {false, #loss{msg = Msg}} -> {false, Msg};
        {false, #gain{msg = Msg}} -> {false, Msg}
    end;
buy_cards(_) -> {false, lang:get("没有卡牌了")}.

