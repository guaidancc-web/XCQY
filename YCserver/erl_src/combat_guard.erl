convert(#m_guard{guards = Guards}) ->
    [to_c_guard(Guard)
     || Guard = #guard{status = Status} <- Guards,
        Status =/= 2].

convert(#m_guard{guards = Guards}, all) ->
    [to_c_guard(Guard) || Guard = #guard{} <- Guards];
convert(#m_guard{guards = Guards}, SkillList)
    when is_list(SkillList) ->
    [to_c_guard(Guard#guard{skills = Skills ++ SkillList})
     || Guard = #guard{skills = Skills, status = Status}
            <- Guards,
        Status =/= 2].

convert(#m_guard{guards = Guards}, SkillList, all)
    when is_list(SkillList) ->
    [to_c_guard(Guard#guard{skills = Skills ++ SkillList})
     || Guard = #guard{skills = Skills, status = _Status}
            <- Guards];
convert(#m_guard{guards = Guards}, SkillList, fighter)
    when is_list(SkillList) ->
    [to_c_guard(Guard#guard{skills = Skills ++ SkillList})
     || Guard = #guard{skills = Skills, status = Status}
            <- Guards,
        Status =:= 1].

to_c_guard(Guard = #guard{base_id = BaseId, eqm = Eqms,
                          war_id = WarId, alias = Name, classes = Classes,
                          attr = Attr, skills = Skills,
                          astroid = #guard_astroid{skills = ASkills}}) ->
    {_, AddSkills, _} = skill:get_effect_skill(Eqms, []),
    ASkills1 = [{As, 1} || {As, _} <- ASkills],
    DSkills = [Ds || {_, Ds} <- ASkills],
    Skills1 = (Skills ++ AddSkills) -- DSkills,
    NewSkills = ASkills1 ++
                    [{SkillId, 1} || SkillId <- Skills1],
    Looks = guard_api:get_look(Guard),
    #c_guard{base_id = BaseId, war_id = WarId,
             skills = NewSkills, name = Name, classes = Classes,
             attr = Attr, looks = Looks}.

find_team_guard([], _Guards, Team) ->
    lists:reverse(Team);
find_team_guard([GuardBaseId | T], Guards, Team) ->
    case lists:keyfind(GuardBaseId,
                       #c_guard.base_id,
                       Guards)
        of
        CGuard = #c_guard{} ->
            find_team_guard(T, Guards, [CGuard | Team]);
        _ -> find_team_guard(T, Guards, Team)
    end.

update_fighter_guard(F = #fighter{active_guard =
                                      Guards}) ->
    ReadyGuards = [Guard
                   || Guard = #c_guard{war_id = WarId} <- Guards,
                      WarId =/= 0],
    ReadyGuards1 = lists:sublist(ReadyGuards, 4),
    F#fighter{active_guard = ReadyGuards1}.

update_fighter_guard(F = #fighter{active_guard = Guards,
                                  team_guard = TeamGuard},
                     GuardPosList) ->
    Guards1 = find_team_guard(TeamGuard, Guards, []),
    ReadyGuards = find_convert(Guards1, GuardPosList, []),
    ReadyGuards1 = lists:sublist(ReadyGuards, 4),
    F#fighter{active_guard = ReadyGuards1}.

find_convert([], _, Guards) -> Guards;
find_convert(_, [], Guards) -> Guards;
find_convert([Guard = #c_guard{} | T], [Pos | T1],
             Guards) ->
    find_convert(T, T1, [{Guard, Pos} | Guards]).

to_fighter_list(Master, GuardList) ->
    to_fighter_list(Master, GuardList, []).

to_fighter_list(_Master, [], FList) -> FList;
to_fighter_list(Master,
                [Guard = #c_guard{war_id = WarId} | T], FList) ->
    case to_fighter(Master, Guard) of
        F = #fighter{} ->
            to_fighter_list(Master,
                            T,
                            [F#fighter{pos = WarId} | FList]);
        _ -> to_fighter_list(Master, T, FList)
    end;
to_fighter_list(Master, [{Guard, WarId} | T], FList) ->
    case to_fighter(Master, Guard) of
        F = #fighter{} ->
            to_fighter_list(Master,
                            T,
                            [F#fighter{pos = WarId} | FList]);
        _ -> to_fighter_list(Master, T, FList)
    end.

to_fighter(Master = #fighter{m_lev_break = MLevBreak,
                             lev = MasterLev},
           #c_guard{base_id = BaseId, name = Name,
                    classes = Classes, attr = Attr, skills = Skills,
                    looks = Looks}) ->
    NewAttr1 = case attr_ver:do(Attr) of
                   {ok, NewAttr} -> NewAttr;
                   _ -> #attr{}
               end,
    #attr{hp_max = HpMax, mp_max = MpMax} = NewAttr1,
    Minit = #m_combat_init{skills = Skills},
    CombatStat = #combat_statistics{},
    AiId = case guard_data:get_guard_cfg(BaseId) of
               #guard_data{ai_id = Aid} -> Aid;
               _ -> 0
           end,
    MasterLev1 = case MLevBreak of
                     #m_lev_break{} -> lev_break:lev(Master);
                     _ -> MasterLev
                 end,
    #fighter{origin_id = BaseId, base_id = BaseId, type = 5,
             name = Name, attr = NewAttr1, m_init = Minit,
             combat_statistics = CombatStat, classes = Classes,
             hp = HpMax, hp_max = HpMax, mp = MpMax, mp_max = MpMax,
             ai_id = AiId, lev = MasterLev1, looks = Looks};
to_fighter(_, _) -> undefined.

