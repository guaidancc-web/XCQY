                floor => Floor, type => 1}).

do_reward(#{id := RoleId, name := Name, dun_id := DunId,
            floor := Floor, type := Type}) ->
    case dungeon_data:get_reward({DunId, Floor, Type}) of
        #dungeon_reward_data{item_list = ItemList,
                             cast_msg = CastMsg, title = Title, msg = Msg} ->
            {ItemId, Bind, Num, _, IsCast} =
                util:rand_list(ItemList, 4),
            case IsCast of
                1 ->
                    NewCastMsg = notice:replace_msg([{"#role#",
                                                      [{role_2, Name}]},
                                                     {"#item#",
                                                      [{item_2,
                                                        ItemId,
                                                        Bind,
                                                        Num}]}],
                                                    CastMsg),
                    notice:cast(all, 4, NewCastMsg);
                _ -> ignore
            end,
            mail:send(RoleId,
                      #{title => Title, content => Msg,
                        items => [{ItemId, Bind, Num}]});
        _ -> ignore
    end.

