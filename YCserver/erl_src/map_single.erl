-spec distance(#pos{}, #pos{}) -> {ok,
                                   {integer(), integer()}} |
                                  false.

distance(#pos{map_pid = MapPid, x = X1, y = Y1},
         #pos{map_pid = MapPid, x = X2, y = Y2}) ->
    Dx = erlang:abs(util:floor(X1 / 600) -
                        util:floor(X2 / 600)),
    Dy = erlang:abs(util:floor(Y1 / 370) -
                        util:floor(Y2 / 370)),
    {ok, {Dx, Dy}};
distance(_, _) -> false.

