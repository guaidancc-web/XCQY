init([]) ->
    logger:info("[~w] 正在启动...", [ask_mgr], ask_mgr, 135),
    process_flag(trap_exit, true),
    case catch load_data() of
        ok ->
            Pltm = case env:get(platform) of
                       undefined -> "";
                       TmpPltm -> TmpPltm
                   end,
            ZoneId = case env:get(zone_id) of
                         undefined -> 0;
                         TmpZoneId -> TmpZoneId
                     end,
            logger:info("[~w] 启动完成", [ask_mgr], ask_mgr, 141),
            {ok, #ask_state{platform = Pltm, zone_id = ZoneId}};
        {ok, State} ->
            Pltm = case env:get(platform) of
                       undefined -> "";
                       TmpPltm -> TmpPltm
                   end,
