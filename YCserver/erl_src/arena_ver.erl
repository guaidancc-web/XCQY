convert(ArenaRole = #arena_role{ver = 6}) ->
    {ok, ArenaRole};
convert(_ArenaRole) ->
    logger:debug("ArenaRole:~w",
                 [_ArenaRole],
                 arena_ver,
                 66),
    {false, lang:get("角色竞技场数据转换失败")}.

do({m_arena, CdTime, AccNum, Cup}) ->
    Ver = 1,
    RollTime = 0,
    RollGraph = [],
    RollId = 0,
    do({m_arena,
        Ver,
        CdTime,
        AccNum,
        Cup,
        RollTime,
        RollId,
        RollGraph});
do(Marena = #m_arena{}) -> {ok, Marena};
do(_Err) ->
    logger:error("竞技场版本错误:~w", [_Err], arena_ver, 79),
    {false, "竞技场版本转换失败"}.

convert_rank_list(RankList) ->
    convert_rank_list(RankList, []).

convert_rank_list([], RankList) ->
    lists:reverse(RankList);
convert_rank_list([ArenaRole | T], RankList) ->
    case arena_ver:convert(ArenaRole) of
        {false, Reason} ->
            logger:error("竞技场数据转换失败:~w", [Reason], arena_ver, 89),
            convert_rank_list(T, RankList);
        {ok, NewArenaRole = #arena_role{}} ->
            convert_rank_list(T, [NewArenaRole | RankList])
    end.

