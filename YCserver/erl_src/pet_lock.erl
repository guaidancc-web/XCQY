lock(PetId,
     Role = #role{m_pet = MPet = #m_pet{pets = Pets}}) ->
    case lists:keyfind(PetId, #pet.id, Pets) of
        Pet = #pet{lock = 0} ->
            NewPet = Pet#pet{lock = 1},
            NewPets = lists:keystore(PetId, #pet.id, Pets, NewPet),
            NewMPet = MPet#m_pet{pets = NewPets},
            NewRole = Role#role{m_pet = NewMPet},
            {ok, NewRole};
        #pet{lock = 1} -> {false, lang:get("宠物已被锁定")};
        _ -> {false, lang:get("未找到要锁定的宠物")}
    end.

unlock(PetId,
       Role = #role{m_pet = MPet = #m_pet{pets = Pets}}) ->
    case lists:keyfind(PetId, #pet.id, Pets) of
        Pet = #pet{lock = 1} ->
            NewPet = Pet#pet{lock = 0},
            NewPets = lists:keystore(PetId, #pet.id, Pets, NewPet),
            NewMPet = MPet#m_pet{pets = NewPets},
            NewRole = Role#role{m_pet = NewMPet},
            {ok, NewRole};
        #pet{lock = 0} -> {false, lang:get("宠物已被解锁")};
        _ -> {false, lang:get("未找到要解锁的宠物")}
    end.

