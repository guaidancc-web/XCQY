login(#role{id = RoleId,
            m_wedding =
                MWedding = #m_wedding{status = 3, mail = MailList}} =
          Role) ->
    case wedding:lover(RoleId) of
        {ok, #lover{time = Time}} ->
            case wedding_data:list_memorial_day() of
                List when is_list(List) ->
                    Day = date:day_diff(Time, date:unixtime()),
                    AchieveRole = role_trigger:fire(#evt_wedding_day{day =
                                                                         Day},
                                                    Role),
                    {DaysAll, MailDays} = reward_day(Day, Time, MailList),
                    mail_send(Role, MailDays),
                    {ok,
                     AchieveRole#role{m_wedding =
                                          MWedding#m_wedding{mail = DaysAll}}};
                _ -> ok
            end;
        _ -> ok
    end;
