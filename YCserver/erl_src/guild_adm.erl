info() ->
    case guild_mgr:list() of
        {ok, L} ->
            {ok,
             [{struct,
               [{guild_id, Gid},
                {platform, unicode:characters_to_binary(P)},
                {zone_id, Z},
                {guild_name, unicode:characters_to_binary(Name)},
                {guild_lev, Lev},
                {leader_rid, Lrid},
                {leader_platform, unicode:characters_to_binary(Lp)},
                {leader_zone_id, Lz},
                {leader_name, unicode:characters_to_binary(Lname)},
                {members_num, Num},
                {assets, Assets},
                {board, unicode:characters_to_binary(Board)},
                {create_time, Time}]}
              || #guild{id = {Gid, P, Z}, lev = Lev,
                        leader_id = {Lrid, Lp, Lz}, leader_name = Lname,
                        create_time = Time, mem_num = Num, name = Name,
                        assets = Assets, board = Board}
                     <- L]};
        _ -> {ok, []}
    end.

mem(Gid, P, Z) ->
    case guild_mgr:info(by_id, {Gid, P, Z}) of
        {ok, #guild{members = Members}} ->
            {ok,
             [{struct,
               [{rid, Rid},
                {platform, Rp},
                {zone_id, Rz},
                {lev, Lev},
                {name, Name},
                {signature, Signature}]}
              || #guild_role{id = {Rid, Rp, Rz}, name = Name,
                             lev = Lev, signature = Signature}
                     <- Members]};
        _ -> {ok, []}
    end.

clean(Gid, P, Z) ->
    guild:apply(async,
                {Gid, P, Z},
                {guild_adm, async_clean_signature, []}),
    ok.

async_clean_signature(State = #guild{members =
                                         Members}) ->
    NewMembers = do_clean_signature(Members, Members, []),
    NewState = State#guild{members = NewMembers, flag = 1},
    guild:sync_cache(NewState),
    {ok, NewState}.

do_clean_signature(_, [], Members) -> Members;
do_clean_signature(OldMem,
                   [R = #guild_role{pid = Pid} | T], Members) ->
    NewR = R#guild_role{signature = <<"">>},
    case is_pid(Pid) of
        true ->
            role:apply(async,
                       Pid,
                       {guild_role, set, [{signature, <<"">>}]});
        false -> skip
    end,
    guild:cast(OldMem, 10904, NewR),
    do_clean_signature(OldMem, T, [NewR | Members]).

