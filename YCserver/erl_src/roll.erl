dungeon_roll(DunId, RoleList) ->
    case roll_data:get({1, DunId}) of
        {#{timeout := TimeOut}, ItemList} ->
            RollRoles = [to_roll_role(Role) || Role <- RoleList],
            case length(RollRoles) >= 3 of
                true ->
                    roll_mgr:add_roll({1, DunId},
                                      TimeOut,
                                      ItemList,
                                      RollRoles,
                                      {roll_role, 41});
                false -> ok
            end;
        _ ->
            logger:error("副本roll点无法找到roll点数据:~w",
                         [DunId],
                         roll,
                         39),
            ok
    end.

