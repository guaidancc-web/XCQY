convert(MCampRecharge = #m_camp_recharge{recharges =
                                             Recharges}) ->
    case do_convert(Recharges, []) of
        {ok, NewRecharges} ->
            {ok,
             MCampRecharge#m_camp_recharge{recharges =
                                               NewRecharges}};
        {false, Reason} -> {false, Reason}
    end;
convert(_) -> {false, lang:get("充值转盘活动转换数据出错")}.

do_convert([], List) -> {ok, lists:reverse(List)};
do_convert([I | T], List) ->
    case do(I) of
        {ok, Recharge} -> do_convert(T, [Recharge | List]);
        {false, Reason} -> {false, Reason}
    end.

