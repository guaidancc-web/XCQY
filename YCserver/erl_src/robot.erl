         Robot = #robot_role{attr =
                                 #attr{hp_max = HpMax, phy_dmg = PhyDmg,
                                       magic_dmg = MagicDmg} =
                                     Attr}} ->
            NewHpMax = round(HpMax * Ratio / 1000),
            NewPhyDmg = round(PhyDmg * Ratio / 1000),
            NewMagicDmg = round(MagicDmg * Ratio / 1000),
            NewAttr = Attr#attr{hp_max = NewHpMax,
                                phy_dmg = NewPhyDmg, magic_dmg = NewMagicDmg},
            Robot2 = Robot#robot_role{id = {Rid, "robot", 0},
                                      attr = NewAttr},
            {true, Robot3} = make_robot(robot_role,
                                        Condition,
                                        Robot2),
            {true, Robot3};
        _Else -> {false, lang:get("无法获取对应角色属性数据")}
    end;
make_robot(robot_role, Condition,
           Robot = #robot_role{pet = Pet, guard = Guards}) ->
    Ratio = case Condition of
                #{attr_ratio := RatioT} -> RatioT;
                _ -> 100
            end,
    Robot2 = case Pet of
                 #c_pet{attr =
                            #attr{hp_max = PetHpMax, phy_dmg = PetPhyDmg,
                                  magic_dmg = PetMagicDmg} =
                                PetAttr} ->
                     PetHpMax2 = round(PetHpMax * Ratio / 1000),
                     PetPhyDmg2 = round(PetPhyDmg * Ratio / 1000),
                     PetMagicDmg2 = round(PetMagicDmg * Ratio / 1000),
                     PetAttr2 = PetAttr#attr{hp_max = PetHpMax2,
                                             phy_dmg = PetPhyDmg2,
                                             magic_dmg = PetMagicDmg2},
                     Robot#robot_role{pet = Pet#c_pet{attr = PetAttr2}};
                 _ -> Robot
             end,
    Guards2 = lists:foldl(fun (#c_guard{attr =
                                            #attr{hp_max = GHpMax,
                                                  phy_dmg = GPhyDmg,
                                                  magic_dmg = GMagicDmg} =
                                                GAttr} =
                                   G,
                               Acc) ->
                                  GHpMax2 = round(GHpMax * Ratio / 1000),
                                  GPhyDmg2 = round(GPhyDmg * Ratio / 1000),
                                  GMagicDmg2 = round(GMagicDmg * Ratio / 1000),
                                  GAttr2 = GAttr#attr{hp_max = GHpMax2,
                                                      phy_dmg = GPhyDmg2,
                                                      magic_dmg = GMagicDmg2},
                                  [G#c_guard{attr = GAttr2} | Acc];
                              (G, Acc) -> [G | Acc]
                          end,
                          [],
                          Guards),
    {true, Robot2#robot_role{guard = Guards2}};
make_robot(_, _, _) -> {false, lang:get("未知类型, 无法产生")}.

make_robot_pet(Lev,
               Robot = #robot_role{pet = Pet = #c_pet{},
                                   classes = Classes}) ->
    case robot_data:get({Lev, Classes}) of
        #{attr := Attr = #attr{}} ->
            Robot#robot_role{pet = Pet#c_pet{attr = Attr}};
        _ -> Robot
    end;
make_robot_pet(_Lev, Robot) -> Robot.

make_robot_guard(Lev,
                 Robot = #robot_role{guard = Guards,
                                     classes = Classes}) ->
    case robot_data:get({Lev, Classes}) of
        #{attr := Attr = #attr{}} ->
            Robot#robot_role{guard =
                                 [G#c_guard{attr = Attr} || G <- Guards]};
        _ -> Robot
    end.

