handle(18800, _, Role) ->
    maze:push(Role),
    ok;
handle(18801, {X, Y}, Role)
    when X =< 5 andalso Y =< 5 ->
    case maze:dig(Role, {X, Y}) of
        {ok, NewRole} ->
            maze:push(NewRole),
            {ok, NewRole};
        {false, Reason} -> {reply, {0, Reason}}
    end;
handle(18803, {}, Role) -> maze:reward_dragon(Role);
handle(18804, {X, Y, Id}, Role = #role{p_bag = PBag})
    when X =< 5 andalso Y =< 5 ->
    case package:find(by_id, Id, PBag) of
        {ok, #item{base_id = BaseId}} ->
            case maze:change(Role, {X, Y}, BaseId) of
                {ok, NewRole} ->
                    maze:push(NewRole),
                    {ok, NewRole};
                {false, Reason} -> {reply, {0, Reason}}
            end;
        _ -> {false, lang:get("找不到道具")}
    end;
handle(18805, {X, Y, VerifyId}, Role)
    when X =< 5 andalso Y =< 5 ->
    case maze:grab(Role, {X, Y}, VerifyId) of
        {ok, NewRole, NewVerifyId} ->
            logger:debug("抓妖 ~w", [VerifyId], maze_rpc, 54),
            logger:debug("抓妖 ~w", [NewVerifyId], maze_rpc, 55),
            maze:push(NewRole),
            {reply, {1, "", NewVerifyId}, NewRole};
        {false, Reason, NewVerifyId} ->
            {reply, {0, Reason, NewVerifyId}};
        {false, Reason} -> {reply, {0, Reason, 0}}
    end;
handle(18806, {X, Y}, Role) ->
    case maze:combat_start(Role, {X, Y}) of
        ok -> {reply, {1, lang:get("向怪物发起攻击")}};
        {false, Reason} -> {reply, {0, Reason}}
    end;
handle(18807, {X, Y}, Role)
    when X > 0 andalso
             X =< 5 andalso Y > 0 andalso Y =< 5 ->
    case maze:get(Role, {X, Y}) of
        {ok, NewRole} -> {ok, NewRole};
        {false, Reason} -> {reply, {0, Reason}}
    end;
handle(18808, {}, Role) ->
    case maze:get_final(Role) of
        {ok, NewRole, List} -> {reply, {1, "", List}, NewRole};
        {false, Reason} -> {reply, {0, Reason, []}}
    end;
handle(18809, {}, Role) ->
    case maze:apperceive(Role) of
        {ok, NewRole, Msg} -> {reply, {1, Msg}, NewRole};
        {false, Reason} -> {reply, {0, Reason}}
    end;
handle(18810, {}, Role) ->
    case maze:double(Role) of
        {ok, NewRole} ->
            {reply,
             {1, lang:get("开启双倍奖励，下个道具奖励将翻倍{face_1, 31}")},
             NewRole};
        {false, Reason} -> {reply, {0, Reason}}
    end;
handle(18811, {}, Role) ->
    case maze:reset(Role) of
        {ok, NewRole} -> {ok, NewRole};
        ok -> {reply, {0, lang:get("未领取最终奖励,不能重置")}}
    end;
handle(18813, {}, Role) -> maze:apply_point(Role);
handle(18814, {X, Y}, Role) ->
    case maze:reward_event(Role, {X, Y}) of
        {ok, Msg, NewRole} -> {reply, {1, Msg}, NewRole};
        {false, Reason} -> {reply, {0, Reason}}
    end;
handle(18815, {X, Y}, Role) ->
    {Exp, PetExp} = maze:monster_reward(Role, {X, Y}),
    logger:debug("经验值 ~w", [{Exp, PetExp}], maze_rpc, 134),
    {reply, {Exp, PetExp, X, Y}};
handle(18816, {X, Y}, Role) ->
    case maze:clean_monster(Role, {X, Y}) of
        {ok, NewRole} -> {reply, {1, "", X, Y}, NewRole};
        {false, Reason} -> {reply, {0, Reason, X, Y}}
    end;
handle(_Cmd, _Data, _Role) ->
    logger:debug("模块[~w]收到无效的RPC调用[~w]: ~w",
                 [maze_rpc, _Cmd, _Data],
                 maze_rpc,
                 148),
    {error, unknow_command}.

