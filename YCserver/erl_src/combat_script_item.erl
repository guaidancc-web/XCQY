to_combat_item(#item{id = ItemId, type = 118,
                     base_id = ItemBaseId, step = Step},
               _CombatType) ->
    case skill_life_data:get_combat({ItemBaseId, Step}) of
        Maps = #{skill_id := SkillId, skill_lev := SkillLev,
                 anti_heal := AntiHeal, can_effect := CanEffect} ->
            Args = maps:get(args, Maps, []),
            case combat_script_skill:to_combat_skill({SkillId,
                                                      SkillLev})
                of
                #c_skill{skill =
                             #skill{target_type = TargetType,
                                    script_id = ScriptId, buff_self = BuffSelf,
                                    buff_target = BuffTarget},
                         action = Action} ->
                    #c_item{item_id = ItemId, base_id = ItemBaseId,
                            step = Step, target_type = TargetType,
                            skill_id = SkillId, skill_lev = SkillLev,
                            script_id = ScriptId, script_args = Args,
                            buff_self = BuffSelf, buff_target = BuffTarget,
                            action = Action, anti_heal = AntiHeal,
                            can_effect = CanEffect};
                _Err -> {false, lang:get("无法使用的战斗道具")}
            end;
        _ -> {false, lang:get("无法使用的战斗道具")}
    end;
to_combat_item(#item{id = ItemId, type = 134,
                     base_id = ItemBaseId, step = Step},
               CombatType) ->
    case skill_life_data:get_combat({ItemBaseId, Step}) of
        Maps = #{skill_id := SkillId, skill_lev := SkillLev,
                 anti_heal := AntiHeal, can_effect := CanEffect} ->
            case 6 =:= CombatType orelse
                     115 =:= CombatType orelse
                         40 =:= CombatType orelse 58 =:= CombatType
                of
                true ->
                    Args = maps:get(args, Maps, []),
                    case combat_script_skill:to_combat_skill({SkillId,
                                                              SkillLev})
                        of
                        #c_skill{skill =
                                     #skill{target_type = TargetType,
                                            script_id = ScriptId,
                                            buff_self = BuffSelf,
                                            buff_target = BuffTarget},
                                 action = Action} ->
                            #c_item{item_id = ItemId, base_id = ItemBaseId,
                                    step = Step, target_type = TargetType,
                                    skill_id = SkillId, skill_lev = SkillLev,
                                    script_id = ScriptId, script_args = Args,
                                    buff_self = BuffSelf,
                                    buff_target = BuffTarget, action = Action,
                                    anti_heal = AntiHeal,
                                    can_effect = CanEffect};
                        _Err -> {false, lang:get("无法使用的战斗道具")}
                    end;
                false -> {false, lang:get("该药品只能在切磋时使用")}
            end;
