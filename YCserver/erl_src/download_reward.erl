push(Role = #role{link = Link}) ->
    DwTimes = var:get_var(Role, acc, 1012, 0),
    GuideTimes = var:get_var(Role, acc, 1024, 0),
    Data = [{1, DwTimes}, {2, GuideTimes}],
    logger:debug("9929返回信息:~w",
                 [Data],
                 download_reward,
                 24),
    role:link_send(Link, 9929, {Data}),
    ok.

rpc_get_download_reward(Role, 1) ->
    RwTimes = var:get_var(Role, acc, 1012, 0),
    case RwTimes > 0 of
        true -> {false, lang:get("您已经领取过游戏下载奖励，请不要重复领取")};
        false ->
            VarRole = var:set_var(Role, acc, 1012, RwTimes + 1),
            case download_reward_data:get_download_reward() of
                [] -> {false, lang:get("当前无法领取游戏下载奖励，请留意稍后官方通知")};
                Gain ->
                    Gl = format:val_to_gain(Gain),
                    case role_gain:do_notice(Gl, VarRole) of
                        {ok, NewRole} ->
                            push(NewRole),
                            {ok, NewRole};
                        {false, #gain{msg = Msg}} -> {false, Msg};
                        _Err ->
                            logger:error("领取下载游戏奖励错误:~w",
                                         [_Err],
                                         download_reward,
                                         45)
                    end
            end
    end;
