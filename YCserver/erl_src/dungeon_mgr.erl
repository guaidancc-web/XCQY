    {noreply,
     State#state{dungeons = [{BattleId, Pid} | Duns]}};
handle_cast({stop, BattleId, _Pid},
            State = #state{dungeons = Duns, off_list = OffList}) ->
    NewDuns = lists:keydelete(BattleId, 1, Duns),
    NewOffList = [R
                  || R = {_, _, Bid, _} <- OffList, Bid =/= BattleId],
    {noreply,
     State#state{dungeons = NewDuns, off_list = NewOffList}};
handle_cast({in_rank,
             #{battle_pid := BattlePid, record := Record,
               record_id := RecordId},
             RoleList,
             Cfg = #dungeon_lord_data{id = DunId, floor = Floor}},
            State) ->
    Platform = env:get(platform),
    ZoneId = env:get(zone_id),
    combat_record:save(11, RecordId, Record),
    case ets:lookup(dungeon_lord, {DunId, Floor}) of
        [DunLord = #dungeon_lord{ranks = Ranks,
                                 lords = OldLords}] ->
            List = rank_role(Ranks, RoleList, []),
            List2 = util:keys_sort([#dungeon_rank_role.lev,
                                    #dungeon_rank_role.val2,
                                    {asc, #dungeon_rank_role.val1}],
                                   List),
            NewRanks = rank(List2, 1, []),
            Lords = case NewRanks of
                        [R = #dungeon_rank_role{id = Id, name = Name, sex = Sex,
                                                classes = Classes, lev = Lev,
                                                looks = Looks}
                         | _] ->
                            cast_lord(R, Cfg),
                            combat_record:save(10,
                                               {DunId * 1000 + Floor * 10,
                                                Platform,
                                                ZoneId},
                                               Record),
                            [#dungeon_lord_role{id = Id, name = Name, sex = Sex,
                                                classes = Classes, lev = Lev,
                                                looks = Looks}];
                        _ -> OldLords
                    end,
            ets:insert(dungeon_lord,
                       DunLord#dungeon_lord{lords = Lords, ranks = NewRanks}),
            dets:insert(dungeon_lord,
                        DunLord#dungeon_lord{lords = Lords, ranks = NewRanks}),
            battle_mgr:apply(async,
                             BattlePid,
                             {dungeon_mgr, update_statue, [DunId, Floor]});
        _ ->
            List2 = util:keys_sort([#dungeon_rank_role.lev,
                                    #dungeon_rank_role.val2,
                                    {asc, #dungeon_rank_role.val1}],
                                   RoleList),
            NewRanks = rank(List2, 1, []),
            Lords = case NewRanks of
                        [R = #dungeon_rank_role{id = Id, name = Name, sex = Sex,
                                                classes = Classes, lev = Lev,
                                                looks = Looks}
                         | _] ->
                            cast_lord(R, Cfg),
                            combat_record:save(10,
                                               {DunId * 1000 + Floor * 10,
                                                Platform,
                                                ZoneId},
                                               Record),
                            [#dungeon_lord_role{id = Id, name = Name, sex = Sex,
                                                classes = Classes, lev = Lev,
                                                looks = Looks}];
                        _ -> []
                    end,
            Data = #dungeon_lord{key = {DunId, Floor},
                                 dun_id = DunId, floor = Floor, lords = Lords,
                                 ranks = NewRanks},
            ets:insert(dungeon_lord, Data),
            dets:insert(dungeon_lord, Data),
            battle_mgr:apply(async,
                             BattlePid,
                             {dungeon_mgr, update_statue, [DunId, Floor]})
    end,
    {noreply, State};
