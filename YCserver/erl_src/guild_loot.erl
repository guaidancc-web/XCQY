add(Gid, Items) -> add(Gid, Items, "").

add(Gid, Items, Msg) ->
    guild_mgr:apply(async,
                    Gid,
                    {guild_loot, apply_guild, [{add, Items, Msg}]}).

gm(Gid, clear) ->
    guild_mgr:apply(async,
                    Gid,
                    {guild_loot, apply_guild, [gm_clear]}).

allocate(_, []) -> {false, lang:get("请指定一个要分配的成员")};
allocate(#role{m_guild =
                   #m_guild{post = Post, pid = Pid},
               id = Id, link = #link{conn_pid = ConnPid}},
         Alloc)
    when Post > 50 ->
    case guild_mgr:apply(sync,
                         Pid,
                         {guild_loot,
                          apply_guild,
                          [{allocate, #{id => Id, l => Alloc}}]})
        of
        {ok, Loot = #guild_loot{}} ->
            sys_conn:pack_send(ConnPid, 11180, {Loot}),
            ok;
        Else -> Else
    end;
allocate(_, _) -> {false, lang:get("只有公会会长可以分配")}.

reset(G = #guild{loot =
                     Loot = #guild_loot{allocated = Allocated}}) ->
    Now = date:unixtime(),
    Allocated1 = [O
                  || O = {_, _, Time} <- Allocated,
                     date:is_same_week(Now, Time)],
    G#guild{loot = Loot#guild_loot{allocated = Allocated1}}.

apply_guild(G = #guild{members = Members},
            {add, AddItems, Pref}) ->
    G1 = #guild{loot = Loot = #guild_loot{items = Items}} =
             reset(G),
    NewItems = do_add_items(AddItems, Items),
    Msg = notice:format(lang:get("~ts公会宝库增加了~ts"),
                        [{string_1, Pref}, {item_2, AddItems}]),
    guild:notice(Members, Msg),
    {ok,
     G1#guild{loot = Loot#guild_loot{items = NewItems}}};
apply_guild(G = #guild{loot = Loot}, gm_clear) ->
    {ok, G#guild{loot = Loot#guild_loot{allocated = []}}};
apply_guild(G, {allocate, Alloc}) ->
    Res = case check_allocate(Alloc, G) of
              {ok, G1 = #guild{}} -> batch_allocate(Alloc, G1);
              Else -> Else
          end,
    case Res of
        {ok, NewG = #guild{loot = NewLoot}} ->
            {ok, {ok, NewLoot}, NewG};
        _ -> {ok, Res}
    end;
apply_guild(#guild{}, _Act) ->
    logger:error("未知消息 ~w", [_Act], guild_loot, 84),
    ok.

do_add_items([], Items) -> Items;
do_add_items([{BaseId, Num} | T], Items) ->
    case lists:keyfind(BaseId, 1, Items) of
        {_, N} ->
            case get_num_limit(BaseId) of
                0 ->
                    do_add_items(T,
                                 lists:keyreplace(BaseId,
                                                  1,
                                                  Items,
                                                  {BaseId, Num + N}));
                Max ->
                    do_add_items(T,
                                 lists:keyreplace(BaseId,
                                                  1,
                                                  Items,
                                                  {BaseId, min(Max, Num + N)}))
            end;
        _ -> do_add_items(T, [{BaseId, Num} | Items])
    end.

do_allocate(G = #guild{members = Members},
            #{base_id := BaseId, num := Num, target_id := TargetId,
              name := Name}) ->
    Title = item:attr(name, BaseId),
    MailInfo = #{items => [{BaseId, 0, Num}],
                 title => Title,
                 content =>
                     notice:format(lang:get("你对公会的贡献有目共睹，会长特此授予你~ts！希望你尽心竭力，帮助公会日益强盛！"),
                                   [{item_2, BaseId, Num}])},
    mail:send(TargetId, MailInfo),
    Msg =
        notice:format(lang:get("公会壮大~ts功不可没，会长决定授予其~ts！{face_1, 18}"),
                      [{role_2, Name}, {item_2, BaseId, Num}]),
    guild:notice(Members, Msg),
    {ok, G}.

batch_allocate(#{l := []}, G) -> {ok, G};
batch_allocate(Alloc = #{l :=
                             [{R, P, Z, BaseId, Num} | T]},
               G = #guild{members = Members}) ->
    TargetId = {R, P, Z},
    case lists:keyfind(TargetId, #guild_role.id, Members) of
        #guild_role{name = Name} ->
            case do_allocate(G,
                             #{name => Name, base_id => BaseId, num => Num,
                               target_id => TargetId})
                of
                {ok, NewG = #guild{}} ->
                    batch_allocate(Alloc#{l := T}, NewG);
                Else -> Else
            end;
        _ -> {false, lang:get("请分配奖励给本公会的成员哦")}
    end.

check_allocate(#{l := []}, G) -> {ok, G};
check_allocate(Alloc = #{l :=
                             [{R, P, Z, BaseId, Num} | T]},
               G = #guild{loot =
                              Loot = #guild_loot{allocated = Allocated,
                                                 items = Items, log = Log},
                          members = Members, leader_name = LeaderName}) ->
    TargetId = {R, P, Z},
    case lists:keyfind(TargetId, #guild_role.id, Members) of
        #guild_role{name = Name, enter_time = Entered} ->
            Now = date:unixtime(),
            Allocated1 = [O
                          || O = {_, _, Time} <- Allocated,
                             date:is_same_week(Now, Time)],
            case lists:keyfind({TargetId, BaseId}, 1, Allocated1) of
                _ when Now - Entered < 86400 * 3 ->
                    {false,
                     notice:format(lang:get("~ts的入会时间还没满三天"),
                                   [{role_2, Name}])};
                {_, N, _} when N >= 1 ->
                    {false,
                     notice:format(lang:get("~ts本周分配额度已用完"),
                                   [{role_2, Name}])};
                {_, N, _} when N + Num >= 1 ->
                    {false,
                     notice:format(lang:get("~ts本周已经分配~ts个了"),
                                   [{role_2, Name}, {string_2, 5, 1}])};
                RA ->
                    case lists:keyfind(BaseId, 1, Items) of
                        {_, N} when N >= Num ->
                            Items1 = case N =:= Num of
                                         true ->
                                             lists:keydelete(BaseId, 1, Items);
                                         _ ->
                                             lists:keyreplace(BaseId,
                                                              1,
                                                              Items,
                                                              {BaseId, N - Num})
                                     end,
                            Allocated2 = case RA of
                                             {_, RN, _} ->
                                                 lists:keyreplace({TargetId,
                                                                   BaseId},
                                                                  1,
                                                                  Allocated1,
                                                                  {{TargetId,
                                                                    BaseId},
                                                                   RN + Num,
                                                                   Now});
                                             _ ->
                                                 [{{TargetId, BaseId}, Num, Now}
                                                  | Allocated1]
                                         end,
                            LogMsg = notice:format(lang:get("~ts分配了~ts给~ts"),
                                                   [{role_2, LeaderName},
                                                    {item_2, BaseId, Num},
                                                    {role_2, Name}]),
                            Log1 = lists:sublist([{LogMsg, BaseId, Now} | Log],
                                                 20),
                            NewG = G#guild{loot =
                                               Loot#guild_loot{allocated =
                                                                   Allocated2,
                                                               items = Items1,
                                                               log = Log1}},
                            check_allocate(Alloc#{l := T}, NewG);
                        _ -> {false, lang:get("奖品数量不足")}
                    end
            end;
        _ -> {false, lang:get("请分配奖励给本公会的成员哦")}
    end.

