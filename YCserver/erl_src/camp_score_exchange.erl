accept_quest_list(Role = #role{m_quest =
                                   #m_quest{quest_score_exchange =
                                                #quest_score_exchange{doing =
                                                                          CurDoing,
                                                                      finish =
                                                                          CurFinish}}},
                  QuestList, Flag) ->
    logger:debug("~w", [Flag], camp_score_exchange, 321),
    {Role1, AcceptQuestList} = case Flag of
                                   true ->
                                       {ok, Role2} = remove_all_quest(Role),
                                       {Role2, QuestList};
                                   config ->
                                       {ok, Role3} = remove_config_quest(Role),
                                       {Role3, QuestList};
                                   _ ->
                                       {Role,
                                        QuestList -- CurDoing ++ CurFinish}
                               end,
    logger:debug("~w",
                 [AcceptQuestList],
                 camp_score_exchange,
                 340),
    Fun = fun (QuestId, RtnRole) ->
                  case quest:callback_accept(RtnRole,
                                             QuestId,
                                             [condition, accept, fire])
                      of
                      {ok,
                       AcceptRole = #role{m_quest =
                                              MQuest =
                                                  #m_quest{quest_score_exchange
                                                               =
                                                               QuestScoreExchange =
                                                                   #quest_score_exchange{doing
                                                                                             =
                                                                                             Doing}}}} ->
                          logger:debug("~w",
                                       [QuestId],
                                       camp_score_exchange,
                                       344),
                          NewDoing = [QuestId | Doing],
                          NewQuestScoreExchange =
                              QuestScoreExchange#quest_score_exchange{doing =
                                                                          NewDoing},
                          NewMQuest = MQuest#m_quest{quest_score_exchange =
                                                         NewQuestScoreExchange},
                          AcceptRole#role{m_quest = NewMQuest};
                      _Err ->
                          logger:error("接受任务失败：~w 原因:~w",
                                       [QuestId, _Err],
                                       camp_score_exchange,
                                       350),
                          Role
                  end
          end,
    NewRole = lists:foldl(Fun, Role1, AcceptQuestList),
    MQ = NewRole#role.m_quest,
    QSE = MQ#m_quest.quest_score_exchange,
    DoingList = QSE#quest_score_exchange.doing,
    {TriRef, AutoRole} = role_trigger:add(#trigger{label =
                                                       evt_finish_quest,
                                                   m = camp_score_exchange,
                                                   f = auto_commit,
                                                   a = [DoingList]},
                                          NewRole),
    TimeRole = role_timer:add(#timer{id =
                                         camp_score_exchange,
                                     timeout =
                                         date:now_diff(today, {23, 59, 59}) *
                                             1000,
                                     m = camp_score_exchange, f = remove_timer,
                                     a = [TriRef], times = 1},
                              AutoRole),
    {ok, TimeRole}.

remove_all_quest(Role = #role{m_quest =
                                  MQuest = #m_quest{quest = Quests}}) ->
    Fun = fun (#quest{sec_type = SecType}) ->
                  SecType =/= 34;
              (_) -> false
          end,
    LeftQuests = lists:filter(Fun, Quests),
    NewRole = Role#role{m_quest =
                            MQuest#m_quest{quest = LeftQuests,
                                           quest_score_exchange =
                                               #quest_score_exchange{}}},
    {ok, NewRole}.

remove_config_quest(Role = #role{m_quest =
                                     MQuest = #m_quest{quest = Quests,
                                                       quest_score_exchange =
                                                           #quest_score_exchange{doing
                                                                                     =
                                                                                     CurDoing,
                                                                                 finish
                                                                                     =
                                                                                     CurFinish}}}) ->
    Fun1 = fun (#quest{id = Id, sec_type = 34}) ->
                   case camp_score_exchange_data:get_quest_info(Id) of
                       {Id, _, _, _, 1} -> false;
                       _ -> true
                   end;
               (_) -> true
           end,
    LeftQuests = lists:filter(Fun1, Quests),
    Fun2 = fun (Id) ->
                   case camp_score_exchange_data:get_quest_info(Id) of
                       {Id, _, _, _, 1} -> false;
                       _ -> true
                   end
           end,
    LeftDoing = lists:filter(Fun2, CurDoing),
    LeftFinish = lists:filter(Fun2, CurFinish),
    NewRole = Role#role{m_quest =
                            MQuest#m_quest{quest = LeftQuests,
                                           quest_score_exchange =
                                               #quest_score_exchange{doing =
                                                                         LeftDoing,
                                                                     finish =
                                                                         LeftFinish}}},
    {ok, NewRole}.

get_quest_list_info([], _MQuest, ResQuestInfo) ->
    ResQuestInfo;
get_quest_list_info([QuestId | T],
                    MQuest = #m_quest{quest = Quest}, QuestInfo) ->
    {QuestId, QuestRewards, Icon, Sort, _} =
        camp_score_exchange_data:get_quest_info(QuestId),
    NewQuestInfo = case lists:keyfind(QuestId,
                                      #quest.id,
                                      Quest)
                       of
                       #quest{progress = Progress} ->
                           [#quest_progress{target_val = TargetVal,
                                            value = Value}] =
                               Progress,
                           QuestStatus = case TargetVal =:= Value of
                                             true -> 1;
                                             _ -> 0
                                         end,
                           QuestInfo1 = {QuestId,
                                         QuestRewards,
                                         Icon,
                                         Value,
                                         TargetVal,
                                         QuestStatus,
                                         Sort},
                           [QuestInfo1 | QuestInfo];
                       _ ->
                           case quest_data:get(QuestId) of
                               #quest_data{progress =
                                               [#quest_progress{target_val =
                                                                    TargetVal1}]} ->
                                   QuestInfo2 = {QuestId,
                                                 QuestRewards,
                                                 Icon,
                                                 0,
                                                 TargetVal1,
                                                 0,
                                                 Sort},
                                   [QuestInfo2 | QuestInfo];
                               _ ->
                                   logger:error("任务信息出错~w",
                                                [QuestId],
                                                camp_score_exchange,
                                                415),
                                   QuestInfo
                           end
                   end,
    get_quest_list_info(T, MQuest, NewQuestInfo).

check_is_open() ->
    Now = date:unixtime(),
    case campaign_mgr:get_camp_time(60053) of
        {StartTime, EndTime}
            when StartTime =< Now andalso Now =< EndTime ->
            true;
        _ -> false
    end.

get_day() ->
    Now = date:unixtime2(),
    case campaign_mgr:get_camp_info(60053) of
        #camp_cache{id = Id, start_time = St, end_time = ET}
            when St =< Now andalso Now =< ET ->
            {Id, date:day_diff(St, Now) + 1};
        _ -> {0, 0}
    end.

