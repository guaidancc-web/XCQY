get_all(#role{id = Rid0} = Role) ->
    AuctionList = auction_mgr:auction_list(),
    FocusList = auction_mgr:focus_list_get(Rid0),
    Fun = fun (#auction{idx = Idx, item_id = ItemId,
                        item_count = ItemCount, role_id = RoldId, gold = Gold,
                        gold_once = GoldOnce, time_auction = Time,
                        state = State},
               Acc) ->
                  GoldMy = case RoldId of
                               Rid0 -> Gold;
                               _ -> 0
                           end,
                  Focus = case lists:member(Idx, FocusList) of
                              true -> 1;
                              _ -> 0
                          end,
                  [{Idx,
                    ItemId,
                    ItemCount,
                    Gold,
                    GoldMy,
                    GoldOnce,
                    Time,
                    Focus,
                    State}
                   | Acc]
          end,
    AuctionList1 = lists:foldl(Fun, [], AuctionList),
    auction_mgr:join_cast(Role),
    AuctionList1.

get_time() ->
    TimeList = case catch auction_mgr:time_list() of
                   List when is_list(List) -> List;
                   _ -> []
               end,
    [Times
     || {_, {Time1, _Time2} = Times} <- TimeList,
        Time1 =/= 0].

get_focus(Role) -> auction_mgr:focus_get(Role#role.id).

auction(#role{id = Id, name = RoleName} = Role, Idx,
        GoldAdd, Gold) ->
    case auction_mgr:auction_get(Idx) of
        #auction{role_id = RoldId, gold = GoldNow}
            when GoldNow =:= Gold ->
            Gold2 = case RoldId of
                        Id -> GoldAdd;
                        _ -> Gold + GoldAdd
                    end,
            Loss = format:val_to_loss([{90002, Gold2}]),
            case role_gain:do_notice(Loss, Role) of
                {ok, Role1} ->
                    case auction_mgr:call({add_gold,
                                           Role,
                                           RoldId,
                                           Idx,
                                           GoldAdd,
                                           Gold})
                        of
                        {ok, _Data} -> {ok, Role1};
                        {error, timeout} ->
                            logger:error("拍卖竞拍超时啦!!!!~w~n",
                                         [{Id, RoleName, Idx, GoldAdd, Gold}],
                                         auction,
                                         69),
                            {ok, Role1};
                        {false, Msg} -> {false, Msg};
                        Error ->
                            logger:error("拍卖竞拍未知错误!!!!~w~n",
                                         [Error],
                                         auction,
                                         74),
                            {false, lang:get("不可竞拍")}
                    end;
                {false, #loss{msg = Msg}} -> {false, Msg}
            end;
        _R ->
            logger:debug("============~w~n",
                         [{Idx, _R}],
                         auction,
                         81),
            {false, "该物品不存在"}
    end.

