                                           Role),
    do_list_sub_type(Type, [SelfFriendRole | FriendRoles]).

-spec get_one_info(Type :: pos_integer(),
                   RoleId :: tuple(), atom()) -> false | tuple().

get_one_info(Type, RoleId, Label) ->
    L = list_show(Type),
    do_get_one_info(Type,
                    Label,
                    lists:keyfind(RoleId, 3, L)).

do_get_one_info(_Type, role, RankRc = #rank_rc{}) ->
    {ok, RankRc};
do_get_one_info(_Type, pet, #rank_rc{pet = Pet}) ->
    {ok, Pet};
do_get_one_info(_Type, eqm,
                #rank_rc{eqm = Eqm = #item{}}) ->
    {ok, Eqm};
do_get_one_info(_Type, guard,
                #rank_rc{name = Name, guard = Guard}) ->
    {ok, Guard, Name};
do_get_one_info(_Type, _Label, _Rc) -> false.

