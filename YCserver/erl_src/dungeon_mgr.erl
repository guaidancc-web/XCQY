call_login(RoleId) ->
    case catch gen_server:call(dungeon_mgr,
                               {role_login, RoleId},
                               10000)
        of
        {'EXIT', {timeout, _}} -> {error, timeout};
        {'EXIT', {noproc, _}} -> {error, noproc};
        {'EXIT', {normal, _}} -> {error, exit};
        {'EXIT', _Call_Err} -> {error, _Call_Err};
        _Call_Return -> _Call_Return
    end.

combat_over(_Role, _, _Loser, _Args) -> ok.

combat_over(#combat{winner = Winner, loser = Loser,
                    start_time = StartTime}) ->
    WinnerFighter = [I || I = #fighter{type = 1} <- Winner],
    case [1
          || #fighter{type = 1, origin_id = RoleId} <- Winner,
             not role_misc:is_local_role(RoleId)]
        of
        [] ->
            case [#dungeon_first_role{id = RoleId, name = Name,
                                      sex = Sex, classes = Classes}
                  || #fighter{type = 1, origin_id = RoleId, name = Name,
                              sex = Sex, classes = Classes}
                         <- Winner]
                of
                [] -> [];
                WinL ->
                    case lists:keyfind(1, #fighter.is_leader, Loser) of
                        #fighter{type = 2, base_id = BaseId} ->
                            case dungeon_data:get_lord(BaseId) of
                                #dungeon_lord_data{is_lord = 0} -> ignore;
                                Cfg = #dungeon_lord_data{id = DunId,
                                                         floor = Floor} ->
                                    Record = combat_record:get_buffer(),
                                    dungeon_mgr !
                                        {first_killer,
                                         #{killer => WinL, dun_id => DunId,
                                           floor => Floor, record => Record}},
                                    Now = date:unixtime(),
                                    CombatTime = max(1, Now - StartTime),
                                    RecordId =
                                        {env:update_counter(combat_record_id,
                                                            1),
                                         env:get(platform),
                                         env:get(zone_id)},
                                    RankRoleList = to_rank_role(Winner,
                                                                CombatTime,
                                                                RecordId,
                                                                []),
                                    case WinnerFighter of
                                        [#fighter{s_event_pid = BattlePid}
                                         | _] ->
                                            gen_server:cast(dungeon_mgr,
                                                            {in_rank,
                                                             #{battle_pid =>
                                                                   BattlePid,
                                                               record => Record,
                                                               record_id =>
                                                                   RecordId},
                                                             RankRoleList,
                                                             Cfg});
                                        _ -> ignore
                                    end;
                                _ -> ignore
                            end;
                        _ -> ignore
                    end
            end;
        _ -> ignore
    end;
combat_over(_) -> ok.

