    end.

get_honor_ids(#role{sex = Sex,
                    m_honor = #m_honor{r_list = List}}) ->
    logger:debug("称号列表~w~n", [List], wedding_memory, 310),
    Ids = wedding_data:list_cash_honor(),
    Fun = fun (Id, Acc) ->
                  HonorId = case wedding_data:get_cash_honor(Id) of
                                #{male_id := MaleId, female_id := FemaleId} ->
                                    case Sex of
                                        1 -> MaleId;
                                        _ -> FemaleId
                                    end;
                                _ -> 0
                            end,
                  case lists:keyfind(HonorId, #honor.id, List) of
                      false -> Acc;
                      _ -> [HonorId | Acc]
                  end
          end,
    lists:foldl(Fun, [], Ids).

