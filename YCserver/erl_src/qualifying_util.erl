                false ->
                    Msg =
                        notice:format(lang:get("段位赛最多与~ts组队参与{face_1, 36}"),
                                      [{string_2, 5, lang:get("1名队友")}]),
                    {false, Msg}
            end;
        _ -> {false, lang:get("队伍无法找到队长")}
    end.

check_classes([#team_mate{classes = C},
               #team_mate{classes = C},
               #team_mate{classes = C}],
              1) ->
    {false, lang:get("三个相同职业无法报名3v3比赛")};
check_classes(_, _) -> true.

team_convert([], _QualifyingType, QualifyingRoles,
             RolePids) ->
    {true, QualifyingRoles, RolePids};
team_convert([#team_mate{pid = Pid, status = Status}
              | T],
             QualifyingType, QualifyingRoles, RolePids)
    when is_pid(Pid) andalso
             (Status =:= 1 orelse Status =:= 2) ->
    case role:apply(sync,
                    Pid,
                    {qualifying_util, convert_role, [QualifyingType]})
        of
        {ok, QualifyingRole, RoleId, RolePid} ->
            NewQualifyingRoles = [QualifyingRole | QualifyingRoles],
            NewRolePids = [{RoleId, RolePid} | RolePids],
            team_convert(T,
                         QualifyingType,
                         NewQualifyingRoles,
                         NewRolePids);
        {false, Reason} -> {false, Reason};
        _ -> {false, lang:get("队员正在忙碌中，无法报名")}
    end;
team_convert([#team_mate{name = Name} | _T],
             _QualifyingType, _QualyfyingRoles, _RolePids) ->
    {false,
     util:flist(lang:get("~ts没有归队，无法报名段位赛"), [Name])};
team_convert([_ | _T], _QualifyingType,
             _QualyfyingRoles, _RolePids) ->
    {false, lang:get("无法获取队员状态")}.

convert_role(Role = #role{id = RoleId, pid = RolePid,
                          name = Name, s_event = 5},
             QualifyingType) ->
    Reply = case qualifying_mgr:get_count(Role,
                                          QualifyingType)
                of
                Num when is_integer(Num) andalso Num < 8 ->
                    case role_convert:to(qualifying_role, Role) of
                        {ok, QualifyingRole} ->
                            {ok,
                             QualifyingRole#qualifying_role{times = Num},
                             RoleId,
                             RolePid};
                        _ ->
                            {false,
                             util:flist(lang:get("~ts无法转换, 报名失败"), [Name])}
                    end;
                _ ->
                    {false, util:flist(lang:get("~ts次数不足, 报名失败"), [Name])}
            end,
    {ok, Reply};
convert_role(#role{name = Name}, _QualifyingType) ->
    {ok,
     {false, util:flist(lang:get("~ts不在准备区，无法报名"), [Name])}}.

