has_item(#role{p_bag = #package{items = Items}}, ItemId,
         CombatType) ->
    Reply = case lists:keyfind(ItemId, #item.id, Items) of
                Item = #item{type = 118, quantity = Quantity}
                    when Quantity > 0 ->
                    case to_combat_item(Item, CombatType) of
                        Citem = #c_item{} -> {true, Citem};
                        {false, Reason} -> {false, Reason}
                    end;
                Item = #item{type = 134, quantity = Quantity}
                    when Quantity > 0 ->
                    case to_combat_item(Item, CombatType) of
                        Citem = #c_item{} -> {true, Citem};
                        {false, Reason} -> {false, Reason}
                    end;
                _ -> {false, lang:get("只有战斗道具才能使用")}
            end,
    {ok, Reply}.

loss_item(Role = #role{p_bag = #package{items = Items}},
          Citem = #c_item{item_id = ItemId, base_id = ItemBaseId,
                          step = Step}) ->
    case lists:keyfind(ItemId, #item.id, Items) of
        #item{base_id = ItemBaseId, step = Step, type = 118} ->
            Loss = [#loss{label = item_id, val = [{ItemId, 1}]}],
            case role_gain:do(Loss, Role) of
                {false, _} -> {ok, {false, lang:get("道具数量为0，无法使用")}};
                {ok, NewRole} -> {ok, {true, Citem}, NewRole}
            end;
        #item{base_id = ItemBaseId, step = Step, type = 134} ->
            Loss = [#loss{label = item_id, val = [{ItemId, 1}]}],
            case role_gain:do(Loss, Role) of
                {false, _} -> {ok, {false, lang:get("道具数量为0，无法使用")}};
                {ok, NewRole} -> {ok, {true, Citem}, NewRole}
            end;
        _ -> {ok, {false, lang:get("道具数量为0，无法使用")}}
    end.

