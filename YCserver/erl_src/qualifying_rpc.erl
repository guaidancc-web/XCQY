handle(13500, _, #role{lev = Lev}) when Lev < 40 ->
    {reply, {0, lang:get("你的实力不够，抓紧提升，40级再来找我吧！")}};
handle(13500, {QualifyingType},
       Role = #role{s_event = 5, status = 0}) ->
    case qualifying_util:sign_up(QualifyingType, Role) of
        {false, Reason} -> {reply, {0, Reason}};
        _ -> ok
    end;
handle(13500, _, #role{status = 2}) ->
    {reply, {0, lang:get("战斗中无法发起匹配")}};
handle(13500, _, _) ->
    {reply, {0, lang:get("请先进入段位赛准备区再来匹配")}};
handle(13501, {},
       #role{id = RoleId, m_qualifying = Mqua}) ->
    case Mqua of
        #m_qualifying{sign_type = 1} ->
            qualifying_mgr:cancel_match(1, [RoleId]);
        _ -> skip
    end,
    ok;
handle(13502, {}, #role{pid = Pid}) ->
    qualifying_mgr:get_status(Pid),
    ok;
handle(13504, {Rid, P, Z}, #role{}) ->
    case role_misc:check_cd(13501) of
        false -> ok;
        true ->
            case role_misc:is_local_role({Rid, P, Z}) of
                true ->
                    QualifyingMark = qualifying_mgr:get_mark({Rid, P, Z}),
                    {reply, QualifyingMark};
                _ -> ok
            end
    end;
handle(13508, {Type, Idx, Num}, Role)
    when Idx >= 1 andalso
             Num >= 1 andalso (Type =:= 1 orelse Type =:= 2) ->
    qualifying_rank:get_rank(Role, Type, Idx, Num),
    ok;
handle(13509, {}, #role{pid = RolePid}) ->
    case role_misc:check_cd(13509) of
        false -> ok;
        true ->
            qualifying_mgr:query_news(RolePid),
            ok
    end;
handle(13510, {Rid, P, Z},
       #role{id = RoleId, pid = RolePid}) ->
    Tid = {Rid, P, Z},
    case get(qualifying_team_mate) of
        MateList = [_ | _] ->
            case lists:member(Tid, MateList) of
                true ->
                    NewMateList = MateList -- [Tid],
                    put(qualifying_team_mate, NewMateList),
                    qualifying_mgr:thumb_up(RoleId, RolePid, Tid);
                false -> skip
            end;
        _ -> skip
    end,
    ok;
handle(13511, {}, Role) ->
    qualifying_util:push_13511(Role),
    ok;
handle(13512, _, #role{lev = Lev}) when Lev < 40 ->
    {reply, {0, lang:get("你的实力不够，抓紧提升，40级再来找我吧！")}};
handle(13512, {}, Role = #role{cross_type = 0}) ->
    case role_misc:check_event(Role) of
        {false, Reason} -> {reply, {0, Reason}};
        true ->
            case qualifying_zone:enter(Role) of
                {false, Reason} -> {reply, {0, Reason}};
                ok -> ok
            end
    end;
handle(13512, _, #role{}) ->
    {reply, {0, lang:get("跨服下不支持参与该活动")}};
handle(13513, {}, Role = #role{s_event = 5}) ->
    case qualifying_zone:exit(Role) of
        {false, Reason} -> {reply, {0, Reason}};
        {ok, NewRole} -> {ok, NewRole};
        ok -> ok
    end;
handle(13513, {}, _) ->
    {reply, {0, lang:get("当前不在准备区, 无需退出")}};
handle(13514, {Flag}, Role)
    when Flag =:= 1 orelse Flag =:= 2 ->
    case qualifying_util:get_day_reward(Flag, Role) of
        {false, Reason} -> {reply, {0, Reason}};
        {ok, Msg, NewRole} ->
            qualifying_util:push_13511(NewRole),
            {reply, {1, Msg}, NewRole}
    end;
handle(_Cmd, _Data, _Role) ->
