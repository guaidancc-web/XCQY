-record(state, {group_id = 0, map_id = 0, map_pid = 0}).

start_link(GroupId) ->
    gen_server:start_link({local,
                           list_to_atom(lists:concat([canyon_summit_zone,
                                                      "_",
                                                      GroupId]))},
                          canyon_summit_zone,
                          [GroupId],
                          []).

cast(ZonePid, Info) when is_pid(ZonePid) ->
    gen_server:cast(ZonePid, Info);
cast(_, Info) ->
    logger:error("错误的请求:~w",
                 [Info],
                 canyon_summit_zone,
                 56),
    ok.

call(ZonePid, Info) when is_pid(ZonePid) ->
    gen_server:call(ZonePid, Info);
call(_, Info) ->
    logger:error("错误的请求:~w",
                 [Info],
                 canyon_summit_zone,
                 62),
    ok.

init([GroupId]) ->
    process_flag(trap_exit, true),
    logger:info("[~w] 正在启动...",
                [canyon_summit_zone],
                canyon_summit_zone,
                71),
    case map_mgr:create(52002) of
        {error, Err} ->
            logger:error("启动峡谷之巅准备区失败:~w:~w",
                         [GroupId, Err],
                         canyon_summit_zone,
                         74),
            {stop, normal};
        {ok, MapPid, MapId} ->
            State = #state{group_id = GroupId, map_id = MapId,
                           map_pid = MapPid},
            erlang:send_after(180 * 1000, self(), gain_exp),
            unit_mgr:create({60, GroupId * 1000},
                            32040,
                            {MapId, 2045, 1512}),
            logger:info("[~w] 启动完成...",
                        [canyon_summit_zone],
                        canyon_summit_zone,
                        80),
            {ok, State}
    end.

handle_call(quest_map_id, _From,
            State = #state{map_id = MapId}) ->
    {reply, MapId, State};
handle_call({enter, _EnterNum}, _From,
            State = #state{map_id = MapId}) ->
    Platform = env:get(platform),
    ZoneId = env:get(zone_id),
    {reply, {Platform, ZoneId, MapId, self()}, State};
handle_call(_Request, _From, State) ->
    {reply, {false, lang:get("未知请求")}, State}.

handle_cast(enroll_team,
            State = #state{map_pid = MapPId}) ->
    case get(canyon_zone_notice) of
        OldRef when is_reference(OldRef) ->
            erlang:cancel_timer(OldRef);
        _ -> ok
    end,
    map:async_apply(MapPId,
                    {canyon_summit_role, role_callback, [enroll_team]}),
    {noreply, State};
handle_cast(notice_team,
            State = #state{map_id = MapId}) ->
    notice:cast({map, MapId},
                11,
                lang:get("队伍人数3人以上才可参与峡谷之巅，人数越多越有优势，请务必集结队友{face_1,7}")),
    notice:cast({map, MapId},
                5,
                lang:get("队伍人数3人以上才可参与峡谷之巅，人数越多越有优势，请务必集结队友{face_1,7}")),
    Ref = erlang:send_after(60 * 1000, self(), notice_team),
    put(canyon_zone_notice, Ref),
    {noreply, State};
handle_cast(notice_not_ready,
            State = #state{map_pid = MapPId}) ->
    logger:debug("===========",
                 [],
                 canyon_summit_zone,
                 120),
    map:async_apply(MapPId,
                    {canyon_summit_role,
                     role_callback,
                     [notice_not_ready]}),
    {noreply, State};
handle_cast(close, #state{map_pid = MapPId}) ->
    map:async_apply(MapPId,
                    {canyon_summit_role, role_callback, [apply_exit]}),
    {stop,
     normal,
     #state{group_id = 0, map_id = 0, map_pid = 0}};
handle_cast(role_less, #state{map_pid = MapPId}) ->
    map:async_apply(MapPId,
                    {canyon_summit_role, role_callback, [notice_exit]}),
    {stop,
     normal,
     #state{group_id = 0, map_id = 0, map_pid = 0}};
handle_cast(_Msg, State) -> {noreply, State}.

