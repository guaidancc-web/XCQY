handle_cast({del_ask_question, AskId, StartTime},
            State = #ask_state{platform = Pltm,
                               zone_id = ZoneId}) ->
    {ok, NewState} = case lookup_ask_question(AskId) of
                         {ok, #ask_question{start_time = StartTime}} ->
                             delete(ask_tab, AskId),
                             FreeState = case AskId of
                                             {Pltm, ZoneId, Id} ->
                                                 {ok, NState} = free_id(State,
                                                                        Id),
                                                 sync_state(NState),
                                                 NState;
                                             _ -> State
                                         end,
                             {ok, FreeState};
                         _ -> {ok, State}
                     end,
    {noreply, NewState};
handle_cast(Msg, State) ->
    logger:info("[~w]接收到未知的消息[~w]",
                [ask_mgr, Msg],
                ask_mgr,
                197),
