init() -> #m_achievement{}.

-spec login(#role{}) -> {ok, #role{}}.

login(Role) ->
    Role1 = #role{m_achievement =
                      MAchi = #m_achievement{doing = Quests, focus = Focus}} =
                overdue(Role),
    Quests1 = quest_revise:do_list(Role1,
                                   achievement,
                                   Quests),
    {NewQuests,
     NRole = #role{m_achievement =
                       #m_achievement{finish = FinL}}} =
        quest:load_quest(Quests1, [], achievement, Role1),
    NewFocus = check_focus(Focus, []),
    NewRole = flush(NRole#role{m_achievement =
                                   MAchi#m_achievement{doing = NewQuests,
                                                       focus = NewFocus,
                                                       finish = FinL}},
                    not_push),
    {ok, NewRole}.

-spec calc(Ac :: #attr_calc{},
           Role :: #role{}) -> NewAc :: #attr_calc{}.

calc(Ac,
     #role{m_achievement = #m_achievement{finish = FinL}}) ->
    do_calc(FinL, Ac).

do_calc([], Ac) -> Ac;
do_calc([{Id, _} | T], Ac) ->
    case achievement_data:get_attr(Id) of
        AttrL = [_ | _] ->
            NewAttrL = attr_type:to_attr(fixed, AttrL),
            case attr_type:do_attr(NewAttrL, Ac) of
                {false, Reason} ->
                    logger:error("成就属性计算出错[~w]:[~w]",
                                 [Id, Reason],
                                 achievement,
                                 81),
                    do_calc(T, Ac);
                {ok, NewAc} -> do_calc(T, NewAc)
            end;
        _ -> do_calc(T, Ac)
    end.

-spec flush(#role{}, push | not_push) -> #role{}.

flush(Role, Push) ->
    NRole = calc_can_do(achievement_data:list(),
                        Role,
                        Push),
    NRole.

-spec open_next(#role{},
                PreId :: non_neg_integer() |
                         [non_neg_integer()]) -> #role{}.

open_next(Role, PreId) ->
    calc_can_do(achievement_data:pre_quest(PreId),
                Role,
                push).

-spec levup(#evt_levup{}, #role{}) -> #role{}.

levup(#evt_levup{old_lev = OldLev, lev = Lev}, Role) ->
    do_levup(OldLev, Lev, Role).

do_levup(OldLev, Lev, Role) when Lev >= OldLev ->
    NRole = calc_can_do(achievement_data:lev(OldLev),
                        Role,
                        push),
    do_levup(OldLev + 1, Lev, NRole);
do_levup(_OldLev, _Lev, Role) -> Role.

-spec zero_flush(#role{}, #role{}) -> #role{}.

zero_flush(Role, _) ->
    NRole = overdue(Role),
    {ok, NRole}.

-spec reward(#role{}, [pos_integer()]) -> {ok,
                                           #role{}} |
                                          {false, bitstring()}.

reward(Role, Ids) -> reward(Role, Ids, []).

reward(Role, [], DelIds) ->
    NRole = open_next(Role, DelIds),
    {ok, attr:calc_and_push(NRole)};
reward(Role, [{Id} | T], DelIds) ->
    case do_reward(Role, Id) of
        {ok, NRole} -> reward(NRole, T, [Id | DelIds]);
        {false, Reason} when DelIds =:= [] -> {false, Reason};
        _ -> reward(Role, T, DelIds)
    end.

-spec push(#role{}, integer()) -> ok.

push(#role{m_achievement =
               #m_achievement{doing = DoL, finish = FinL,
                              overdue = OverL}},
     Cmd = 10219) ->
    L = DoL ++
            [#quest{id = Id, finish = 2, finish_time = T}
             || {Id, T} <- FinL]
                ++ [#quest{id = Id1, finish = 3} || Id1 <- OverL],
    sys_conn:pack_send(Cmd, {L}),
    ok;
push(#role{m_achievement =
               #m_achievement{point = Num, assets_point = AssetsNum}},
     Cmd = 10222) ->
    logger:debug("推送成就点数:~w, 成就积分:~w",
                 [Num, AssetsNum],
                 achievement,
                 140),
    sys_conn:pack_send(Cmd, {Num, AssetsNum}),
    ok.

