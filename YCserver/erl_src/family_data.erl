get_furnishing_map_grid(GridId, Dir) ->
    case get_furnishing_map_grid(GridId) of
        #{gird_type := GT, gird_list_1 := GL1,
          gird_list_2 := GL2, gird_list_3 := GL3,
          gird_list_4 := GL4}
            when GT =:= 0 ->
            case Dir of
                1 -> GL1;
                3 -> GL2;
                5 -> GL3;
                7 -> GL4;
                _ -> []
            end;
        _ -> []
    end.

get_max_build_lev(HouseLev, BdgType) ->
    case get_family(HouseLev) of
        #{bedroom := MaxBedRoom, petroom := MaxPetRoom,
          productroom := MaxProductRoom,
          warehouse := MaxWareHouse} ->
            case BdgType of
                2 -> MaxPetRoom;
                1 -> MaxBedRoom;
                3 -> MaxProductRoom;
                4 -> MaxWareHouse;
                _ -> false
            end;
        false -> false
    end.

