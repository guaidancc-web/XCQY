skill_name(#child_talent_skill{id = SkillId}) ->
    skill_name(SkillId);
skill_name(SkillId) ->
    case skill_data:get_child_talent({SkillId, 1}) of
        #{name := SkillName} -> SkillName;
        _ -> lang:get("未知技能")
    end.

recalc_talent_skill(Child = #child{grade = Grade,
                                   talent_skills = TalentSkills}) ->
    case Grade >= 0 of
        true ->
            case lists:keyfind(Grade,
                               #child_talent_skill.grade,
                               TalentSkills)
                of
                false ->
                    TalentSkill = #child_talent_skill{grade = Grade},
                    NewTalentSkills = [TalentSkill | TalentSkills],
                    Child#child{talent_skills = NewTalentSkills};
                _ -> Child
            end;
        _ -> Child
    end.

combat_add_talent(Role, CombatType, ChildList) ->
    case check_talent_combat_type(CombatType) of
        true -> do_combat_add_talent(Role, ChildList);
        false -> Role
    end.

do_combat_add_talent(Role, []) -> Role;
do_combat_add_talent(Role,
                     [#fighter{origin_id = ChildId} | T]) ->
    case child_util:find_child(Role, ChildId, [3]) of
        {true, #child{talent_skills = TalentSkills}} ->
            logger:debug("孩子天赋技能:~w",
                         [TalentSkills],
                         child_talent,
                         66),
            RandTalentSkills = lists:filter(fun
                                                (#child_talent_skill{id = Id,
                                                                     lev = Lev,
                                                                     exp =
                                                                         Exp}) ->
                                                    case
                                                        skill_data:get_child_talent({Id,
                                                                                     Lev})
                                                        of
                                                        #{max_lev := Lev} ->
                                                            false;
                                                        #{max_exp := Exp} ->
                                                            false;
                                                        _ -> true
                                                    end
                                            end,
                                            TalentSkills),
            logger:debug("孩子天赋技能:~w",
