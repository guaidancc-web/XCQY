                 _Score},
                Rtn) ->
                   Fun2 = fun (#mount_decorate{decorate_base_id =
                                                   DecorateId},
                               DecorateRtn) ->
                                  case mount_data:get_decorate(DecorateId) of
                                      #{appearance := AppearanceId} ->
                                          [AppearanceId | DecorateRtn];
                                      _ -> DecorateRtn
                                  end
                          end,
                   AppList = lists:foldl(Fun2, [], DecorateList),
                   AppList ++ Rtn;
               (_, Rtn) -> Rtn
           end,
    DecorateAppList = lists:foldl(Fun1, [], Mounts),
    NewAppearanceList = lists:foldl(fun (AppId, AppRtn) ->
                                            case lists:member(AppId, AppRtn) of
                                                true -> AppRtn;
                                                false -> [AppId | AppRtn]
                                            end
                                    end,
                                    AppearanceList,
                                    DecorateAppList),
    do({m_mount,
        NewVer,
        Mounts,
        MountGoal,
        NextMountId,
        RideMount,
        NewAppearanceList,
        CombatActiveTimes});
