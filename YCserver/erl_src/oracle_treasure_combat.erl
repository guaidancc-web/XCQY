next_wave(#combat{type = Type,
                  start_args = #combat_start_args{}}) ->
    Wave = get(oracle_treasure_wave),
    NextWave = Wave + 1,
    put(oracle_treasure_wave, NextWave),
    case oracle_treasure_data:get_wave_info(NextWave) of
        #{unit_id := UnitBaseId}
            when is_integer(UnitBaseId) andalso UnitBaseId > 0 ->
            UnitBaseIds = case unit_data:get(UnitBaseId) of
                              #unit_data{slave = Slave} ->
                                  Slaves = gen_slave(Slave, []),
                                  logger:debug("随从列表:~w",
                                               [Slaves],
                                               oracle_treasure_combat,
                                               47),
                                  [{unit_baseid, UnitBaseId} | Slaves];
                              _ -> [{unit_baseid, UnitBaseId}]
                          end,
            combat:add_next_wave(Type, UnitBaseIds, 1),
            true;
        _ ->
            logger:error("查找不到下一批怪:type:~w",
                         [NextWave],
                         oracle_treasure_combat,
                         56),
            false
    end.

