init() -> #camp_sign{}.

push(#role{m_campaign =
               #m_campaign{camp_sign =
                               #camp_sign{camp_id = OldCampId, date = Date,
                                          num = Num}}}) ->
    Now = date:unixtime(),
    {Today, _} = date:seconds_to_datetime(Now),
    case get_camp() of
        {OldCampId, St, ET} when Now >= St andalso Now =< ET ->
            case Date of
                Today -> sys_conn:pack_send(17843, {1, Num});
                _ -> sys_conn:pack_send(17843, {0, Num})
            end;
        {_CampId, St, ET} when Now >= St andalso Now =< ET ->
            sys_conn:pack_send(17843, {0, 0});
        _ -> sys_conn:pack_send(17843, {0, 0})
    end,
    ok;
push(_) -> ok.

reward(Role = #role{m_campaign =
                        #m_campaign{camp_sign =
                                        OldCampSign = #camp_sign{camp_id =
                                                                     OldCampId}}}) ->
    Now = date:unixtime(),
    {Today, _} = date:seconds_to_datetime(Now),
    CampInfo = {_, St, ET} = get_camp(),
    Result = case CampInfo of
                 {OldCampId, St, ET} when Now >= St andalso Now =< ET ->
                     {ok, OldCampSign};
                 {CampId, St, ET} when Now >= St andalso Now =< ET ->
                     {ok, #camp_sign{camp_id = CampId}};
                 _ -> {false, lang:get("不在活动期间")}
             end,
    case Result of
        {ok, CampSign = #camp_sign{date = Date, num = Num}} ->
            case Today of
                Date ->
                    NewNum = Num + 1,
                    case camp_sign_data:get(NewNum) of
                        #camp_sign_data{cost = []} ->
                            {false, lang:get("今天的奖励已经领取，明天再来{face_1,1}")};
                        Cfg = #camp_sign_data{cost = Cost} ->
                            DayDiff = date:day_diff(Now, St) + 1,
                            case NewNum =< DayDiff of
                                true ->
                                    case do_reward(Role, NewNum, Cost, Cfg) of
                                        {ok,
                                         NRole = #role{m_campaign =
                                                           MCamp =
                                                               #m_campaign{}}} ->
                                            NewCampSign = CampSign#camp_sign{num
                                                                                 =
                                                                                 NewNum},
                                            NewMCamp =
                                                MCamp#m_campaign{camp_sign =
                                                                     NewCampSign},
                                            NewRole = NRole#role{m_campaign =
                                                                     NewMCamp},
                                            push(NewRole),
                                            {ok, NewRole};
                                        Else -> Else
                                    end;
                                _ -> {false, lang:get("时间还没有到，不用心急")}
                            end;
                        _ -> {false, lang:get("签到奖励已领取完毕")}
                    end;
                _ ->
                    NewNum = Num + 1,
                    case camp_sign_data:get(NewNum) of
                        Cfg = #camp_sign_data{} ->
                            case do_reward(Role, NewNum, [], Cfg) of
                                {ok,
                                 NRole = #role{m_campaign =
                                                   MCamp = #m_campaign{}}} ->
                                    NewCampSign = CampSign#camp_sign{num =
                                                                         NewNum,
                                                                     date =
                                                                         Today},
                                    NewMCamp = MCamp#m_campaign{camp_sign =
                                                                    NewCampSign},
                                    NewRole = NRole#role{m_campaign = NewMCamp},
                                    push(NewRole),
                                    {ok, NewRole};
                                Else -> Else
                            end;
                        _ -> {false, lang:get("签到奖励已领取完毕")}
                    end
            end;
        {false, Reason} -> {false, Reason}
    end.

do_reward(Role = #role{lev = _Lev, sex = Sex}, _Day,
          Loss, #camp_sign_data{item_list = Reward}) ->
    NewReward = [{ItemId, Bind, INum}
                 || {ItemId, Bind, INum, ISex} <- Reward,
                    ISex == Sex orelse ISex == 2],
    Gain = format:val_to_gain(NewReward) ++
               format:val_to_loss(Loss),
    case role_gain:do_notice(Gain, Role, lang:get("签到")) of
        {ok, NewRole} -> {ok, NewRole};
        {false, #loss{}} -> {false, lang:get("材料不足")};
        {false, _} -> {false, lang:get("背包空间不足")}
    end.

get_camp() ->
    case campaign_mgr:get_camp_info(60016) of
        #camp_cache{id = Id, start_time = St, end_time = ET} ->
            {Id, St, ET};
        _ -> {0, -1, -1}
    end.

