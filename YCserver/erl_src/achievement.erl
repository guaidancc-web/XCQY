                                Id,
                                {#achievement_log.accept, 1}),
            ets:update_counter(achievement_log,
                               Id,
                               {#achievement_log.accept, 1});
        _ -> achievement ! {accept, Id}
    end.

count_finish(RoleId, Id) ->
    case ets:lookup(achievement_log, Id) of
        [#achievement_log{finish = Num}] ->
