match(trial,
      {Role = #role{id = RoleId},
       LevList,
       FcList,
       HasMatch}) ->
    RoleFc = attr:get_war_fc(Role),
    FcList1 = [{round(RoleFc * (1000 + MinFc) / 1000),
                round(RoleFc * (1000 + MaxFc) / 1000)}
               || {MinFc, MaxFc} <- FcList],
    do_match_trial(LevList, FcList1, RoleId, HasMatch, []).

do_match_trial([], [], _RoleId, _HasMatch, []) -> false;
do_match_trial([], [], RoleId, HasMatch, BackList) ->
    case BackList of
        [List1 | _] ->
            List2 = [R
                     || R = #robot_role_index{id = RobotId} <- List1,
                        lists:member(RobotId, [RoleId | HasMatch]) =:= false],
            case List2 of
                [_ | _] ->
                    case util:rand_list(List2) of
                        #robot_role_index{id = GetRoleId} -> {true, GetRoleId};
                        _ -> false
                    end;
                _ -> false
            end;
        _ -> false
    end;
do_match_trial([], [_], RoleId, HasMatch, BackList) ->
    do_match_trial([], [], RoleId, HasMatch, BackList);
do_match_trial([], [_ | T2], RoleId, HasMatch,
               BackList) ->
    do_match_trial(BackList, T2, RoleId, HasMatch, []);
do_match_trial([RoleList = [_ | _] | T1],
               [{MinFc, MaxFc} | T2], RoleId, HasMatch, BackList) ->
    BackRoleList = [Robot
                    || Robot = #robot_role_index{id = RobotId,
                                                 all_fc = AllFc}
                           <- RoleList,
                       AllFc >= MinFc andalso
                           AllFc =< MaxFc andalso
                               lists:member(RobotId, [RoleId | HasMatch]) =:=
                                   false],
    case BackRoleList of
        [_ | _] ->
            case util:rand_list(BackRoleList) of
                #robot_role_index{id = GetRoleId} -> {true, GetRoleId};
                _ -> false
            end;
        _ ->
            do_match_trial(T1,
                           [{MinFc, MaxFc} | T2],
                           RoleId,
                           HasMatch,
                           [RoleList | BackList])
    end;
do_match_trial([Lev | T1], [{MinFc, MaxFc} | T2],
               RoleId, HasMatch, BackList)
    when is_integer(Lev) ->
    case robot_mgr:get_role_index(by_lev, Lev) of
        RoleList = [_ | _] ->
            BackRoleList = [Robot
                            || Robot = #robot_role_index{id = RobotId,
                                                         all_fc = AllFc}
                                   <- RoleList,
                               AllFc >= MinFc andalso
                                   AllFc =< MaxFc andalso
                                       lists:member(RobotId,
                                                    [RoleId | HasMatch])
                                           =:= false],
            case BackRoleList of
                [_ | _] ->
                    case util:rand_list(BackRoleList) of
                        #robot_role_index{id = GetRoleId} -> {true, GetRoleId};
                        _ -> false
                    end;
                _ ->
                    do_match_trial(T1,
                                   [{MinFc, MaxFc} | T2],
                                   RoleId,
                                   HasMatch,
                                   [RoleList | BackList])
            end;
        _ ->
            do_match_trial(T1,
                           [{MinFc, MaxFc} | T2],
                           RoleId,
                           HasMatch,
                           BackList)
    end;
do_match_trial([_ | T1], [{MinFc, MaxFc} | T2], RoleId,
               HasMatch, BackList) ->
    do_match_trial(T1,
                   [{MinFc, MaxFc} | T2],
                   RoleId,
                   HasMatch,
                   BackList).

