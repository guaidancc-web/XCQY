-spec list(Type :: pos_integer()) -> RankList :: list().

list(Type) ->
    #rank{list = L} = rank_mgr:lookup(Type),
    L.

list_show(Type) ->
    #rank{show_list = L} = rank_mgr:lookup(Type),
    L.

list(Role, Type, Page, Num, SubType)
    when Num > 0 andalso Num =< 100 ->
    L1 = case SubType =:= 2 of
             true -> list_sub_type(Role, Type);
             false ->
                 #rank{show_list = ShowL} = rank_mgr:lookup(Type),
                 ShowL
         end,
    NewL = set_rank(L1),
    NewLen = length(NewL),
    PageTotal = util:ceil(NewLen / Num),
    {Flag, NowPage} = if Page < 1 orelse PageTotal =:= 0 ->
                             {false, 1};
                         Page > PageTotal -> {false, PageTotal};
                         true -> {true, Page}
                      end,
    case Flag of
        true ->
            StartIdx = (NowPage - 1) * Num + 1,
            PageList = lists:sublist(NewL, StartIdx, Num),
            {Type, SubType, NowPage, PageTotal, NewLen, PageList};
        false ->
            PageList = [],
            {Type, SubType, NowPage, PageTotal, NewLen, PageList}
    end;
list(Role, Type, Page, _Num, SubType) ->
    list(Role, Type, Page, 100, SubType).

current_list(Role, Type, Page, Num, SubType)
    when Num > 0 andalso Num =< 100 ->
    L1 = case SubType =:= 2 of
             true -> list_sub_type(Role, Type);
             false ->
                 #rank{list = L} = rank_mgr:lookup(Type),
                 L
         end,
    NewL = set_rank(L1),
    NewLen = length(NewL),
    PageTotal = util:ceil(NewLen / Num),
    {Flag, NowPage} = if Page < 1 orelse PageTotal =:= 0 ->
                             {false, 1};
                         Page > PageTotal -> {false, PageTotal};
                         true -> {true, Page}
                      end,
    case Flag of
        true ->
            StartIdx = (NowPage - 1) * Num + 1,
            PageList = lists:sublist(NewL, StartIdx, Num),
            {Type, SubType, NowPage, PageTotal, NewLen, PageList};
        false ->
            PageList = [],
            {Type, SubType, NowPage, PageTotal, NewLen, PageList}
    end;
current_list(Role, Type, Page, _Num, SubType) ->
    list(Role, Type, Page, 100, SubType).

set_rank(L) -> set_rank(L, 1, []).

set_rank([], _, L) -> lists:reverse(L);
set_rank([Rc | T], Idx, L) ->
    set_rank(T, Idx + 1, [Rc#rank_rc{rank = Idx} | L]).

