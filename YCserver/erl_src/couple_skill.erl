study(Role = #role{id = RoleId,
                   m_skill =
                       Skills = #m_skill{skill_couple = CoupleySkill},
                   m_wedding = #m_wedding{status = 3}},
      SkillId) ->
    case wedding:lover(RoleId) of
        {ok, #lover{lover_id = LoverId}} ->
            case team:get_members(Role) of
                [#team_mate{id = LoverId, pid = Pid, status = 2}] ->
                    case check_active_condition(Role, LoverId, SkillId) of
                        {false, Reason} -> {false, Reason};
                        {true, Loss} ->
                            case role_gain:do_notice(Loss, Role) of
                                {ok, LossRole} ->
                                    Intimacy = friend:get_intimacy(RoleId,
                                                                   LoverId),
                                    case role:apply(sync,
                                                    Pid,
                                                    {couple_skill,
                                                     apply_study,
                                                     [SkillId, Intimacy]})
                                        of
                                        {false, Reason} ->
                                            logger:error("伴侣学习技能错误:~w",
                                                         [Reason],
                                                         couple_skill,
                                                         38),
                                            {false, Reason};
                                        ok ->
                                            NewCoupleSkills = case
                                                                  check_has_active(CoupleySkill,
                                                                                   SkillId)
                                                                  of
                                                                  true ->
                                                                      CoupleySkill;
                                                                  false ->
                                                                      [SkillId
                                                                       | CoupleySkill]
                                                              end,
                                            NewRole = LossRole#role{m_skill =
                                                                        Skills#m_skill{skill_couple
                                                                                           =
                                                                                           NewCoupleSkills}},
                                            calc_and_push(NewRole,
                                                          SkillId,
                                                          Intimacy),
                                            {ok, NewRole};
                                        _ ->
                                            logger:error("请求对方信息失败",
                                                         [],
                                                         couple_skill,
                                                         49),
