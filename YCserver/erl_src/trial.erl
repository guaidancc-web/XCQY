            case accept_update(Role1) of
                {ok, Role2} ->
                    case enter(Role2) of
                        {ok, NewRole} -> {ok, NewRole, Reset};
                        {false, Reason} -> {false, Reason, Reset}
                    end;
                {false, Reason} -> {false, Reason, Reset}
            end
    end.

