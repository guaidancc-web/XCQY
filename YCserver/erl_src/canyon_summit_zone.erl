    notice:cast({map, MapId},
                5,
                lang:get("队伍人数3人以上才可参与峡谷之巅，人数越多越有优势，请务必集结队友{face_1,7}")),
    erlang:send_after(60 * 1000, self(), notice_team),
    {noreply, State};
handle_info(_Info, State) ->
    logger:debug("收到未知消息:~w",
                 [_Info],
                 canyon_summit_zone,
                 157),
    {noreply, State}.

