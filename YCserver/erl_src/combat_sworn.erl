heal(Self = #fighter{id = Sid, group = Group,
                     sworn_id = SwornId, origin_id = SOriginId},
     HealVal, SkillId) ->
    RoleList = combat_cache:all(Group),
    RoleList1 = [F
                 || F = #fighter{id = Fid, type = 1, is_die = 0,
                                 is_escape = 0, sworn_id = TSwornId,
                                 special_attr =
                                     #special_attr{is_sworn_heal = 0}}
                        <- RoleList,
                    SwornId =:= TSwornId andalso Sid =/= Fid],
    case util:rand_list(RoleList1) of
        Target = #fighter{id = Tid, origin_id = TOriginId} ->
            Svc = [{is_sworn_heal, 0, 1}],
            Tvc = [{hp, 1, HealVal}, {is_sworn_heal, 0, 1}],
            Tc = [{0, HealVal, 0}],
            combat_cache:u(Tid, Tvc),
            combat_cache:u(Sid, Svc),
            sworn:sworn_evt(SOriginId, skill),
            sworn:sworn_evt(TOriginId, skill),
            SubPlay =
                combat_play:gen_sub_skill_play(die_master_effect,
                                               {Self,
                                                Target,
                                                Tc,
                                                1,
                                                0,
                                                [{Tid, SkillId, 1}]}),
            combat_play:add_sub_play(SubPlay);
        _ -> ok
    end.

protect(#fighter{sworn_id = {0, _, _}}, DmgHp,
        DmgHolyHp) ->
    {DmgHp, DmgHolyHp};
protect(Self = #fighter{id = Sid, hp = Hp,
                        hp_max = HpMax, group = Group, sworn_id = SwornId,
                        origin_id = SOriginId,
                        combat_init_attr =
                            #combat_init_attr{sworn_protect =
                                                  {Ratio,
                                                   HpLine,
                                                   ProtectRatio}}},
        DmgHp, DmgHolyHp) ->
    Result = case util:rand(1, 1000) =< Ratio of
                 true ->
                     case Hp / HpMax =< HpLine / 1000 of
                         true ->
                             DmgHp1 = round(DmgHp * ProtectRatio / 1000),
                             DmgHolyHp1 = round(DmgHolyHp * ProtectRatio /
                                                    1000),
                             case DmgHp1 + DmgHolyHp1 >= Hp of
                                 true -> false;
                                 false ->
                                     ProtectDmgHp = max(0, DmgHp - DmgHp1),
                                     ProtectDmgHolyHp = max(0,
                                                            DmgHolyHp -
                                                                DmgHolyHp1),
                                     {true,
                                      DmgHp1,
                                      DmgHolyHp1,
                                      ProtectDmgHp,
                                      ProtectDmgHolyHp}
                             end;
                         _ -> false
                     end;
                 _ -> false
             end,
    case Result of
        {true,
         NewDmgHp,
         NewDmgHolyHp,
         SwordDmgHp,
         SwordDmgHolyHp} ->
            RoleList = combat_cache:all(Group),
            RoleList1 = [F
                         || F = #fighter{id = Fid, type = 1, is_die = 0,
                                         is_escape = 0, sworn_id = TSwornId,
                                         special_attr =
                                             #special_attr{is_sworn_protect =
                                                               0}}
                                <- RoleList,
                            SwornId =:= TSwornId andalso Sid =/= Fid],
            case util:rand_list(RoleList1) of
                Target = #fighter{id = Tid, hp = Thp,
                                  origin_id = TOriginId} ->
                    LastThp = Thp - (SwordDmgHp + SwordDmgHolyHp),
                    case LastThp =< 0 of
                        true -> {DmgHp, DmgHolyHp};
                        false ->
                            {IsTDie, Tvc, Tc} = {0,
                                                 [{hp, 0, LastThp},
                                                  {is_sworn_protect, 0, 1}],
                                                 [{0,
                                                   -(SwordDmgHp +
                                                         SwordDmgHolyHp),
                                                   0}]},
                            combat_cache:u(Tid, Tvc),
                            SwordPlay = combat_play:gen_sub_skill_play(protect,
                                                                       {Target,
                                                                        Self,
                                                                        Tc,
                                                                        IsTDie,
                                                                        []}),
                            combat_play:add_sub_play(SwordPlay),
                            sworn:sworn_evt(SOriginId, skill),
                            sworn:sworn_evt(TOriginId, skill),
                            {NewDmgHp, NewDmgHolyHp}
                    end;
                _ -> {DmgHp, DmgHolyHp}
            end;
        _ -> {DmgHp, DmgHolyHp}
    end;
protect(_, DmgHp, DmgHolyHp) -> {DmgHp, DmgHolyHp}.

