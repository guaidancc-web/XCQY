overdue(Role = #role{m_achievement =
                         MAchi = #m_achievement{doing = Quests, overdue = OverL,
                                                finish = FinL}}) ->
    Point = calc_point(Quests, 0) + calc_point(FinL, 0),
    Now = date:unixtime() - 1,
    NewQuests = [Quest
                 || Quest = #quest{end_time = EndT, finish = Finish}
                        <- Quests,
                    Finish =:= 1 orelse EndT > Now orelse EndT =:= 0],
    NewOverL = [Id
                || #quest{id = Id, end_time = EndT, finish = 0}
                       <- Quests,
                   EndT =< Now, EndT > 0],
    Role#role{m_achievement =
                  MAchi#m_achievement{doing = NewQuests,
                                      overdue = OverL ++ NewOverL,
                                      point = Point}}.

calc_can_do([], Role, _Push) -> Role;
calc_can_do([Id | T], Role, Push) ->
    NRole = do_calc_can_do([lev,
                            finish,
                            doing,
                            pre_quest,
                            condition,
                            add],
                           Role,
                           achievement_data:get(Id),
                           Push),
    calc_can_do(T, NRole, Push).

do_calc_can_do([], Role, _Data, _Push) -> Role;
do_calc_can_do([Label | T], Role, Data, Push) ->
    case do_calc_can_do(Label, Role, Data, Push) of
        {ok, NRole} -> do_calc_can_do(T, NRole, Data, Push);
        true -> do_calc_can_do(T, Role, Data, Push);
        false -> Role
    end;
do_calc_can_do(finish,
               #role{m_achievement =
                         #m_achievement{finish = FinL, overdue = OverL}},
               #quest_data{id = Id}, _Push) ->
    lists:keyfind(Id, 1, FinL) =:= false andalso
        lists:member(Id, OverL) =:= false;
do_calc_can_do(doing,
               #role{m_achievement = #m_achievement{doing = DoL}},
               #quest_data{id = Id}, _Push) ->
    lists:keyfind(Id, #quest.id, DoL) =:= false;
do_calc_can_do(lev, #role{lev = Lev},
               #quest_data{lev = MinLev}, _Push) ->
    Lev >= MinLev;
do_calc_can_do(pre_quest,
               #role{m_achievement =
                         #m_achievement{finish = FinL, doing = Quests}},
               #quest_data{pre_quest = PreId}, _Push) ->
    case lists:keyfind(PreId, #quest.id, Quests) of
        #quest{finish = 1} -> true;
        _ ->
            PreId =:= undefined orelse
                PreId =:= 0 orelse
                    lists:keyfind(PreId, 1, FinL) =/= false
    end;
do_calc_can_do(condition, Role,
               #quest_data{condition = Conds}, _Push) ->
    role_cond:check(Conds, Role) =:= true;
do_calc_can_do(add,
               Role = #role{id = RoleId,
                            m_achievement =
                                MAchi = #m_achievement{doing = DoL,
                                                       point = Point,
                                                       assets_point =
                                                           AssetsPoint,
                                                       finish = FinL}},
