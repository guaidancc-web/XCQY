                                end;
                            _ when OrderId =:= 1 -> {ExOrder, ok};
                            _ -> {ExOrder, {false, lang:get("请优先兑换前边的道具")}}
                        end,
    case Rtn of
        ok ->
            case camp_score_exchange_data:get_special_item(TrupId)
                of
                #camp_score_exchange_item{item_id = ItemId, bind = Bind,
                                          base_num = BaseNum, cost = Cost,
