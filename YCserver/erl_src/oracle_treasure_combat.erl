calc_wave_reward(#combat{type = 70, result = Result,
                         start_time = StartTime,
                         start_args = #combat_start_args{ext_args = ExtArgs}},
                 all) ->
    UseTime = date:unixtime() - StartTime,
    case Result =:= 98 orelse Result =:= 10 of
        true -> put(oracle_treasure_wave_use_time, UseTime);
        _ -> ingore
    end,
    Wave = get(oracle_treasure_wave),
    UnitId = {Group, _BaseId} = case lists:keyfind(unit_id,
                                                   1,
                                                   ExtArgs)
                                    of
                                    {_, _UnitId = {_Group, _}} -> _UnitId;
                                    _ -> 0
                                end,
    Fun = fun (#fighter{pid = Pid, type = 1})
                  when is_pid(Pid) ->
                  IsFirstKill = case
                                    oracle_treasure_mgr:lookup_unit(UnitId)
                                    of
                                    {ok,
                                     #oracle_treasure_unit{offer_teams =
                                                               OfferTeams}} ->
                                        lists:keymember(5,
                                                        #oracle_treasure_team.wave,
                                                        OfferTeams);
                                    _ -> false
                                end,
                  role:apply(async,
                             Pid,
                             {oracle_treasure_role,
                              wave_reward,
                              [Wave, Result, UseTime, IsFirstKill]}),
                  ok;
              (_) -> ok
          end,
    Fighters = [F
                || F = #fighter{type = 1} <- combat_cache:atk()],
    CurrentWave = Wave - 1,
    case CurrentWave > 0 of
        true ->
            RankList = fighter_to_oracle_treasure_rank_rc(Fighters,
                                                          Wave - 1,
                                                          UseTime),
            logger:debug("排行数据转化:~w",
                         [RankList],
                         oracle_treasure_combat,
                         114),
            oracle_treasure_mgr:info({update_rank,
                                      Group,
                                      RankList}),
            ok;
        _ -> ok
    end,
    lists:foreach(Fun, combat_cache:atk()).

