alternative_cards(_, _TotalVal, _Val, Num)
    when Num >= 2 ->
    [];
alternative_cards([], _, _, _) -> [];
alternative_cards(L, TotalVal, Val, Num) ->
    #{item_id := SI, item_num := SN, announce := SA,
      item_price := SP} =
        util:rand_list(L, item_weight),
    Option = #dungeon_card{item_id =
                               item_type:special_id(SI),
                           item_num = SN, announce = SA, selected = 0},
    NewVal = Val + SP,
    [Option | alternative_cards([O
                                 || O = #{item_id := OI, item_price := OP} <- L,
                                    OI =/= SI andalso OP + NewVal =< TotalVal],
                                TotalVal,
                                NewVal,
                                Num + 1)].

