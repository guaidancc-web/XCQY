flush_five(Role = #role{m_dungeon =
                            MDu = #m_dungeon{cards = Cards}},
           _) ->
    ItemList = [{ItemId, 0, Num}
                || {_,
                    [#dungeon_card{selected = 1, item_id = ItemId,
                                   item_num = Num}
                     | _]}
                       <- Cards],
    case ItemList of
        [] -> ok;
        _ ->
            Title = lang:get("副本翻牌奖励"),
            Content = lang:get("您的副本翻牌奖励未领取，请查收"),
            mail:send(Role, Title, Content, ItemList)
    end,
    NewRole = Role#role{m_dungeon =
                            MDu#m_dungeon{cards = []}},
    {ok, NewRole}.

