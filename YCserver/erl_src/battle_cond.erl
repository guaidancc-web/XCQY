-spec check(list()) -> true | false.

check([]) -> true;
check([Cond | T]) ->
    case check(Cond) of
        false -> false;
        true -> check(T)
    end;
check(Cond = #condition{label = 'and', val = Conds}) ->
    rtn(Cond, do_check(Conds, 'and'));
check(Cond = #condition{label = 'or', val = Conds}) ->
    rtn(Cond, do_check(Conds, 'or'));
check(Cond = #condition{label = global_val, op = range,
                        val = {Name, Val1, Val2}}) ->
    GetVal = battle_fun:get_val(Name),
    case GetVal >= Val1 andalso GetVal =< Val2 of
        true -> rtn(Cond, true);
        false -> rtn(Cond, false)
    end;
check(Cond = #condition{label = global_val, op = Op,
                        val = {Name, Val}}) ->
    GetVal = battle_fun:get_val(Name),
    rtn(Cond, comp(Op, GetVal, Val));
check(Cond = #condition{label = unit_sur, op = eq,
                        val = {BattleId, Id}}) ->
    Survival = case unit_mgr:info({BattleId, Id}) of
                   {ok, _U} -> true;
                   _ -> false
               end,
    rtn(Cond, Survival);
check(Cond = #condition{label = unit_sur, op = eq,
                        val = {Id}}) ->
    Survival = case unit_mgr:info({get(battle_id), Id}) of
                   {ok, _U} -> true;
                   _ -> false
               end,
    rtn(Cond, Survival);
check(Cond = #condition{label = unit_die_type,
                        op = range, val = {Val1, Val2}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_die{type = Type} ->
            rtn(Cond, Type >= Val1 andalso Type =< Val2);
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_die_type, op = Op,
                        val = {Target}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_die{type = Type} ->
            rtn(Cond, comp(Op, Type, Target));
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_die_id, op = range,
                        val = {Val1, Val2}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_die{unit_id = {_, Id}} ->
            rtn(Cond, Id >= Val1 andalso Id =< Val2);
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_die_id, op = Op,
                        val = {Target}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_die{unit_id = {_, Id}} ->
            rtn(Cond, comp(Op, Id, Target));
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_killed_id,
                        op = range, val = {Val1, Val2}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_killed{unit_id = {_, Id}} ->
            rtn(Cond, Id >= Val1 andalso Id =< Val2);
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_killed_id, op = Op,
                        val = {Target}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_killed{unit_id = {_, Id}} ->
            rtn(Cond, comp(Op, Id, Target));
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_killed_type,
                        op = range, val = {Val1, Val2}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_killed{type = Type} ->
            rtn(Cond, Type >= Val1 andalso Type =< Val2);
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_killed_type,
                        op = Op, val = {Target}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_killed{type = Type} ->
            rtn(Cond, comp(Op, Type, Target));
        _ -> rtn(Cond, false)
    end;
check(Cond = #condition{label = unit_killed_base_id,
                        op = Op, val = {Target}}) ->
    case get(battle_last_evt) of
        #evt_battle_unit_killed{base_id = Id} ->
            rtn(Cond, comp(Op, Id, Target));
        _ -> rtn(Cond, false)
    end;
check(Cond) ->
    logger:error("不支持的判定条件: ~w", [Cond], battle_cond, 148),
    rtn(Cond, false).

do_check([], 'and') -> true;
do_check([], 'or') -> false;
do_check([Cond | T], 'and') ->
    case check(Cond) of
        false -> false;
        true -> do_check(T, 'and')
    end;
do_check([Cond | T], 'or') ->
    case check(Cond) of
        false -> do_check(T, 'or');
        true -> true
    end.

comp(ue, Val, TargetVal) -> Val =/= TargetVal;
comp(eq, Val, TargetVal) -> Val =:= TargetVal;
comp(lt, Val, TargetVal) -> Val < TargetVal;
comp(gt, Val, TargetVal) -> Val > TargetVal;
comp(le, Val, TargetVal) -> Val =< TargetVal;
comp(ge, Val, TargetVal) -> Val >= TargetVal.

rtn(_Cond, true) -> true;
rtn(_Cond, false) -> false.

