get_feedable(Role) ->
    {max(0,
         2 - var:get_var(Role, day, guild_boss_feed_time, 0)),
     2}.

-spec feed(Role :: #role{}) -> {ok,
                                NewRole :: #role{}} |
                               {false, Why :: string()}.

feed(#role{m_guild = #m_guild{guild_lev = Lev}})
    when Lev < 3 ->
    {false, lang:get("需要3级公会才能喂养神兽")};
feed(#role{m_guild = #m_guild{post = 0}}) ->
    {false, lang:get("公会新秀不能喂养")};
feed(Role = #role{m_guild =
                      Mg = #m_guild{pid = GuildPid},
                  id = Id, pid = Pid})
    when is_pid(GuildPid) ->
    Donation = 30,
    case role_gain:do([#loss{label = item_base_id,
                             val = [{20038, 1}]},
                       #gain{label = guild, val = Donation}],
                      Role)
        of
        {ok, NewRole} ->
            case guild:apply(sync,
                             GuildPid,
                             {guild_boss, sync_apply, [{feed, Id}]})
                of
                {ok,
                 #guild_role{value = Value, total_value = Total},
                 NewBoss} ->
                    NRole1 = NewRole#role{m_guild =
                                              Mg#m_guild{value = Value,
                                                         total_value = Total}},
                    role:pack_send(Pid, 11134, {NewBoss}),
                    {ok, NRole1};
                {false, Reason} -> {false, Reason};
                _Err ->
                    logger:error("喂养公会神兽时发生异常: ~w", [_Err], guild_boss, 54),
                    {ok, Role}
            end;
        _ -> {false, lang:get("资产不足")}
    end;
feed(_) -> {false, lang:get("请先加入公会")}.

