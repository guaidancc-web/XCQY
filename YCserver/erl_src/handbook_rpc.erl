handle(17108, {Id},
       Role = #role{p_bag = Pbag,
                    m_handbook = #m_handbook{book_list = BookList}}) ->
    case package:find(by_id, Id, Pbag) of
        false -> {reply, {0, lang:get("碎片不存在，无法分解")}};
        {ok, #item{type = 136, base_id = BaseId}} ->
            Flag = case handbook_data:get_decompose(BaseId) of
                       {0, Val} -> {true, Val};
                       {BookId, Val} ->
                           case lists:keyfind(BookId, #handbook.id, BookList) of
                               #handbook{status = 1} -> {true, Val};
                               _ -> {false, lang:get("您对应的图鉴还未收藏哦，只有收藏后才能拆分呢")}
                           end;
                       _ -> {reply, {0, lang:get("该图鉴碎片不能分解")}}
                   end,
            case Flag of
                {true, GainVal} ->
                    role:send_buff_begin(),
                    AllVal = 1 * GainVal,
                    Loss = [#loss{label = item_id, val = [{Id, 1}]}],
                    Gain = format:val_to_gain([{90024, AllVal}]),
                    case role_gain:do(Loss, Role) of
                        {ok, LossRole} ->
                            case role_gain:do(Gain, LossRole) of
                                {ok, GainRole} ->
                                    Msg = notice:format(lang:get("消耗~ts，获得~ts"),
                                                        [{item_2, BaseId, 1},
                                                         {assets_1,
                                                          90024,
                                                          AllVal}]),
                                    role:send_buff_flush(),
                                    {reply, {1, Msg}, GainRole};
                                {false, _} ->
                                    logger:error("增加图鉴积分失败[~w]",
                                                 [Gain],
                                                 handbook_rpc,
                                                 103),
                                    role:send_buff_clean(),
                                    {reply, {0, lang:get("无法增加图鉴积分")}}
                            end;
                        _Err ->
                            logger:error("神秘商店购买失败[~w]",
                                         [_Err],
                                         handbook_rpc,
                                         108),
                            role:send_buff_clean(),
                            {reply, {0, lang:get("图鉴碎片不足，无法分解")}}
                    end;
                {false, Reason} -> {reply, {0, Reason}}
            end;
        _ -> {reply, {0, lang:get("只有图鉴碎片才能分解")}}
    end;
