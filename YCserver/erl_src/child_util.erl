calc_child_classes_type(ClassesList) ->
    calc_child_classes_type(ClassesList, []).

calc_child_classes_type([], ClassesTypes) ->
    case ClassesTypes of
        [_ | _] ->
            case util:rand(1, 100) =< 10 of
                true -> util:rand_list([1, 2, 3]);
                false -> util:rand_list(ClassesTypes)
            end;
        _ -> util:rand_list([1, 2, 3])
    end;
calc_child_classes_type([Classes | T], ClassesTypes) ->
    Type = case Classes of
               1 -> 1;
               2 -> 2;
               3 -> 1;
               4 -> 3;
               5 -> 3;
               6 -> 2;
               7 -> 1;
               _ -> 2
           end,
    case lists:member(Type, ClassesTypes) of
        true -> calc_child_classes_type(T, ClassesTypes);
        _ -> calc_child_classes_type(T, [Type | ClassesTypes])
    end.

get_growth_val(BaseId, Grade, GrowthType, ChildLev,
               ExtGrowth) ->
    case child_data:get_growth_val({ChildLev, GrowthType})
        of
        GrowthVal when is_integer(GrowthVal) ->
            case Grade > 0 of
                true ->
                    case child_data:get_grade_growth({BaseId, Grade}) of
                        GradeGrowth when is_integer(GradeGrowth) ->
                            GrowthVal + GradeGrowth + ExtGrowth;
                        _ ->
                            logger:error("无法找到[~w][~w]对应的成长值",
                                         [BaseId, Grade],
                                         child_util,
                                         196),
                            GrowthVal + ExtGrowth
                    end;
                _ -> GrowthVal + ExtGrowth
            end;
        _ ->
            logger:error("无法找到[~w][~w]对应的成长值",
                         [ChildLev, GrowthType],
                         child_util,
                         203),
            0
    end.

