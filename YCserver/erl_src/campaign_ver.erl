parse_field(MCampaign, []) -> {ok, MCampaign};
parse_field(MCampaign, [Field | T]) ->
    case do_parse_field(Field, MCampaign) of
        {error, Reason} -> {error, Reason};
        {ok, NewMCampaign} -> parse_field(NewMCampaign, T)
    end.

do_parse_field(camp_doll,
               MCampaign = #m_campaign{camp_doll = CampDoll}) ->
    case do_camp_doll(CampDoll) of
        {error, Reason} -> {error, Reason};
        {ok, NewCampDoll} ->
            {ok, MCampaign#m_campaign{camp_doll = NewCampDoll}}
    end;
do_parse_field(recharge,
               MCampaign = #m_campaign{recharge = Recharge}) ->
    case do_recharge(Recharge) of
        {error, Reason} -> {error, Reason};
        {ok, NewRecharge} ->
            {ok, MCampaign#m_campaign{recharge = NewRecharge}}
    end;
do_parse_field(recharge_open,
               MCampaign = #m_campaign{recharge_open =
                                           RechargeOpen}) ->
