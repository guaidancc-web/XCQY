focus(Role = #role{m_achievement =
                       MAchi = #m_achievement{focus = Focus, finish = FinL,
                                              overdue = OverL}},
      Id) ->
    case length(Focus) >= 5 of
        true -> {false, lang:get("最多关注5个成就，可取消已关注成就")};
        _ ->
            case {lists:keyfind(Id, 1, FinL),
                  lists:member(Id, OverL)}
                of
                {false, false} ->
                    NewFocus = (Focus -- [Id]) ++ [Id],
                    NewMAchi = MAchi#m_achievement{focus = NewFocus},
                    NewRole = Role#role{m_achievement = NewMAchi},
                    focus_push(NewRole),
                    case achievement_data:get(Id) of
                        #quest_data{name = Name} ->
                            notice:send(Role,
                                        3,
                                        notice:format(lang:get("已关注~ts，可在[进行中]优先查看"),
