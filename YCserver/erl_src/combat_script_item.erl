do_use_item(Self = #fighter{type = Type,
                            master_fid = MasterFid},
            Target = #fighter{},
            #c_item{skill_id = SkillId, skill_lev = SkillLev,
                    anti_heal = AntiHeal},
            Sc, Tc, IsSelfDie, IsTargetDie) ->
    case Type of
        3 ->
            combat_pet:pet_talk(Self, 6),
            combat_cache:u(MasterFid, [{has_use_item, 1, 1}]);
        6 -> combat_cache:u(MasterFid, [{has_use_item, 1, 1}]);
        _ -> combat_cache:u(Self, [{has_use_item, 1, 1}])
    end,
    case AntiHeal > 0 of
        true ->
            combat_cache:u(Target, [{anti_heal, 1, AntiHeal}]);
        _ -> skip
    end,
    combat_play:add_sub_play(combat_play:gen_sub_skill_play(use_item,
                                                            {Self,
                                                             Target,
                                                             SkillId,
                                                             SkillLev,
                                                             Sc,
                                                             Tc,
                                                             IsSelfDie,
                                                             IsTargetDie})).

heal_hp_link(Self = #fighter{},
             _Target = #fighter{id = Tid, type = TType,
                                special_attr = #special_attr{hp_link = HpLink},
                                master_fid = MasterFid},
             #c_item{skill_id = SkillId, skill_lev = SkillLev},
             HealHp) ->
    logger:debug("heal hp link ~w",
                 [HealHp],
                 combat_script_item,
                 167),
    {LinkFighter, HpLinkRatio} = case TType of
                                     3 ->
                                         case combat_cache:f(by_id, MasterFid)
                                             of
                                             Master = #fighter{is_escape = 0,
                                                               is_die = 0}
                                                 when HpLink > 0 ->
                                                 {Master, HpLink};
                                             _ -> {undefined, 0}
                                         end;
                                     _ ->
                                         case combat_cache:f(by_master_id, Tid)
                                             of
                                             Pet = #fighter{is_escape = 0,
                                                            is_die = 0,
                                                            special_attr =
                                                                #special_attr{hp_link
                                                                                  =
                                                                                  PetHpLink}}
                                                 when PetHpLink > 0 ->
                                                 {Pet, PetHpLink};
                                             _ -> {undefined, 0}
                                         end
                                 end,
    case LinkFighter of
        #fighter{id = LinkId} ->
            LinkHealHp = round(HealHp * HpLinkRatio / 1000),
            Tvc = [{hp, 1, LinkHealHp}],
            Tc = [{0, LinkHealHp, 0}],
            combat_cache:u(LinkId, Tvc),
            logger:debug("heal hp ratio ~w hp ~w",
                         [HpLinkRatio, LinkHealHp],
                         combat_script_item,
                         187),
            combat_play:add_sub_play(combat_play:gen_sub_skill_play(use_item,
                                                                    {Self,
                                                                     LinkFighter,
                                                                     SkillId,
                                                                     SkillLev,
                                                                     [],
                                                                     Tc,
                                                                     0,
                                                                     0})),
            ok;
        _ -> ok
    end.

