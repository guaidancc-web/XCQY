update_pet_skill(PetSkill) ->
    update_pet_skill(PetSkill, []).

update_pet_skill([], PetSkill) ->
    {true, lists:reverse(PetSkill)};
update_pet_skill([Skill | T], PetSkill) ->
    case do_update_pet_skill(Skill) of
        {ok, NewSkill} ->
            update_pet_skill(T, [NewSkill | PetSkill]);
        {error, Reason} -> {error, Reason}
    end.

