do_update_statue([I | T], N, DunId, Floor) ->
    do_update_statue(I, N, DunId, Floor),
    do_update_statue(T, N + 1, DunId, Floor);
do_update_statue(#dungeon_lord_role{id = RoleId,
                                    name = Name, lev = Lev, classes = Classes,
                                    sex = Sex, looks = Looks},
                 N, DunId, Floor) ->
    Id = DunId * 1000 + Floor * 10 + N,
    case unit_mgr:info({get(battle_id), Id}) of
        {ok, Unit = #unit{role_id = OldRoleId}}
            when RoleId =/= OldRoleId ->
            ElemPos = [{#unit.role_id, RoleId},
                       {#unit.name, Name},
                       {#unit.lev, Lev},
                       {#unit.classes, Classes},
                       {#unit.sex, Sex},
                       {#unit.looks, Looks}],
            unit_mgr:set_element(Unit, ElemPos);
        _ -> ok
    end;
do_update_statue(_, _N, _DunId, _Floor) -> ok.

to_rank_role([], _, _, List) -> List;
to_rank_role([#fighter{type = 1, origin_id = Id,
                       name = Name, sex = Sex, classes = Classes,
                       attr = #attr{fc = Fc}, lev = Lev, looks = Looks,
                       is_leader = IsLeader}
              | T],
             CombatTime, {RecordId, RePlat, ReZoneId}, List) ->
    R = #dungeon_rank_role{id = Id, name = Name, sex = Sex,
                           classes = Classes, lev = Lev, looks = Looks,
                           val1 = CombatTime, fc = Fc, val2 = IsLeader,
                           val3 = RecordId, val4 = ReZoneId, msg1 = RePlat},
    to_rank_role(T, CombatTime, RecordId, [R | List]);
