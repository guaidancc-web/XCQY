-spec fetch_ask_id() -> {ok, AskId :: pos_integer()} |
                        {false, string()}.

fetch_ask_id() ->
    case case catch gen_server:call(ask_mgr,
                                    fetch_ask_id,
                                    10000)
             of
             {'EXIT', {timeout, _}} -> {error, timeout};
             {'EXIT', {noproc, _}} -> {error, noproc};
             {'EXIT', {normal, _}} -> {error, exit};
             {'EXIT', _Call_Err} -> {error, _Call_Err};
             _Call_Return -> _Call_Return
         end
        of
        {ok, AskId} -> {ok, AskId};
        {false, Msg} -> {false, Msg};
        _ -> {false, lang:get("无法获取求助记录Id")}
    end.

