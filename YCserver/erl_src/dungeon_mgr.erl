agenda_flag(Now, Id) ->
    WeekDay = date:day_of_the_week(Now),
    case agenda_data:get(Id) of
        #{args := Args} ->
            case lists:member(WeekDay, Args) of
                true -> true;
                _ -> false
            end;
        _ -> false
    end.

