revoke_dfd_pos() ->
    [CombatType] =
        combat_cache:get_context_elem([#combat_context.type]),
    AtkPos = get({pos, 0}),
    DfdPos = get({pos, 1}),
    combat_fighter:do_revoke_dead_pos(CombatType,
                                      combat_cache:all(0),
                                      0,
                                      AtkPos,
                                      []),
    do_revoke_dfd_pos(CombatType,
                      combat_cache:all(1),
                      1,
                      DfdPos,
                      []).

do_revoke_dfd_pos(_, _, Group, [], Result) ->
    put({pos, Group}, Result);
do_revoke_dfd_pos(CombatType, Fighters, Group,
                  [{PosId, 0} | T], Result) ->
    do_revoke_dfd_pos(CombatType,
                      Fighters,
                      Group,
                      T,
                      [{PosId, 0} | Result]);
do_revoke_dfd_pos(CombatType, Fighters, Group,
                  [{PosId, 1} | T], Result) ->
    case can_revoke_dfd_pos(Fighters, PosId) of
        true ->
            do_revoke_dfd_pos(CombatType,
                              Fighters,
                              Group,
                              T,
                              [{PosId, 0} | Result]);
        false ->
            do_revoke_dfd_pos(CombatType,
                              Fighters,
                              Group,
                              T,
                              [{PosId, 1} | Result])
    end.

can_revoke_dfd_pos([], _PosId) -> true;
can_revoke_dfd_pos([#fighter{id = Fid, pos = PosId,
                             is_escape = 1}
                    | T],
                   PosId) ->
    combat_cache:u(Fid, [{pos, 0, 0}]),
    can_revoke_dfd_pos(T, PosId);
can_revoke_dfd_pos([#fighter{id = Fid, pos = PosId,
                             is_die = 1}
                    | T],
                   PosId) ->
    combat_cache:u(Fid, [{pos, 0, 0}]),
    can_revoke_dfd_pos(T, PosId);
can_revoke_dfd_pos([#fighter{pos = PosId} | _T],
                   PosId) ->
    false;
can_revoke_dfd_pos([_ | T], PosId) ->
    can_revoke_dfd_pos(T, PosId).

gen_slave([], Rtn) -> Rtn;
gen_slave([{UnitBaseId, _, _} | Rest], Rtn) ->
    gen_slave(Rest, [{unit_baseid, UnitBaseId} | Rtn]);
gen_slave([{_, UnitBaseId, _, _} | Rest], Rtn) ->
    gen_slave(Rest, [{unit_baseid, UnitBaseId} | Rtn]);
gen_slave([_H | Rest], Rtn) ->
    logger:error("诸神挑战发现无法转换的随从：~w",
                 [_H],
                 gods_challenge_combat,
                 122),
    gen_slave(Rest, Rtn).

