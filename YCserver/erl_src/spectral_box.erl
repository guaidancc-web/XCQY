    when Num < 1 ->
    BoxList;
create_spectral_box(UnitBase, Maps, Num, BoxList) ->
    N = (Num - 1) rem length(Maps) + 1,
    MapId = lists:nth(N, Maps),
    case do_create_one(MapId, UnitBase) of
        {ok, UnitId, _} ->
            create_spectral_box(UnitBase,
                                Maps,
                                Num - 1,
                                [UnitId | BoxList]);
        _ ->
            create_spectral_box(UnitBase, Maps, Num - 1, BoxList)
    end.

do_create_one(MapId, UnitBase) ->
    case map:rand_pos(MapId) of
        {X, Y} ->
            case unit_mgr:create(45, UnitBase, {MapId, X, Y}) of
                {ok, #unit{id = UnitId}} ->
                    case erlang:get(spectral_box_map_list) of
                        MapL = [_ | _] ->
                            erlang:put(spectral_box_map_list,
                                       [{UnitId, {MapId, UnitBase}} | MapL]);
                        _ ->
                            erlang:put(spectral_box_map_list,
                                       [{UnitId, {MapId, UnitBase}}])
                    end,
                    {ok, UnitId, {X, Y}};
                _False ->
                    logger:error("刷新祈福灯失败:~w", [_False], spectral_box, 305),
                    false
