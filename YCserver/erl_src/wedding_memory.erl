reward_day(Day, Time, MailList) ->
    Years = case Day > 365 of
                true ->
                    Year = anniversary(Time),
                    year_day(Time, Year, []);
                _ -> []
            end,
    List = wedding_data:list_memorial_day(),
    Days = [Day1
            || {_Id, Day1} <- List, Day1 =< Day, Day1 < 365],
    Days1 = Years ++ Days,
    {Days1, Days1 -- MailList}.

year_day(_Time, 0, List) -> List;
year_day(Time, Year, List) ->
    {{Y1, M1, D1}, _} = date:seconds_to_datetime(Time),
    case catch date:datetime_to_seconds({{Y1 + 1, M1, D1},
                                         {0, 0, 0}})
        of
        Time1 when is_integer(Time1) ->
            Day = date:day_diff(Time, Time1),
            year_day(Time1, Year - 1, [Day | List]);
        _ -> List
    end.

