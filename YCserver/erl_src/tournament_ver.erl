    case tournament_ver:do_profile(P) of
        {ok, P1 = #tournament_profile{}} -> {ok, {K, P1}};
        Else -> Else
    end;
do_rank({K, L}) ->
    case do_rank_list(L, []) of
        {ok, L1} when is_list(L1) -> {ok, {K, L1}};
        Else -> Else
    end.

