clean_line([], _Line, Data) -> Data;
clean_line([H = #quest{id = QuestId} | T], Line,
           Data) ->
    case quest_data:get(QuestId) of
        #quest_data{quest_line = Line} ->
            logger:info("删除任务[~w]", [QuestId], quest_ver, 322),
            clean_line(T, Line, Data);
        _ -> clean_line(T, Line, [H | Data])
    end;
clean_line([QuestId | T], Line, Data)
    when is_integer(QuestId) ->
    case quest_data:get(QuestId) of
        #quest_data{quest_line = Line} ->
            logger:info("删除任务[~w]", [QuestId], quest_ver, 330),
            clean_line(T, Line, Data);
        _ -> clean_line(T, Line, [QuestId | Data])
    end;
clean_line([H | T], Line, Data) ->
    clean_line(T, Line, [H | Data]).

do_field([], MQuest) -> {ok, MQuest};
do_field([single_dog | T],
         MQuest = #m_quest{quest_single_dog = Data}) ->
    case single_dog_ver(Data) of
        {ok, Data2 = #quest_single_dog{}} ->
            do_field(T, MQuest#m_quest{quest_single_dog = Data2});
        _Else ->
            logger:error("双11任务版本转换失败 ~w", [_Else], quest_ver, 346),
            {false, "双11任务版本转换失败"}
    end;
do_field([acquaintance | T],
         MQuest = #m_quest{quest_acquaintance = Data}) ->
    case do_acquaintance(Data) of
        {ok, Acq = #quest_acquaintance{}} ->
            do_field(T, MQuest#m_quest{quest_acquaintance = Acq});
        _Else ->
            logger:error("结缘任务版本转换失败 ~w", [_Else], quest_ver, 354),
            {false, "结缘任务版本转换失败"}
    end.

