calc_all(X, Y,
         #child_attr{study_str = Z1, study_con = Z2,
                     study_mag = Z3, study_agi = Z4, study_end = Z5}) ->
    List1 = calc_study(Z1),
    List2 = calc_study(Z2),
    List3 = calc_study(Z3),
    List4 = calc_study(Z4),
    List5 = calc_study(Z5),
    case List1 =/= [] andalso
             List2 =/= [] andalso
                 List3 =/= [] andalso List4 =/= [] andalso List5 =/= []
        of
        true ->
            do_calc_all(X,
                        Y,
                        {List1, List2, List3, List4, List5},
                        List1,
                        List2,
                        List3,
                        List4,
                        List5);
        false -> false
    end.

do_calc_all(_X, _Y, _, [], _L2, _L3, _L4, _L5) -> false;
do_calc_all(X, Y, {OL1, OL2, OL3, OL4, OL5}, [_ | T1],
            [], _L3, _L4, _L5) ->
    do_calc_all(X,
                Y,
                {OL1, OL2, OL3, OL4, OL5},
                T1,
                OL2,
                OL3,
                OL4,
                OL5);
do_calc_all(X, Y, {OL1, OL2, OL3, OL4, OL5}, L1,
            [_ | T2], [], _L4, _L5) ->
    do_calc_all(X,
                Y,
