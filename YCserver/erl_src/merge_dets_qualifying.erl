do_init(Table = #merge_table{server =
                                 #merge_server{index = 1}}) ->
    Functions = {undefined,
                 fun merge_dets_qualifying:merge/2,
                 undefined},
    merge_util:dets_merge(qualifying_season_info,
                          "qualifying_season_info.dets",
                          set,
                          #qualifying_season_data.id,
                          Functions,
                          1),
    {ok, [], Table};
do_init(Table = #merge_table{server =
                                 #merge_server{index = Size, size = Size}}) ->
    merge_util:dets_merge(dets_qualifying_role_mark,
                          "qualifying_role_mark.dets",
                          set,
                          #qualifying_role_mark.id,
                          undefined),
    {ok, [], Table};
do_init(Table) -> {ok, [], Table}.

do_convert([], Table) -> {ok, Table}.

do_end(_Table) -> ignore.

merge(SeasonData = #qualifying_season_data{},
      #merge_server{platform = Platform, zone_id = ZoneId}) ->
    logger:info("清除[~ts][~w]的赛季数据",
                [Platform, ZoneId],
                merge_dets_qualifying,
                38),
    NewSeasonData =
        SeasonData#qualifying_season_data{champion_list = []},
    {ok, NewSeasonData};
merge(Unknow, _MergeServer) ->
    logger:error("未知的段位赛赛季数据:~w",
                 [Unknow],
                 merge_dets_qualifying,
                 42),
    {false, "未知的段位赛赛季数据"}.

