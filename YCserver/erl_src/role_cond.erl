-spec check(CondList, #role{}) -> true |
                                  {false, CondFalse} when CondList ::
                                                              [#condition{}],
                                                          CondFalse ::
                                                              #condition{}.

check([], _Role) -> true;
check([C | T], Role) ->
    case check(C, Role) of
        true -> check(T, Role);
        {false, Cond} -> {false, Cond}
    end;
check(Cond = #condition{label = rpc_cooldown,
                        val = Val},
      _) ->
    Cooldown = {rpc_cooldown, get(rpc_code)},
    T = date:unixtime(),
    case get(Cooldown) of
        undefined ->
            put(Cooldown, T),
            true;
        T0 ->
            put(Cooldown, T),
            rtn(Cond, T - T0 < Val, lang:get("发送请求太快"))
    end;
check(Cond = #condition{label = role_in_normal},
      #role{status = Status}) ->
    rtn(Cond, Status =:= 0, lang:get("当前状态下无法进行此操作"));
check(Cond = #condition{label = role_is_die},
      #role{status = Status}) ->
    rtn(Cond, Status =:= 1, lang:get("非死亡状态下无法进行此操作"));
check(Cond = #condition{label = role_in_combat},
      #role{status = Status}) ->
    rtn(Cond, Status =:= 1, lang:get("非战斗状态下无法进行此操作"));
check(Cond = #condition{label = event_normal},
      #role{s_event = Event}) ->
    rtn(Cond, Event =:= 0, lang:get("在参加活动时无法进行此操作"));
check(Cond = #condition{label = event, op = Op,
                        val = Val},
      #role{s_event = Event}) ->
    rtn(Cond,
        comp(Op, Event, Val),
        lang:get("当前不在指定的活动状态无法进行此操作"));
check(Cond = #condition{label = ride, op = Op,
                        val = Val},
      #role{s_ride = Ride}) ->
    rtn(Cond,
        comp(Op, Ride, Val),
        lang:get("当前不在指定的状态无法进行此操作"));
check(Cond = #condition{label = lev, op = Op,
                        val = Val},
      #role{lev = Lev}) ->
    rtn(Cond,
        comp(Op, Lev, Val),
        msg(lang:get("您的等级不符合要求"), Op, Val));
check(Cond = #condition{label = coin, op = ge,
