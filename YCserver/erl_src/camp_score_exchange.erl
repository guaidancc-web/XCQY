init() -> #m_camp_score_exchange{}.

reload() ->
    case get_day() of
        {0, 0} ->
            role_group:apply(world,
                             {camp_score_exchange, recovery_score, []});
        {Id, Day} ->
            role_group:apply(world,
                             {camp_score_exchange, flush, [{Id, Day}]})
    end.

login(Role = #role{}) ->
    case get_day() of
        {0, 0} ->
            {ok, Role1} = remove_all_quest(Role),
            TimeRole = role_timer:add(#timer{id =
                                                 camp_score_recovery,
                                             timeout = 5 * 1000,
                                             m = camp_score_exchange,
                                             f = recovery_score, a = [],
                                             times = 1},
                                      Role1),
            {ok, TimeRole};
        {Id, Day} -> flush(Role, {Id, Day})
    end;
login(_Role) -> ok.

flush(Role = #role{id = Rid,
                   m_camp_score_exchange =
                       MCampScoreExchange = #m_camp_score_exchange{camp_id =
                                                                       CampId,
                                                                   day =
                                                                       OldDay},
                   assets = Assets = #assets{score_exchange = OldVal}},
      {NewCampId, Day}) ->
    QuestList = case catch
                         camp_score_exchange_data:get_quests({NewCampId, Day})
                    of
                    L when is_list(L) -> L;
                    _ -> []
                end,
    case CampId =/= NewCampId of
        true ->
            logger:info("角色id：~w，活跃活动积分兑换资产清0，原资产：~w",
                        [Rid, OldVal],
                        camp_score_exchange,
                        70),
            {ok, Role1} = recovery_score(Role),
            NewRole = Role1#role{m_camp_score_exchange =
                                     #m_camp_score_exchange{camp_id = NewCampId,
                                                            day = Day},
                                 assets = Assets#assets{score_exchange = 0}},
            accept_quest_list(NewRole, QuestList, true);
        _ ->
            case OldDay =/= Day of
                true ->
                    NewRole = Role#role{m_camp_score_exchange =
                                            MCampScoreExchange#m_camp_score_exchange{day
                                                                                         =
                                                                                         Day}},
                    accept_quest_list(NewRole, QuestList, config);
                _ -> accept_quest_list(Role, QuestList, false)
            end
    end;
flush(Role, {NewCampId, Day}) ->
    NewRole = Role#role{m_camp_score_exchange =
                            #m_camp_score_exchange{camp_id = NewCampId,
                                                   day = Day}},
    flush(NewRole, {NewCampId, Day}).

push_items_info(Role = #role{sex = RSex,
                             classes = RClasses, lev = Lev,
                             m_camp_score_exchange =
                                 #m_camp_score_exchange{camp_id = CampId,
                                                        day = Day,
                                                        owned_item =
                                                            OwnedItems}}) ->
    case camp_score_exchange_data:get_config({CampId, Day})
        of
        {SpecialIds, ComId} ->
            ItemList1 = camp_score_exchange_data:get_special_gift(),
            Fun = fun (Item = #camp_score_exchange_item{id = Id,
                                                        order_id = OrderId,
                                                        item_id = ItemId,
                                                        exchange_num =
                                                            ExchangeNum,
                                                        min_lev = MinLev,
                                                        max_lev = MaxLev,
                                                        sex = Sex,
                                                        classes = Classes},
                       Temp) ->
                          case lists:member(Id, SpecialIds) of
                              true
                                  when Lev >= MinLev andalso
                                           Lev =< MaxLev andalso
                                               (RSex =:= Sex orelse Sex =:= 2)
                                                   andalso
                                                   (Classes =:= RClasses orelse
                                                        Classes =:= 0) ->
                                  case lists:keyfind({Id, OrderId, ItemId},
                                                     1,
                                                     OwnedItems)
                                      of
                                      {{Id, OrderId, ItemId}, OwnedNum} ->
                                          NewItem =
                                              Item#camp_score_exchange_item{exchange_num
                                                                                =
                                                                                max(0,
                                                                                    ExchangeNum
                                                                                        -
                                                                                        OwnedNum)},
                                          [NewItem | Temp];
                                      _ -> [Item | Temp]
                                  end;
                              _ -> Temp
                          end;
                      (_Item, Temp) -> Temp
                  end,
            SpecialList = lists:foldl(Fun, [], ItemList1),
            ItemList2 = camp_score_exchange_data:get_common_gift(),
            CommonList = [Item
                          || Item = #camp_score_exchange_item{id = Id,
                                                              min_lev = MinLev,
                                                              max_lev = MaxLev,
                                                              sex = Sex,
                                                              classes = Classes}
                                 <- ItemList2,
                             Id =:= ComId andalso
                                 Lev >= MinLev andalso
                                     Lev =< MaxLev andalso
                                         (RSex =:= Sex orelse Sex =:= 2) andalso
                                             (Classes =:= RClasses orelse
                                                  Classes =:= 0)],
            Data = {SpecialList, CommonList},
            logger:debug("~w", [Data], camp_score_exchange, 114),
