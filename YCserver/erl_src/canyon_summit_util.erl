convert_to_profile(Role = #role{id = Rid, pid = Pid,
                                name = Name, sex = Sex, classes = Classes,
                                lev = Lev, attr = #attr{fc = Fc}},
                   GroupId) ->
    PetFc = pet_attr:calc_fc(Role),
    #canyon_summit_role{id = Rid, name = Name, sex = Sex,
                        classes = Classes, lev = Lev, group_id = GroupId,
                        fight = Fc + PetFc, pid = Pid}.

get_opposite_side(1) -> 2;
get_opposite_side(_) -> 1.

check_side(Rid1, Rid2) ->
    case {ets:lookup(canyon_summit_role, Rid1),
          ets:lookup(canyon_summit_role, Rid2)}
        of
        {[#canyon_summit_role{group_id = GroupId,
                              match_id = MatchId, side = Side}],
         [#canyon_summit_role{group_id = GroupId,
                              match_id = MatchId, side = Side}]} ->
            true;
        _ -> false
    end.

get_name(SideId) ->
    case SideId of
        1 -> lang:get("联盟");
        2 -> lang:get("部落");
        0 -> lang:get("中立")
    end.

