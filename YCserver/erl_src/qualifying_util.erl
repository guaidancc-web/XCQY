    CheckFlag = case UpdateTime =:= 0 of
                    true -> 0;
                    false ->
                        case date:unixtime(zero) =:=
                                 date:unixtime({zero, UpdateTime})
                            of
                            true when Flag =:= 1 -> WinFlag;
                            true when Flag =:= 2 -> WinFiveFlag;
                            _ -> 1
                        end
                end,
    case CheckFlag of
        0 ->
            Result = case qualifying_mgr:find_role(RoleId) of
                         {ok,
                          #qualifying_role_mark{rank_lev = RankLev,
                                                day_flag = DayFlag,
