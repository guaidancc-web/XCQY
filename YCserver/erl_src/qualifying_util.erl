                                                              Mqua#m_qualifying{update_time
                                                                                    =
                                                                                    date:unixtime(),
                                                                                win_five_flag
                                                                                    =
                                                                                    1}}
                                                     end,
                                    NewRole1 = NewRole#role{m_qualifying =
                                                                NewMqua},
                                    {ok, Msg, NewRole1}
                            end
                    end
            end;
        _ -> {false, lang:get("今天已经领取过奖励，无法再次领取")}
    end.

