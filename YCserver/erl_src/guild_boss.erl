sync_apply(State = #guild{members = Members,
                          boss = Boss = #guild_boss{exp = Exp, log = Log}},
           {feed, RoleId}) ->
    AddVal = 30,
    AddExp = AddVal,
    case lists:keyfind(RoleId, #guild_role.id, Members) of
        R = #guild_role{total_value = TotalValue,
                        name = Name} ->
            Nr = R#guild_role{total_value = TotalValue + AddVal},
            NewMb = lists:keyreplace(RoleId,
                                     #guild_role.id,
                                     Members,
                                     Nr),
            NewLog = lists:sublist([{RoleId, Name, 0, AddExp}
                                    | Log],
                                   10),
            NewBoss = update_boss(Boss#guild_boss{exp =
                                                      Exp + AddExp,
                                                  log = NewLog}),
            NewState = State#guild{members = NewMb, boss = NewBoss,
                                   flag = 1},
            guild:cast(NewMb, 11110, {1, Nr}),
            guild:sync_cache(NewState),
            {ok, {ok, Nr, NewBoss}, NewState};
        _ -> {ok, {false, lang:get("不是该公会的会员，不能捐献")}}
    end;
sync_apply(State = #guild{boss =
                              Boss = #guild_boss{last_renamed = Last},
                          members = Members},
           {rename, RoleId, NewName}) ->
    case lists:keyfind(RoleId, #guild_role.id, Members) of
        #guild_role{post = 60} ->
            Now = date:unixtime(),
            case date:is_same_week(Last, Now) of
                true -> {ok, {false, lang:get("本周已经给神兽改过名了")}};
                _ ->
                    NewState = State#guild{boss =
                                               Boss#guild_boss{name = NewName,
                                                               last_renamed =
                                                                   Now},
                                           flag = 1},
                    guild:sync_cache(NewState),
                    {ok, ok, NewState}
            end;
        _ -> {ok, {false, lang:get("只有会长可以改名")}}
    end;
sync_apply(Guild = #guild{boss =
                              Boss = #guild_boss{called = Unbaned, lev = Lev},
                          map_id = MapId},
           {callout, RoleId, RoleName}) ->
    Now = date:unixtime(),
    case date:is_same_day(Now, Unbaned) of
        true -> {ok, {false, lang:get("今天已经解封过圣兽了，明天再来吧")}};
        _ ->
            case guild_data:get_boss(Lev) of
                #{id := UnitId} ->
                    case unit_data:get_attr(UnitId, 50) of
                        #attr{hp_max = HpMax} ->
                            BattleId = erlang:get(guild_boss_battle_id),
                            unit_mgr:create(BattleId,
                                            UnitId,
                                            {MapId, 2369, 959}),
                            NewGuild = Guild#guild{boss =
                                                       Boss#guild_boss{unit_id =
                                                                           UnitId,
                                                                       called =
                                                                           Now,
                                                                       hp =
                                                                           HpMax,
                                                                       hp_max =
                                                                           HpMax}},
                            Msg =
                                notice:format(lang:get("~ts打开~ts神兽封印，~ts神兽已出现在公会领地，大家请速去前往协助击杀！"),
                                              [{role_1, RoleId, RoleName},
                                               {unit_1, UnitId},
                                               {unit_1, UnitId}]),
                            guild:notice(self(), Msg),
                            {ok, ok, NewGuild};
                        _ -> {ok, {false, lang:get("找不到神兽")}}
                    end;
                _ -> {ok, {false, lang:get("1级以上的神兽才能被召唤出来")}}
            end
    end.

update_boss(Boss = #guild_boss{exp = Exp, lev = Lev}) ->
    NewLev = Lev + 1,
    case guild_data:get_boss(NewLev) of
        #{max_exp := MaxExp, step := Step} when MaxExp =< Exp ->
            update_boss(Boss#guild_boss{lev = NewLev, step = Step});
        _ -> Boss
    end.

