click_over(TRole = #role{lev = Lev,
                         m_trial =
                             Mtrial = #m_trial{coin = AllCoin, mode = Mode,
                                               is_helped = IsHelped}},
           Order) ->
    CampList = camp_assets:get(TRole, 3, 1),
    Role = camp_assets:acc(TRole, 3),
    Coin1 = calc_coin(Order, Mode, Lev),
    ValueAdd = case
                   buff:is_special_effect_exists_one_param(Role, 8)
                   of
                   {true, Value} -> Value;
                   _ -> 0
               end,
    Coin2 = util:ceil(Coin1 * (1000 + ValueAdd) / 1000),
    Minus = case IsHelped of
                "" -> 0;
                _ -> round(Coin2 * 2.99999999999999988898e-1)
            end,
    Coin = max(0, Coin2 - Minus),
    Gain = case Order < 7 of
               true ->
                   format:val_to_gain([{90000, Coin}, {90021, 2}] ++
                                          CampList);
               false -> format:val_to_gain([{90000, Coin}] ++ CampList)
           end,
    NewMtrial = Mtrial#m_trial{coin = AllCoin + Coin,
                               is_helped = ""},
    Role1 = Role#role{m_trial = NewMtrial},
    Role2 = item_gain(Role1, Order),
    case role_gain:do_notice(Gain, Role2) of
        {ok, NewRole} ->
            case IsHelped of
                "" -> ok;
                _ ->
                    Msg = notice:format(lang:get("~ts分到~ts作为酬劳！"),
                                        [{role_2, IsHelped},
                                         {assets_1, 90000, Minus}]),
                    notice:send(Role, 3, Msg)
            end,
            NewRole1 = role_trigger:fire(#evt_trial{mode = Mode},
                                         NewRole),
            accept_next(NewRole1);
        {false, _} ->
            logger:error("无法找到试炼[~w]的奖励数据", [Order], trial, 691),
            accept_next(Role2)
    end.

