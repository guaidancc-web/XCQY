convert_field(Guild, []) -> Guild;
convert_field(Guild, [C | T]) ->
    case convert_field(C, Guild) of
        {false, Reason} -> {false, Reason};
        {ok, NewGuild} -> convert_field(NewGuild, T)
    end;
convert_field(members,
              Guild = #guild{members = Members}) ->
    case convert_members(Members) of
        {false, Reason} -> {false, Reason};
        {ok, NewMembers} ->
            {ok, Guild#guild{members = NewMembers}}
    end;
convert_field(loot, Guild = #guild{loot = Loot}) ->
    case convert_loot(Loot) of
        {false, Reason} -> {false, Reason};
        {ok, NewLoot} -> {ok, Guild#guild{loot = NewLoot}}
    end;
convert_field(apply,
              Guild = #guild{apply_list = Applys}) ->
    case convert_apply(Applys) of
        {false, Reason} -> {false, Reason};
        {ok, NewApplys} ->
            {ok, Guild#guild{apply_list = NewApplys}}
    end;
convert_field(guild_treasure,
              Guild = #guild{treasure = Treasure}) ->
    case convert_treasure(Treasure) of
        {false, Reason} -> {false, Reason};
        {ok, NewTreasure} ->
            {ok, Guild#guild{treasure = NewTreasure}}
    end;
convert_field(C, _Guild) ->
    {false, util:flist("未知公会转换项:~w", [C])}.

