                     [HonorId | _] -> HonorId;
                     _ -> 0
                 end,
    case HonorIdNow =/= 0 of
        true ->
            HonorIds2 = [HonorIdNow | lists:delete(HonorIdNow,
                                                   HonorIds)],
            {HonorIdNow,
             HonorIds2,
             Role#role{m_wedding =
                           Wedding#m_wedding{honor_ids = HonorIds2}}};
        _ -> {HonorIdNow, HonorIds, Role}
    end.

