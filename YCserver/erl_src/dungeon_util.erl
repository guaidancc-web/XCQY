get_gain_list(Role, DunId) ->
    case dungeon_data:get_gain(DunId) of
        {{Nums}, List} ->
            NewList = check_role_cond(Role, List),
            Len = length(NewList),
            case Nums >= Len of
                true -> {true, Len, NewList};
                false -> {true, Nums, NewList}
            end;
        _ -> false
    end.

random_gain_list(Nums, List) ->
    {Normal, RandomList} = lists:partition(fun (#{ratio :=
                                                      Ratio}) ->
                                                   Ratio =:= 0
                                           end,
                                           List),
    Len = length(Normal),
    AllRatio = lists:sum([Ratio
                          || #{ratio := Ratio} <- RandomList]),
    random_gain_list(RandomList, AllRatio, Nums - Len, [])
        ++ Normal.

random_gain_list(_, _, 0, GetList) -> GetList;
random_gain_list([], _, _, GetList) -> GetList;
random_gain_list(List, Rate, Num, GetList) ->
    Seed = util:rand(1, Rate),
    case do_random_gain_item(List, Seed, Rate) of
        {NewList, GetI, NewRate} ->
            random_gain_list(NewList,
                             NewRate,
                             Num - 1,
                             [GetI | GetList]);
        false -> random_gain_list(List, Rate, Num - 1, GetList)
    end.

do_random_gain_item(List, Seed, Rate) ->
    do_random_gain_item(List, Seed, Rate, []).

do_random_gain_item([], _Seed, _Rate, _Back) ->
    logger:error("副本奖励发生错误，副本奖励内容为:~w",
                 [_Back],
                 dungeon_util,
                 759),
    false;
do_random_gain_item([H = #{ratio := Ratio} | T], Seed,
                    Rate, Back) ->
    case Seed =< Ratio of
        true -> {T ++ Back, H, Ratio - Ratio};
        false ->
            do_random_gain_item(T, Seed - Ratio, Rate, [H | Back])
    end.

check_role_cond(#role{sex = Sex, classes = Classes,
                      lev = Lev},
                List) ->
    [Gi
     || Gi = #{sex := Sex1, lev_high := LevHigh1,
               lev_low := LevLow1, classes := Classes1}
            <- List,
        Sex1 =:= Sex orelse Sex1 =:= 2,
        Classes1 =:= Classes orelse Classes1 =:= 0,
        LevLow1 =:= 0 andalso LevHigh1 =:= 0 orelse
            LevLow1 =:= 0 andalso Lev =< LevHigh1 orelse
                Lev >= LevLow1 andalso LevHigh1 =:= 0 orelse
                    Lev >= LevLow1 andalso Lev =< LevHigh1].

calc_buff_double(Role, Key, Rewards) ->
    case Key =:= 100 of
        true ->
            case buff:is_special_effect_exists_two_param(Role, 5) of
                {true, Value, Type} ->
                    case Type of
                        1 ->
                            logger:debug("运势buff作用下，物品道具~w几率翻倍",
                                         [Value div 10],
                                         dungeon_util,
                                         786),
                            case util:rand(0, 1000) < Value of
                                true -> double_item_rewards(Rewards);
                                false -> Rewards
                            end;
                        2 ->
                            logger:debug("运势buff的作用下,经验加成了~w%",
                                         [Value div 10],
                                         dungeon_util,
                                         794),
                            calc_pray_buff_exp(Rewards, Value)
                    end;
                _ -> Rewards
            end;
        false -> Rewards
    end.

double_item_rewards(Rewards) ->
    double_item_rewards(Rewards, []).

double_item_rewards([], NewRewards) -> NewRewards;
double_item_rewards([Gain = #gain{label = item_base_id,
                                  val = ItemList}
                     | T],
                    NewRewards) ->
    ItemList1 = double_item_rewars_list(ItemList),
    double_item_rewards(T,
                        [Gain#gain{val = ItemList1} | NewRewards]);
double_item_rewards([Reward | T], NewRewards) ->
    double_item_rewards(T, [Reward | NewRewards]).

double_item_rewars_list(ItemList) ->
    double_item_rewars_list(ItemList, []).

double_item_rewars_list([], DoubleCountItemList) ->
    DoubleCountItemList;
double_item_rewars_list([{ItemId, Bind, Count} | T],
                        DoubleCountItemList) ->
    double_item_rewars_list(T,
                            [{ItemId, Bind, Count * 2} | DoubleCountItemList]);
double_item_rewars_list([GainItem | T],
                        DoubleCountItemList) ->
    double_item_rewars_list(T,
                            [GainItem | DoubleCountItemList]).

calc_pray_buff_exp(Rewards, AddPrecent) ->
    calc_pray_buff_exp(Rewards, AddPrecent, []).

calc_pray_buff_exp([], _AddPrecent, NewRewards) ->
    NewRewards;
calc_pray_buff_exp([Gain = #gain{label = exp, val = Val}
                    | Rest],
                   AddPrecent, NewRewards) ->
    NewVal = util:ceil(Val * (1000 + AddPrecent) / 1000),
    logger:debug("在运势BUFF作用下, 副本的经验增加了, 增加前:~w, 增加后:~w",
                 [Val, NewVal],
                 dungeon_util,
                 830),
    calc_pray_buff_exp(Rest,
                       AddPrecent,
                       [Gain#gain{val = NewVal} | NewRewards]);
calc_pray_buff_exp([Rw | Rest], AddPrecent,
                   NewRewards) ->
    calc_pray_buff_exp(Rest, AddPrecent, [Rw | NewRewards]).

