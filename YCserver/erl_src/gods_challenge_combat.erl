next_wave(#combat{type = Type}) ->
    Wave = get(gods_challenge_wave),
    NextWave = Wave + 1,
    case NextWave of
        2 ->
            TeamName1 = case env:get(challengename) of
                            undefined -> lang:get("神秘战队");
                            _TeamName1 -> _TeamName1
                        end,
            Msg1 =
                notice:format(lang:get("<color='#00ff00'>~ts</color>队伍气势如虹，在全服玩家的见证下，"
                                       "成功完成对龙神·法涅斯的挑战，正在向复苏女神·迪凯娥斯涅大步迈进"),
                              [{string_1, TeamName1}]),
            big_world:cast(all, notice, cast, [all, 11, Msg1]),
            big_world:cast(all, notice, cast, [all, 4, Msg1]),
            ok;
        3 ->
            TeamName2 = case env:get(challengename) of
                            undefined -> lang:get("神秘战队");
                            _TeamName2 -> _TeamName2
                        end,
            Msg2 =
                notice:format(lang:get("<color='#00ff00'>~ts</color>队伍气势如虹，在全服玩家的见证下，"
                                       "成功完成对复苏女神·迪凯娥斯涅的挑战，正在向众神之主·柯罗诺斯大步迈进"),
                              [{string_1, TeamName2}]),
            big_world:cast(all, notice, cast, [all, 11, Msg2]),
            big_world:cast(all, notice, cast, [all, 4, Msg2]),
            ok;
        _ -> ok
    end,
    put(gods_challenge_wave, NextWave),
    gods_challenge_mgr:info({update_challenge_wave,
                             NextWave}),
    case gods_challenge_data:get_wave_info(NextWave) of
        #{unit_id := UnitBaseId}
            when is_integer(UnitBaseId) andalso UnitBaseId > 0 ->
            UnitBaseIds = case unit_data:get(UnitBaseId) of
                              #unit_data{slave = Slave} ->
                                  Slaves = gen_slave(Slave, []),
                                  [{unit_baseid, UnitBaseId} | Slaves];
                              _ -> [{unit_baseid, UnitBaseId}]
                          end,
            combat:add_next_wave(Type, UnitBaseIds, 1),
            true;
        _ ->
            logger:debug("查找不到下一波怪:~w",
                         [NextWave],
                         gods_challenge_combat,
                         66),
            false
    end.

