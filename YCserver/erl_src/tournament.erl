combat_over(#combat{winner = Winner, type = CombatType,
                    loser = Loser,
                    start_args = #combat_start_args{ext_args = ExtArgs},
                    round = Round}) ->
    WinnerF = [F
               || F = #fighter{type = Ftype} <- Winner,
                  Ftype == 1 orelse Ftype == 5],
    LoserF = [F
              || F = #fighter{type = Ftype} <- Loser,
                 Ftype == 1 orelse Ftype == 5],
    MatchId = case CombatType of
                  58 ->
                      {TMatchId, _, _} = ExtArgs,
                      TMatchId;
                  _ -> ExtArgs
              end,
    PZ = cast_record(#{round => Round, winner => WinnerF,
                       loser => LoserF, record => combat_record:get_buffer(),
                       match_id => MatchId}),
    PkType = case CombatType of
                 58 -> 2;
                 _ -> 1
             end,
    tournament !
        {combat_over,
         #{winner => WinnerF, combat_type => CombatType,
           loser => LoserF, pk_type => PkType, match_id => MatchId,
           round => Round, record_pz => PZ}};
combat_over(_) -> skip.

combat_fail(#combat{start_args =
                        #combat_start_args{ext_args = ExtArgs}},
            AtkList, DfdList) ->
    AtkListI = [I
                || #fighter{origin_id = I, type = 1} <- AtkList],
    DfdListI = [I
                || I = #fighter{origin_id = I, type = 1} <- DfdList],
    tournament ! {combat_fail, AtkListI, DfdListI, ExtArgs};
combat_fail(_, _, _) -> skip.

