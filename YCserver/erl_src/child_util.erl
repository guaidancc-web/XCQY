get_look(#child{base_id = BaseId, grade = Grade,
                child_skin = ChildSkin}) ->
    {Model, Skin} = case child_data:get_base(BaseId) of
                        #child_base{skin_id_0 = SkinId0, model_id = Model0}
                            when Grade =:= 0 ->
                            {Model0, SkinId0};
                        #child_base{skin_id_1 = SkinId1, model_id1 = Model1}
                            when Grade =:= 1 ->
                            {Model1, SkinId1};
                        #child_base{skin_id_2 = SkinId2, model_id2 = Model2}
                            when Grade =:= 2 ->
                            {Model2, SkinId2};
                        #child_base{skin_id_3 = SkinId3, model_id3 = Model3}
                            when Grade =:= 3 ->
                            {Model3, SkinId3};
                        _ -> {0, 0}
                    end,
    UseSkinId = case child_skin:get_use_skin(ChildSkin) of
                    #child_skin{skin_id = SkinId} -> SkinId;
                    _ -> Skin
                end,
    case UseSkinId =:= Skin of
        true -> [{51, Model, Skin, ""}];
        _ ->
            case child_data:get_skin(UseSkinId) of
                #{texture := Texture, model_id := ModelId,
                  animation_id := AnimationId} ->
                    [{51, ModelId, Texture, ""}, {77, 0, AnimationId, ""}];
                _ -> [{51, Model, Skin, ""}]
            end
    end.

