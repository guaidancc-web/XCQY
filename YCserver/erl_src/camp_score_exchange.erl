                                #assets{score_exchange = OldVal}})
    when OldVal > 0 ->
    case catch camp_score_exchange_data:get_other_info() of
        [{ReVal, Title, Content, _}] ->
            NewVal = ReVal * OldVal,
            Loss = format:val_to_loss([{90066, OldVal}]),
            role:send_buff_begin(),
            case role_gain:do_notice(Loss, Role) of
                {false, #loss{msg = Msg}} ->
                    role:send_buff_clean(),
                    logger:error("=============~w",
                                 [Msg],
                                 camp_score_exchange,
                                 290),
                    {ok, Role};
                {ok, Role2} ->
                    role:send_buff_flush(),
                    logger:debug("=============",
                                 [],
                                 camp_score_exchange,
                                 294),
                    mail:send(Role2,
                              #{title => Title, content => Content,
                                items => [{90000, NewVal}]}),
                    {ok, Role2};
