match_rival(Role = #role{lev = Lev}, Mode, Order,
            HasMatch) ->
    case trial_data:get(Order) of
        #{type := 2} -> box;
        #{lev_low := LevLow, lev_high := LevHigh,
          fc_list := FcList, easy_attr_ratio := EasyAttrRatio,
          hard_attr_ratio := HardAttrRatio} ->
            AttrRatio = case Mode of
                            1 -> EasyAttrRatio;
                            _ -> HardAttrRatio
                        end,
            MinLev = util:check_range(LevLow + Lev, 30, 120),
            MaxLev = util:check_range(LevHigh + Lev, 30, 120),
            UnitClasses = util:rand_list([1, 2, 3, 4, 5, 6, 7]),
            UnitArgs = #{classes => UnitClasses,
                         sex => util:rand(0, 1), lev => MinLev,
                         attr_ratio => AttrRatio},
            LevList = lists:reverse(lists:seq(MinLev, MaxLev)),
            case robot:match(trial,
                             {Role, LevList, FcList, HasMatch})
                of
                {true, GetRoleId} ->
                    case robot_mgr:get_role(GetRoleId) of
                        {ok, R} -> ratio_robot(R, UnitArgs);
                        _ -> {self_clone, UnitArgs}
                    end;
                false -> {self_clone, UnitArgs}
            end;
        _ -> box
    end.

ratio_robot(R = #robot_role{attr =
                                Attr = #attr{hp_max = HpMax},
                            pet = Pet, guard = Guard},
            #{attr_ratio := AttrRatio}) ->
    NewHpMax = round(HpMax * AttrRatio / 1000),
    NewAttr = Attr#attr{hp_max = NewHpMax},
    NewPet = ratio_robot_pet(Pet, AttrRatio),
    NewGuard = ratio_robot_guard(Guard, AttrRatio),
    R#robot_role{attr = NewAttr, pet = NewPet,
                 guard = NewGuard}.

ratio_robot_pet(Pet = #c_pet{attr =
                                 Attr = #attr{hp_max = HpMax}},
                AttrRatio) ->
    NewHpMax = round(HpMax * AttrRatio / 1000),
    NewAttr = Attr#attr{hp_max = NewHpMax},
    Pet#c_pet{attr = NewAttr};
ratio_robot_pet(Pet, _) -> Pet.

ratio_robot_guard(GuardList, AttrRatio) ->
    ratio_robot_guard(GuardList, AttrRatio, []).

ratio_robot_guard([], _, GuardList) -> GuardList;
ratio_robot_guard([Guard = #c_guard{attr =
                                        Attr = #attr{hp_max = HpMax}}
                   | T],
                  AttrRatio, GuardList) ->
    NewHpMax = round(HpMax * AttrRatio / 1000),
    NewAttr = Attr#attr{hp_max = NewHpMax},
    Guard1 = Guard#c_guard{attr = NewAttr},
    ratio_robot_guard(T, AttrRatio, [Guard1 | GuardList]);
ratio_robot_guard([_ | T], AttrRatio, GuardList) ->
    ratio_robot_guard(T, AttrRatio, GuardList).

