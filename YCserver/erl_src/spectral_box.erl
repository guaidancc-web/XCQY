get_timeout() ->
    {_, {Hour, Minute, _}} =
        date:seconds_to_datetime(date:unixtime()),
    case Hour >= 0 andalso Hour =< 23 of
        true when Minute < 30 -> date:next_diff(Hour, 30, 0);
        true when Hour < 23 -> date:next_diff(Hour + 1, 0, 0);
        _ -> date:next_diff(0, 0, 0)
    end.

