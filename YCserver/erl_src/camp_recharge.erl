get_camp() ->
    case campaign_mgr:get_camp_info(60035) of
        #camp_cache{id = Id, start_time = St, end_time = ET} ->
            {Id, St, ET};
        _ -> {0, -1, -1}
    end.

check_camp() ->
    Now = date:unixtime(),
    {_, StartTime, EndTime} = get_camp(),
    if Now < StartTime -> 0;
       Now >= StartTime andalso Now < EndTime -> 1;
       true -> 0
    end.

get_days_camp_recharge(#role{m_camp_recharge =
                                 #m_camp_recharge{recharges = Recharges}},
                       Days) ->
    {CampID, _, _} = get_camp(),
    case lists_ext:multikeyfind([{Days,
                                  #camp_recharge.days},
                                 {CampID, #camp_recharge.camp_id}],
                                Recharges)
        of
        Recharge = #camp_recharge{} -> Recharge;
        _ -> #camp_recharge{days = Days, camp_id = CampID}
    end.

get_cur_camp_recharge(Role) ->
    {_, StartTime, _} = get_camp(),
    CurDays = date:day_diff(StartTime, date:unixtime()) + 1,
    get_days_camp_recharge(Role, CurDays).

