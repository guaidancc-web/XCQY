                               {unit_1, BaseId},
                               {string_2, 5, Add}])),
    Gain = format:val_to_gain(ExpList),
    case role_gain:do_notice(Gain, Role) of
        {ok, NRole} -> {ok, NRole};
        _ -> {ok, Role}
    end;
