get_extra() ->
    Score = case get(dungeon_shipping_score) of
                SVal when is_integer(SVal) -> SVal;
                _ -> 0
            end,
    CountDonw1 = case get({global, count_down}) of
                     CVal when is_integer(CVal) -> CVal;
                     _ -> 0
                 end,
    CountDonw2 = case get({global, count_down2}) of
                     CVal2 when is_integer(CVal2) -> CVal2;
                     _ -> 0
                 end,
    BoxIds = [73250, 73251],
    BoxList = [{3, BoxId, get_box_num(BoxId), "", ""}
               || BoxId <- BoxIds],
    [{1, 1, CountDonw1, "", ""},
     {1, 2, CountDonw2, "", ""},
     {2, Score, 0, "", ""}]
        ++ BoxList.

pick_box(#battle{role_id = BattleRoleId}, Pid, _Name,
         BaseId) ->
    Add = get_box_score(BaseId),
    Score = case get_score() of
                SVal when is_integer(SVal) -> SVal;
                _ -> 0
            end,
    put(dungeon_shipping_score, Score + Add),
    Box = get_box_num(BaseId),
    notice:send({pid, Pid},
                1,
                notice:format(lang:get("获得~ts个神秘雕像"),
                              [{string_2, 5, Add}])),
    role:apply(async,
               Pid,
               {dungeon_shipping,
                pick_box_apply,
                [BattleRoleId, BaseId, Add]}),
    put({dungeon_shipping_box, BaseId}, Box + 1).

