handle_call({create_one, MapId, BaseId}, _From,
            State = #state{boxes = OldBoxesList}) ->
    Res = case erlang:get(spectral_box_map_list) of
              MapL = [_ | _] ->
                  case lists:keyfind({MapId, BaseId}, 2, MapL) of
                      {UId, _} -> {ok, UId};
                      _ -> do_create_one(MapId, BaseId)
                  end;
              _ -> do_create_one(MapId, BaseId)
          end,
    case Res of
        {ok, UnitId} -> {reply, {ok, UnitId}, State};
        {ok, UnitId, {X, Y}} ->
            {reply,
             {ok, X, Y},
             State#state{boxes = [UnitId | OldBoxesList]}};
        _ -> {reply, Res, State}
    end;
