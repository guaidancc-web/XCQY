          Args = #{lev := Lev, sex := RSex, classes := RClasses,
                   day := Day, buy_list := BuyList}) ->
    {Type, Times} = lists:keyfind(Type, 1, BuyList),
    NRtn = case camp_bring_up_open_data:get_gift({Day,
                                                  Type})
               of
               #{need_val := NeedVal, times := AT, reward := Reward,
                 add_val := AddVal, title := Title, desc := Desc} ->
                   NReward = lists:foldl(fun ({ItemId, Bind, Num}, Acc) ->
                                                 [{ItemId, Bind, Num, 0} | Acc];
                                             ({ItemId,
                                               Bind,
                                               Num,
                                               LevMin,
                                               LevMax},
                                              Acc)
                                                 when LevMin =< Lev andalso
                                                          Lev =< LevMax ->
                                                 [{ItemId, Bind, Num, 0} | Acc];
                                             ({ItemId,
                                               Bind,
                                               Num,
                                               LevMin,
                                               LevMax,
                                               Sex,
                                               ClientEffect},
                                              Acc)
                                                 when LevMin =< Lev andalso
                                                          Lev =< LevMax andalso
                                                              (Sex =:= RSex
                                                                   orelse
                                                                   Sex =:= 2) ->
                                                 [{ItemId,
                                                   Bind,
                                                   Num,
                                                   ClientEffect}
                                                  | Acc];
                                             ({ItemId,
                                               Bind,
                                               Num,
                                               LevMin,
                                               LevMax,
                                               Sex,
                                               Classes,
                                               ClientEffect},
                                              Acc)
                                                 when LevMin =< Lev andalso
                                                          Lev =< LevMax andalso
                                                              (Sex =:= RSex
                                                                   orelse
                                                                   Sex =:= 2)
                                                                  andalso
                                                                  (Classes =:=
                                                                       RClasses
                                                                       orelse
                                                                       Classes
                                                                           =:=
                                                                           0) ->
                                                 [{ItemId,
                                                   Bind,
                                                   Num,
                                                   ClientEffect}
                                                  | Acc];
                                             (_, Acc) -> Acc
                                         end,
                                         [],
                                         Reward),
                   [{Type,
                     NeedVal,
                     AT - Times,
                     NReward,
                     AddVal,
                     Title,
                     Desc}
                    | Rtn];
               _ -> Rtn
           end,
    make_data(Type - 1, NRtn, Args).

make_bring_info(BringLev) ->
    AllInfo = camp_bring_up_open_data:list_bring_info(),
    Info = [{GoalPoint, Pic}
            || {Lev, GoalPoint, Pic} <- AllInfo, Lev =:= BringLev],
    LevupPoint = case
                     camp_bring_up_open_data:get_bring_gift(BringLev)
                     of
                     {_, _LevupPoint, _, _} -> _LevupPoint;
                     _ -> 200
                 end,
    {Info, LevupPoint}.

make_bring_gift() ->
    AllLev = camp_bring_up_open_data:list_bring_lev(),
    [begin
         {Lev, _LevupPoint, GiftType, [{ItemId, _Bind, Num}]} =
             camp_bring_up_open_data:get_bring_gift(Lev),
         {Lev, GiftType, ItemId, Num}
     end
     || Lev <- AllLev].

get_already_buy(Role, Day, Type) ->
    TimesL = var:get_var(Role, other, 2144, []),
    case lists:keyfind(Day, 1, TimesL) of
        {Day, Times} ->
            case lists:keyfind(Type, 1, Times) of
                {Type, Num} -> Num;
                _ -> 0
            end;
        _ -> 0
    end.

