acc_unit_rewards(Rewards,
                 Role = #role{m_dungeon =
                                  Mdun = #m_dungeon{dun_id = DunId,
                                                    unit_rewards = L}}) ->
    Rewards1 = format:gain_to_val(Rewards),
    logger:debug("奖励 ~w", [Rewards1], dungeon_util, 223),
    NL = do_acc_unit_rewards(Rewards1, L),
    Role1 = Role#role{m_dungeon =
                          Mdun#m_dungeon{unit_rewards = NL}},
    case L of
        [] ->
            Role2 = update_pass(Role1, DunId),
            role_trigger:fire(#evt_dungeon_unit_reward{id = DunId},
                              Role2);
        _ -> Role1
    end.

do_acc_unit_rewards([], L) -> L;
do_acc_unit_rewards([{I, _, N} | T], L) ->
    case lists:keyfind(I, 1, L) of
        {I, V} ->
            do_acc_unit_rewards(T,
                                lists:keyreplace(I, 1, L, {I, V + N}));
        _ -> do_acc_unit_rewards(T, [{I, N} | L])
    end;
do_acc_unit_rewards([{I, N} | T], L) ->
    case lists:keyfind(I, 1, L) of
        {I, V} ->
            do_acc_unit_rewards(T,
                                lists:keyreplace(I, 1, L, {I, V + N}));
        _ -> do_acc_unit_rewards(T, [{I, N} | L])
    end.

calc_gain(Role = #role{lev = RoleLev}, DunId) ->
    GetGainMap = case get_gain_list(Role, DunId) of
                     {true, 0, _} -> [];
                     {true, Nums, List} -> random_gain_list(Nums, List);
                     _ -> []
                 end,
    Fun = fun (#{item_id := 90010, num := [Num]},
               GetGain) ->
                  case levup_data:get_exp({Num, RoleLev}) of
                      #{exp := Exp} -> [{90010, Exp} | GetGain];
                      _ -> GetGain
                  end;
              (#{item_id := 90000, num := [Num]}, GetGain) ->
                  case levup_data:get_exp({Num, RoleLev}) of
                      #{coin := Coin} -> [{90000, Coin} | GetGain];
                      _ -> GetGain
                  end;
              (#{item_id := 90005, num := [Num]}, GetGain) ->
                  case levup_data:get_exp({Num, RoleLev}) of
                      #{pet_exp := PetExp} -> [{90005, PetExp} | GetGain];
                      _ -> GetGain
                  end;
              (#{item_id := ItemId, num := Num}, GetGain) ->
                  GetNum = case Num of
                               [Int] when is_integer(Int) -> Int;
                               [_ | _] ->
                                   {GetN, _} = util:rand_list(Num, 2),
                                   GetN;
                               _ -> 1
                           end,
                  [{ItemId, 0, GetNum} | GetGain]
          end,
    lists:foldl(Fun, [], GetGainMap).

team_check(enter, Role = #role{}) ->
    case team:get_status(Role) of
        {true, 1} ->
            case team:get_members(Role) of
                [] -> {true, []};
                TeamList = [_ | _] ->
                    case [M
                          || M = #team_mate{status = Status} <- TeamList,
                             Status =/= 2]
                        of
                        [] -> {true, TeamList};
                        _ -> false
                    end;
                _ -> false
            end;
        {true, _} -> false;
        false -> {true, []}
    end;
