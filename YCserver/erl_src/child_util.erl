find_child(_Role = #role{id = RoleId,
                         m_child = #m_child{kids = Kids}},
           ChildId, StageList) ->
    case lists:keyfind(ChildId, #child.id, Kids) of
        Child = #child{status = 1, stage = Stage,
                       follow = RoleId} ->
            case lists:member(Stage, StageList) of
                true -> {true, Child};
                false -> {false, lang:get("当前成长阶段不可进行此操作")}
            end;
        #child{} -> {false, lang:get("跟随后才能进行该操作")};
        _ -> {false, lang:get("找不到孩子")}
    end.

update_child(#role{id = RoleId},
             Child = #child{id = ChildId}) ->
    case child:fetch(ChildId) of
        [#child{status = 1, follow = RoleId}] ->
            child:update(Child),
            child_rank:in(Child),
            true;
        _ -> {false, lang:get("跟随后才能操作")}
    end.

notice_code(RoleId, #child{custody = {Id1, Id2}}, Code,
            Data) ->
    case RoleId =:= Id1 of
        true -> role:pack_send(Id2, Code, Data);
        false -> role:pack_send(Id1, Code, Data)
    end;
notice_code(_, _, _, _) -> ok.

