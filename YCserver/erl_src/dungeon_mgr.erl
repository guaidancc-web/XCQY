handle_call({role_login, RoleId}, _From,
            State = #state{off_list = OffList}) ->
    case lists:keyfind(RoleId, 1, OffList) of
        {_, DunId, BattleId, BattlePid}
            when is_pid(BattlePid) ->
            NewOffList = lists:keydelete(RoleId, 1, OffList),
            NewState = State#state{off_list = NewOffList},
            {reply, {ok, DunId, BattleId, BattlePid}, NewState};
        _ -> {reply, false, State}
    end;
handle_call(_Request, _From, State) -> {noreply, State}.

handle_cast({start, BattleId, Pid},
