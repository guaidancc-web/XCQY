family_delete([Id | T], FChild) ->
    family:delete_child(Id, FChild),
    family_delete(T, FChild).

to_family_child(#child{stage = Stage = 2, id = Id,
                       name = Name, sex = Sex, classes = Classes, lev = Lev,
                       base_id = BaseId}) ->
    UnitBase = case Sex of
                   0 -> 71160;
                   _ -> 71159
               end,
    #family_child{id = Id, name = Name, sex = Sex,
                  classes = Classes, lev = Lev, unit_base_id = UnitBase,
                  stage = Stage, base_id = BaseId};
to_family_child(#child{stage = Stage, id = Id,
                       base_id = BaseId, grade = Grade, name = Name, sex = Sex,
                       classes = Classes, lev = Lev}) ->
    UnitBase1 = case Sex of
                    0 -> 71160;
                    _ -> 71159
                end,
    UnitBase2 = case child_data:get_base(BaseId) of
                    #child_base{unit_id_3 = Skin} when Grade >= 3 -> Skin;
                    #child_base{unit_id_2 = Skin} when Grade >= 2 -> Skin;
                    #child_base{unit_id_1 = Skin} when Grade >= 1 -> Skin;
                    #child_base{unit_id = Skin} -> Skin;
                    _Else ->
                        logger:debug("找不到配置 ~w, ~w",
                                     [BaseId, _Else],
                                     child_util,
                                     368),
                        UnitBase1
                end,
    #family_child{id = Id, name = Name, sex = Sex,
                  classes = Classes, lev = Lev, unit_base_id = UnitBase2,
                  stage = Stage, base_id = BaseId}.

