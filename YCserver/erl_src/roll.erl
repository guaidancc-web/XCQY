fairyland_box(UnitId, RoleList) ->
    case roll_data:get({3, UnitId}) of
        {#{timeout := TimeOut}, ItemList} ->
            {WorldLev, _} = world_lev:get_world_lev(),
            NewItemList = [RandItem
                           || RandItem = #{world_lev := Wl} <- ItemList,
                              WorldLev >= Wl],
            RollRoles = [to_roll_role(Role) || Role <- RoleList],
            roll_mgr:add_roll({3, UnitId},
                              TimeOut,
                              NewItemList,
                              RollRoles,
                              {roll_role, 41}),
            ok;
        _ ->
            logger:error("队伍宝箱roll点无法找到roll点数据:~w",
                         [UnitId],
                         roll,
                         90),
            ok
    end.

team_roll_check(Role, PickArgs) ->
    case team:get_status(Role) of
        {true, 1} ->
            case team:get_members(Role) of
                TeamList when length(TeamList) >= 2 ->
                    {true,
                     maps:put(team_roll_list, [Role | TeamList], PickArgs)};
                _ -> {false, lang:get("三人以上合力方可开启")}
            end;
        _ -> {false, lang:get("三人以上合力方可开启")}
    end.

to_roll_role(#battle_role{id = RoleId, name = RoleName,
                          pid = RolePid, sex = Sex, classes = Classes}) ->
    #roll_role{role_id = RoleId, name = RoleName,
               pid = RolePid, sex = Sex, classes = Classes};
to_roll_role(#role{id = RoleId, name = RoleName,
                   pid = RolePid, sex = Sex, classes = Classes,
                   m_team = MTeam}) ->
    TeamStatus = case MTeam of
                     #m_team{pid = TeamPid, status = St}
                         when is_pid(TeamPid) ->
                         St;
                     _ -> 0
                 end,
    #roll_role{role_id = RoleId, name = RoleName,
               pid = RolePid, sex = Sex, classes = Classes,
               team_status = TeamStatus};
to_roll_role(#team_mate{id = RoleId, name = RoleName,
                        pid = RolePid, sex = Sex, classes = Classes,
                        status = Status}) ->
    #roll_role{role_id = RoleId, name = RoleName,
               pid = RolePid, sex = Sex, classes = Classes,
               team_status = Status}.

