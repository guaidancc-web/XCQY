    CoinRatio = trial_data:get_coin_ratio(Order),
    ModeRatio = case Mode of
                    1 -> 1;
                    _ -> 1.3
                end,
    round(52668 * (88 + 5.0e-1 * Lev) / 100 * CoinRatio /
              1000
              * ModeRatio).

