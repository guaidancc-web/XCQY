-spec start_link(#map_grid{}) -> {ok, pid()}.

start_link(MapGrid) ->
    put(map_grid, MapGrid),
    {ok, 0}.

-spec stop(pid()) -> ok.

stop(_Pid) -> ok.

-spec enter(pid(), #map_role{}) -> ok.

enter(_Pid, R = #map_role{conn_pid = ConnPid}) ->
    sys_conn:pack_send(ConnPid, 10122, {[R]}),
    {ok, Bin} = proto_101:pack(srv, 10113, R),
    ConnPid ! {send_data, Bin},
    ok.

-spec move(pid(), pid(), non_neg_integer(),
           non_neg_integer(), non_neg_integer(), non_neg_integer(),
           non_neg_integer()) -> ok.

move(_Pid, _RolePid, _SrcX, _SrcY, _DestX, _DestY,
     _Dir) ->
    ok.

-spec transmit(pid(), pos_integer(), pos_integer(),
               pos_integer(), pid(), non_neg_integer(),
               non_neg_integer(), non_neg_integer(), non_neg_integer(),
               list(), list()) -> ok.

transmit(_Pid, _BaseId, Mode, Speed, RolePid, SrcX,
         SrcY, _DestX, _DestY, DestList, _Looks) ->
    #map_role{conn_pid = ConnPid, rid = Rid,
              platform = Platform, zone_id = ZoneId, dir = Dir} =
        get({role, RolePid}),
    {ok, Bin} = proto_101:pack(srv,
                               10118,
                               {Rid,
                                Platform,
                                ZoneId,
                                Mode,
                                Speed,
                                Dir,
                                SrcX,
                                SrcY,
                                DestList,
                                0,
                                0}),
    ConnPid ! {send_data, Bin},
    ok.

