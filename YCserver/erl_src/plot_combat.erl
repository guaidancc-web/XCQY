-spec handle(Evt :: tuple(), #fighter{}) -> #fighter{}.

handle(Evt,
       F = #fighter{plot =
                        {_, _, #m_plot{combat_list = DoL = [_ | _]}},
                    type = 1}) ->
    RoleNum = case Evt of
                  #evt_combat_init{self = SelfL, opp = OppL} ->
                      combat_util:count_f(SelfL ++ OppL,
                                          [{#fighter.type, 1}]);
                  #evt_combat_round{self = SelfL, opp = OppL} ->
                      combat_util:count_f(SelfL ++ OppL,
                                          [{#fighter.type, 1}]);
                  _ -> 1
              end,
    case RoleNum =:= 1 of
        true ->
            try do_match(DoL, Evt, F) of
                Result -> Result
            catch
                Type:Reason ->
                    logger:error("战斗中处理剧情出错[event:~w] [type:~w] [reason:w]",
                                 [Evt, Type, Reason],
                                 plot_combat,
                                 39),
                    F
            end;
        _ -> F
    end;
handle(_Evt, F) -> F.

-spec finish(#fighter{}) -> #fighter{}.

finish(F = #fighter{plot =
                        {Id,
                         _L,
                         MPlot = #m_plot{finished = FinL,
                                         combat_list = DoL}}}) ->
    case plot_data:get(Id) of
        #plot_trigger{num = MaxNum} ->
            case lists:keyfind(Id, #plot.id, DoL) of
                Plot = #plot{num = Num}
                    when MaxNum =:= 0 orelse Num + 1 < MaxNum ->
                    NewPlot = Plot#plot{num = Num + 1},
                    role:pack_send(F#fighter.pid, 11001, {}),
                    F#fighter{plot =
                                  {0,
                                   [],
                                   MPlot#m_plot{combat_list =
                                                    lists:keyreplace(Id,
                                                                     #plot.id,
                                                                     DoL,
                                                                     NewPlot)}}};
                _Plot = #plot{} ->
                    role:pack_send(F#fighter.pid, 11001, {}),
                    F#fighter{plot =
                                  {0,
                                   [],
                                   MPlot#m_plot{finished = [Id | FinL -- [Id]],
                                                combat_list =
                                                    lists:keydelete(Id,
                                                                    #plot.id,
                                                                    DoL)}}};
                _ -> F
            end;
        _ -> F
    end;
finish(F) -> F.

do_match([], _Evt, F) -> F;
do_match([#plot{id = Id, act_idx = 0} | T], Evt,
         F = #fighter{plot = {_, _, MPlot}}) ->
    case plot_data:get(Id) of
        #plot_trigger{vars = Vars, event = Evts,
                      condition = Conds, action = Acts} ->
            EvtLabel = element(1, Evt),
            case lists:keyfind(EvtLabel, 1, Evts) of
                false -> do_match(T, Evt, F);
                _ ->
                    case plot_cond:check(Conds, Evt, F) of
                        true ->
                            [put({plot_fun_var, Key}, Val)
                             || {Key, Val} <- Vars],
                            Acts0 = plot_fun:act_args(Acts),
                            NewActs = handle_act(Acts0, [], Evt, F),
                            F#fighter{plot = {Id, NewActs, MPlot}};
                        false -> do_match(T, Evt, F)
                    end
            end;
        _ -> do_match(T, Evt, F)
    end;
do_match([_ | T], Evt, F) -> do_match(T, Evt, F).

handle_act([], Acts, _Evt, _F) -> lists:reverse(Acts);
handle_act([{action, I} | T], Acts, Evt, F)
    when is_list(I) ->
    I0 = [handle_act_type(Act, Evt, F) || Act <- I],
    NewI = [Act0 || Act0 <- I0, Act0 =/= false],
    handle_act(T, [NewI | Acts], Evt, F);
handle_act([I | T], Acts, Evt, F) ->
    case handle_act_type(I, Evt, F) of
        false -> handle_act(T, Acts, Evt, F);
        Act -> handle_act(T, [[Act] | Acts], Evt, F)
    end.

handle_act_type(Act, _Evt, _F) -> Act.

