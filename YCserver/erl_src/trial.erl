            win, Round) ->
    MaxOrder = case Mode of
                   2 -> MaxOrderHard;
                   _ -> MaxOrderEasy
               end,
    CanJumpOrder = max(0, MaxOrder - 4),
    {JumpFlag, NewDirectOrder} = case Order =< CanJumpOrder
                                     of
                                     true ->
                                         case trial_data:jump(Order) of
                                             {MinRound, GetOrder, Msg}
                                                 when Round =< MinRound ->
                                                 notice:send(Role, 1, Msg),
                                                 {true, GetOrder};
                                             _ -> {false, DirectOrder}
                                         end;
                                     false -> {false, DirectOrder}
                                 end,
    NewMtrial = Mtrial#m_trial{round = AllRound + Round,
                               direct_order = NewDirectOrder},
    Role1 = case IsHelped of
                "" -> Role#role{m_trial = NewMtrial};
                _ ->
                    var:acc_var(Role#role{m_trial = NewMtrial},
                                day_five,
                                124)
            end,
    NewRole = case JumpFlag of
                  true ->
                      case buff:add(Role1, 20000) of
                          {ok, Role2} ->
                              Role3 = attr:calc_and_push(Role2),
                              map:role_update(Role3),
                              Role3;
                          _ -> Role1
                      end;
                  false -> Role1
              end,
    NewRole1 = item_gain(NewRole, Order),
    case accept_next(NewRole1) of
        {ok, NewRole2} -> NewRole2;
        _ -> NewRole1
    end;
