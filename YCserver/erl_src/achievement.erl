    case achievement_data:get(Id) of
        #quest_data{ach_num = Add} ->
            calc_point(T, Point + Add);
        _ -> calc_point(T, Point)
    end;
calc_point([{Id, _} | T], Point) ->
    case achievement_data:get(Id) of
        #quest_data{ach_num = Add} ->
            calc_point(T, Point + Add);
        _ -> calc_point(T, Point)
    end;
calc_point([_ | T], Point) -> calc_point(T, Point).

