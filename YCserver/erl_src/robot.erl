make_robot(trial,
           #{classes := Classes, sex := Sex, lev := Lev,
             attr_ratio := Ratio},
           _Role) ->
    AllClasses = [1, 2, 3, 4, 5],
    ClassesList = util:rand_list_n(AllClasses, 4),
    AllData = [{Ca, util:rand(0, 1)} || Ca <- ClassesList],
    AllData1 = [{Classes, Sex} | AllData],
    Fun = fun ({Rclasses, Rsex}, FighterList) ->
                  case robot_data:get({Lev, Rclasses}) of
                      #{attr := Attr = #attr{hp_max = HpMax},
                        skills := Skills} ->
                          AiId = role_misc:get_ai(Rclasses),
                          NewHpMax = round(HpMax * Ratio / 1000),
                          NewAttr = Attr#attr{hp_max = NewHpMax},
                          Name = lang:get("试炼官"),
                          Robot = #robot_role{id = {1, "robot", 0}, name = Name,
                                              sex = Rsex, classes = Rclasses,
                                              lev = Lev, skills = Skills,
                                              guard = [], attr = NewAttr,
                                              ai_id = AiId,
                                              time = date:unixtime()},
                          logger:debug("AiId:~w", [AiId], robot, 36),
                          [Robot | FighterList];
                      _ -> FighterList
                  end
          end,
    RobotList = lists:foldl(Fun, [], AllData1),
    case RobotList of
        [_ | _] -> {true, RobotList};
        _ ->
            logger:error("无法获取机器人数据Lev:~w, Data:~w",
                         [Lev, AllData1],
                         robot,
                         46),
            {false, lang:get("无法获取试炼属性")}
    end;
