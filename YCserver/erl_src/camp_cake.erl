get_idle_time() ->
    Now = date:unixtime(),
    {StartTime, EndTime} = case
                               campaign_mgr:get_camp_time(60010)
                               of
                               {-1, -1} ->
                                   {date:datetime_to_seconds({{2016, 3, 29},
                                                              {0, 0, 0}}),
                                    date:datetime_to_seconds({{2016, 4, 20},
                                                              {0, 0, 0}})};
                               {S, E} -> {S, E};
                               _ ->
                                   {date:datetime_to_seconds({{2016, 3, 29},
                                                              {0, 0, 0}}),
                                    date:datetime_to_seconds({{2016, 4, 20},
                                                              {0, 0, 0}})}
                           end,
    if Now < StartTime ->
           {999, idel, max((StartTime - Now) * 1000, 1)};
       Now >= StartTime andalso Now < EndTime ->
           TimeList = camp_cake_data:time_list(),
           {Id, NextTime, StateName} = get_idle_time(TimeList,
                                                     #{st => StartTime,
                                                       et => EndTime,
                                                       now => Now},
                                                     EndTime,
                                                     active,
                                                     []),
           {Id, StateName, max(NextTime - Now, 1) * 1000};
       true -> {999, idel, date:next_diff(0) * 1000}
    end.

get_idle_time([], _, Time, StateName, []) ->
    {999, Time, StateName};
get_idle_time([], _, _Time, _StateName, List) ->
    [Id | _] = lists:reverse(List),
    {StartTime, _EndTime} = camp_cake_data:get_time(Id),
    {Id, StartTime, active};
get_idle_time([Id | T],
              Arg = #{st := St, et := Et, now := Now}, Time,
              StateName, List) ->
    {StartTime, EndTime} = camp_cake_data:get_time(Id),
    case StartTime >= St andalso StartTime < Et of
        true when StartTime > Now ->
            get_idle_time(T, Arg, Time, StateName, [Id | List]);
        true when EndTime =< Now ->
            get_idle_time(T, Arg, Time, StateName, List);
        true when Now >= StartTime andalso Now < EndTime ->
            {Id, min(EndTime, Et), open};
        _ -> get_idle_time(T, Arg, Time, StateName, List)
    end.

