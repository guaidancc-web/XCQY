special_reward() ->
    guild_reward(),
    qualifying_reward(),
    ok.

guild_reward() ->
    case date:open_srv_day() of
        5 ->
            case guild_mgr:list() of
                {ok, L} ->
                    logger:info("开始发放公会奖励", [], campaign_misc, 36),
                    do_guild_reward(L);
                _ ->
                    logger:error("发放公会奖励时, 无法获取公会列表",
                                 [],
                                 campaign_misc,
                                 39),
                    skip
            end,
            ok;
        Day when is_integer(Day) ->
            logger:info("开服第~w天,不发放公会奖励", [Day], campaign_misc, 44),
            ok;
        _ -> ok
    end.

do_guild_reward([]) -> ok;
do_guild_reward([G | T]) ->
    do_guild_reward(G),
    do_guild_reward(T);
do_guild_reward(G = #guild{lev = Lev, id = Gid,
                           name = GName, members = Mems}) ->
    case campaign_data:guild_reward(Lev) of
        #{title := Title, content := Content, items := Items} ->
            logger:info("帮派[~w:~ts]等级:~w 成员奖励：~w",
                        [Gid, GName, Lev, Items],
                        campaign_misc,
                        56),
            Now = date:unixtime(),
            Args = #{title => Title, content => Content,
                     items => Items, time => Now},
            do_guild_mem_reward(Mems, G, Args);
        _ -> skip
    end.

do_guild_mem_reward([], _G, _Args) -> ok;
do_guild_mem_reward([#guild_role{last_logout =
                                     LastLogout}
                     | T],
                    G, Args = #{time := Time})
    when Time - LastLogout > 7 * 86400 ->
    do_guild_mem_reward(T, G, Args);
do_guild_mem_reward([#guild_role{id = RoleId} | T], G,
                    Args) ->
    mail:send(RoleId, Args),
    do_guild_mem_reward(T, G, Args).

qualifying_reward() ->
    case date:open_srv_day() of
        5 ->
            RankL = qualifying_rank:get_mark_rank(),
            logger:info("开始发放段位赛活动奖励：~w",
                        [length(RankL)],
                        campaign_misc,
                        78),
            do_qualifying_rank(RankL, 1);
        Day when is_integer(Day) ->
            logger:info("开服第~w天,不发放段位赛奖励",
                        [Day],
                        campaign_misc,
                        81),
            ok;
        _ -> ok
    end.

do_qualifying_rank([], _Rank) -> ok;
do_qualifying_rank([R | T], Rank) ->
    do_qualifying_rank(R, Rank),
    do_qualifying_rank(T, Rank + 1);
do_qualifying_rank(#qualifying_role_mark{id = RoleId,
                                         name = Name},
                   Rank) ->
    case campaign_data:qualifying_reward(Rank) of
        #{title := Title, content := Content, items := Items} ->
            logger:info("角色[~w:~ts]段位赛奖励：~w",
                        [RoleId, Name, Items],
                        campaign_misc,
                        94),
            Args = #{title => Title, content => Content,
                     items => Items},
            mail:send(RoleId, Args);
        _ -> skip
    end.

week_reward() ->
    case date:day_of_the_week(erlang:date()) of
        7 ->
            case guild_mgr:list() of
                {ok, L} ->
                    logger:info("开始发放公会周奖励", [], campaign_misc, 109),
                    do_week_reward(L);
                _ ->
                    logger:error("发放公会奖励时, 无法获取公会列表",
                                 [],
                                 campaign_misc,
                                 112),
                    skip
            end,
            ets:delete_all_objects(guild_join),
            dets:delete_all_objects(guild_join),
            ok;
        Day when is_integer(Day) ->
            logger:info("星期~w,不发放公会周奖励", [Day], campaign_misc, 119),
            ok;
        _ -> ok
    end.

do_week_reward([]) -> ok;
do_week_reward([G | T]) ->
    do_week_reward(G),
    do_week_reward(T);
do_week_reward(G = #guild{pid = GuildPid, lev = _Lev,
                          id = Gid, name = GName, members = Mems}) ->
    logger:info("帮派[~w:~ts]等级:~w",
                [Gid, GName, _Lev],
                campaign_misc,
                129),
    Msg =
        notice:format(lang:get("在全体成员的一致努力下，~ts又往前迈进了一步，本周的公会工资已通过邮件发放，下周继续努力"
                               "哦{face_1, 18}"),
                      [{string_2, 5, GName}]),
    guild:notice(GuildPid, Msg),
    JoinList1 = case ets:lookup(guild_join, Gid) of
                    [{Gid, JoinList}] -> JoinList;
                    _ -> []
                end,
    do_week_mem_reward(Mems,
                       G,
                       #{date => date:unixtime(), join_list => JoinList1}).

do_week_mem_reward([], _G, _Args) -> ok;
do_week_mem_reward([#guild_role{id = RoleId,
                                post = Post, enter_time = _Entered}
                    | T],
                   G = #guild{academy_lev = AcademyLev},
                   Args = #{join_list := JoinList}) ->
    Flag = lists:member(RoleId, JoinList),
    logger:debug("周奖励 ~w",
                 [{Flag, RoleId, JoinList}],
                 campaign_misc,
                 144),
    case guild_data:get_week_reward({Post, AcademyLev}) of
        #{title := Title, content := Content, items := Items,
          items_extra := ItemExtra}
            when Flag =:= true ->
            ItemsAll = lists:foldl(fun ({BaseId, Num}, Acc) ->
                                           case lists:keytake(BaseId, 1, Acc) of
                                               {value,
                                                {BaseId, OldNum},
                                                Acc1} ->
                                                   [{BaseId, OldNum + Num}
                                                    | Acc1];
                                               _ -> [{BaseId, Num} | Acc]
                                           end
                                   end,
                                   Items,
                                   ItemExtra),
            Mail = #{title => Title, content => Content,
                     items => ItemsAll},
            mail:send(RoleId, Mail),
            do_week_mem_reward(T, G, Args);
        _ -> do_week_mem_reward(T, G, Args)
    end;
do_week_mem_reward([_ | T], G, Args) ->
    do_week_mem_reward(T, G, Args).

