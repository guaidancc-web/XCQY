                 287),
    Ids = get_honor_ids(Role),
    case wedding_data:get_cash_honor(Id) of
        #{male_id := MaleId, female_id := FemaleId} ->
            HonorId = case Sex of
                          1 -> MaleId;
                          _ -> FemaleId
                      end,
            honor:del({RoleId, Platform, Zone}, Ids, push),
            honor:add_and_use({RoleId, Platform, Zone},
                              HonorId,
                              push),
            HonorIds1 = case Ids of
                            [OldId | _] ->
                                [OldId | lists:delete(OldId, HonorIds)];
                            _ -> HonorIds
                        end,
            HonorIds2 = [HonorId | lists:delete(HonorId,
                                                HonorIds1)],
            logger:debug("称号列表信息 ~w~n",
                         [{Id, Ids, HonorId, HonorIds1, HonorIds2}],
                         wedding_memory,
                         301),
            {ok,
             ok,
             Role#role{m_wedding =
                           Wedding#m_wedding{honor_ids = HonorIds2}}};
        _ ->
            logger:error("不存在的ID ~w~n", [Id], wedding_memory, 304),
