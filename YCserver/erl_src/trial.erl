rpc_accept(Role, Mode) ->
    case check_accept(Role, Mode) of
        {false, Reason, Reset} -> {false, Reason, Reset};
        {has_trial, Mode, Reset} ->
            case enter(Role) of
                {ok, NewRole} -> {ok, NewRole, Reset};
                {false, Reason} -> {false, Reason, Reset}
            end;
        {has_trial, _, Reset} ->
            {false, lang:get("当前没有该难度的进度"), Reset};
        {true, NewMtrial, Reset} ->
            Role1 = var:set_var(Role#role{m_trial = NewMtrial},
                                day_five,
                                124,
