                                         true -> {true, RankLev};
                                         false ->
                                             {false,
                                              lang:get("今日胜利场次不足，无法领取奖励")}
                                     end;
                                 _ ->
                                     case qualifying_mgr:get_count(Role, 1) of
                                         CombatTime
                                             when is_integer(CombatTime) andalso
                                                      CombatTime >= 5 ->
                                             {true, RankLev};
                                         _ ->
                                             {false,
                                              lang:get("今日参与场次不足，无法领取奖励")}
                                     end
                             end;
                         _ -> {false, lang:get("未满足领取条件，请继续加油")}
                     end,
            case Result of
                {false, Reason} -> {false, Reason};
                {true, GetRankLev} ->
                    GetGain = case qualifying_data:get_win({GetRankLev,
                                                            RoleLev})
                                  of
                                  {Gain = [_ | _], _} when Flag =:= 1 ->
                                      format:val_to_gain(Gain);
                                  {_, FiveGain = [_ | _]} when Flag =:= 2 ->
                                      format:val_to_gain(FiveGain);
                                  _ -> []
                              end,
                    case GetGain of
                        [] -> {false, lang:get("未满足领取条件，请继续加油")};
                        GainList = [_ | _] ->
                            case role_gain:do_notice(GainList, Role) of
                                {false, _} ->
                                    {false, lang:get("背包已满，请整理背包再来领取")};
                                {ok, NewRole} ->
                                    {Msg, NewMqua} = case Flag of
                                                         1 ->
