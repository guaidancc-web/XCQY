rank_role([], Add, List) -> List ++ Add;
rank_role([OldR = #dungeon_rank_role{id = Id,
                                     val1 = OldVal1}
           | T],
          RoleList, List) ->
    NewRoleList = lists:keydelete(Id,
                                  #dungeon_rank_role.id,
                                  RoleList),
    case lists:keyfind(Id, #dungeon_rank_role.id, RoleList)
        of
        #dungeon_rank_role{val1 = Val1} when OldVal1 =< Val1 ->
            rank_role(T,
                      NewRoleList,
                      [OldR#dungeon_rank_role{up = 0} | List]);
        R = #dungeon_rank_role{} ->
            rank_role(T, NewRoleList, [R | List]);
        _ ->
            rank_role(T,
                      NewRoleList,
                      [OldR#dungeon_rank_role{up = 0} | List])
    end.

lord_reward([], List) ->
    CastList = lord_cast(List, []),
    {List, CastList};
lord_reward([#dungeon_lord{dun_id = DunId,
                           floor = Floor, lords = Lords}
             | T],
            List) ->
    NewList = lord_reward2(Lords, DunId, Floor, List),
    lord_reward(T, NewList).

lord_reward2([], _DunId, _Floor, List) -> List;
lord_reward2([#dungeon_lord_role{id = RoleId,
                                 name = Name}
              | T],
             DunId, Floor, List) ->
    NewList = case [I
                    || I = #{dun_id := IDunId, id := IRoleId} <- List,
                       IDunId == DunId andalso IRoleId == RoleId]
                  of
                  [] ->
                      [#{dun_id => DunId, floor => Floor, id => RoleId,
                         name => Name}]
                          ++ List;
                  [#{floor := OldFloor} | _] when OldFloor >= Floor ->
                      List;
                  IL ->
                      [#{dun_id => DunId, floor => Floor, id => RoleId,
                         name => Name}]
                          ++ List -- IL
              end,
    lord_reward2(T, DunId, Floor, NewList).

lord_cast([], List) -> List;
