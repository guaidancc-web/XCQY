check_withered(Plants) ->
    Plants1 = [P || P = #guild_plant{phase = 1} <- Plants],
    case length(Plants1) >= 10 of
        true ->
            Fun = fun (#guild_plant{matured = M1},
                       #guild_plant{matured = M2}) ->
                          M1 < M2
                  end,
            [P1 = #guild_plant{owner_rid = OwnerId,
                               unit_id = UnitId}
             | _] =
                lists:sort(Fun, Plants1),
            unit_mgr:remove(UnitId),
            P2 = P1#guild_plant{unit_id = {0, 0}, phase = 2},
            lists:keyreplace(OwnerId,
                             #guild_plant.owner_rid,
                             Plants,
                             P2);
        _ -> Plants
    end.

do_irrigate(Role = #role{lev = Lev, name = Name}) ->
    G1 = case levup_data:get_exp({3203, Lev}) of
             #{coin := Coin, exp := Exp} ->
                 [{90000, Coin}, {90010, Exp}];
             _ -> []
         end,
    G2 = case pet:get_war_pet(Role) of
             {ok, #pet{lev = PetLev}} ->
                 case levup_data:get_exp({3203, PetLev}) of
                     #{pet_exp := PetExp} -> [{90005, PetExp} | G1];
                     _ -> G1
                 end;
             _ -> G1
         end,
    {FullVal, FullRatio} = {20, 100},
    {HalfVal, HalfRatio} = {30, 50},
    Done = var:get_var(Role, day, 32, 0),
    Ratio = case Done of
                Val when Val < FullVal -> FullRatio;
                Val when Val < HalfVal -> HalfRatio;
                _ -> 0
            end,
    case Ratio of
        0 -> {ok, lang:get("你今天已经照顾了很多花朵，无法再获得经验")};
        _ ->
            Role1 = var:acc_var(Role, day, 32),
            TriggerRole =
                role_trigger:fire(#evt_guild_plant_irrigate{}, Role1),
            G3 = [{T, round(V * Ratio / 100)} || {T, V} <- G2],
            G4 = case Done < 10 andalso util:rand(1, 100) =< 10 of
                     true ->
                         #{item_id := Item, item_num := ItemNum,
                           announce := Ann} =
                             util:rand_list(quest_guild_data:get_irrigate_reward(),
                                            item_weight),
                         case Ann of
                             1 ->
                                 AnnStr =
                                     notice:format(lang:get("~ts在公会领地浇水时，捡到一个~ts {face_1,20}"),
                                                   [{role_2, Name},
                                                    {item_2, Item}]),
                                 notice:cast(all, 5, AnnStr);
                             _ -> ok
                         end,
                         [{Item, 0, ItemNum} | G3];
                     _ -> G3
                 end,
            G5 = case Done < 10 of
                     true -> [{90011, 5} | G4];
                     _ -> G4
                 end,
            NewGain = format:val_to_gain(G5),
            case role_gain:do_notice(NewGain, TriggerRole) of
                {ok, Role2} -> {ok, lang:get("浇水成功"), Role2};
                {false, #gain{reason = bag_full}} ->
                    Title = lang:get("浇水奖励"),
                    Content = lang:get("背包已满，奖励通过邮件发送，请查收。"),
                    mail:send(TriggerRole,
                              #{title => Title, content => Content,
                                items => G5}),
                    {ok, lang:get("浇水成功"), TriggerRole};
                {false, #gain{msg = Msg}} -> {ok, Msg}
            end
    end.

reward_planter(#guild_plant{owner_rid = OwnerId,
                            irrigations = Irrigations},
               Members) ->
    Num = length(Irrigations),
    case lists:keyfind(OwnerId, #guild_role.id, Members) of
        #guild_role{lev = Lev} ->
            Prize = case quest_guild_data:get_plant_reward(Num) of
                        #{reward := Reward} ->
                            case quest_guild_data:get_lev(Lev) of
                                {Ratio, PetRatio} ->
                                    Fun = fun ({90010, V}) ->
                                                  {90010,
                                                   round(V * Ratio / 1000)};
                                              ({90005, V}) ->
                                                  {90005,
                                                   round(V * PetRatio / 1000)};
                                              (D) -> D
                                          end,
                                    [Fun(R) || R <- Reward];
                                _ ->
                                    logger:error("没有等级~w的系数",
                                                 [Lev],
                                                 guild_plant,
                                                 510),
                                    Reward
                            end;
                        _ -> []
                    end,
            MailInfo = case Num of
                           5 ->
                               #{items => Prize, title => lang:get("种花奖励"),
                                 content =>
                                     lang:get("您种下的鲜花被勤劳的公会成员们浇灌了5次，提前成熟，谢谢您为公会领地增添的一抹亮色，现给予"
                                              "奖励如下，敬请查收哦")};
                           _ ->
                               #{items => Prize, title => lang:get("种花奖励"),
                                 content =>
                                     util:flist(lang:get("您种下的鲜花被公会成员们浇灌了~w次，终于在24点时成熟，现给予奖励如下，若能浇水更多次，"
                                                         "奖励也更丰厚哦"),
                                                [Num])}
                       end,
            mail:send(OwnerId, MailInfo);
        _ -> ok
    end.

