rpc_turn(Role, UnitId) ->
    CheckFlag = case var:get_var(Role, other, 2068, {0, 0})
                    of
                    {0, 0} ->
                        case unit_mgr:info({45, UnitId}) of
                            {ok, #unit{base_id = Bid}} ->
                                case Bid of
                                    62320 ->
                                        Nitem = [{22248, 1}],
                                        Dtype = 89,
                                        Vtype = 2066,
                                        {true, Bid, Nitem, Dtype, Vtype};
                                    62319 ->
                                        Nitem = [{22249, 1}],
                                        Dtype = 90,
                                        Vtype = 2067,
                                        {true, Bid, Nitem, Dtype, Vtype};
                                    _ -> {false, lang:get("不支持的宝箱类型")}
                                end;
                            _ -> {false, lang:get("宝箱已经打开了")}
                        end;
                    {_, _} -> has_reward
                end,
    case CheckFlag of
        has_reward ->
            role:rpc(self(), 18202, {}),
            ok;
        {true, BaseId, NeedItem, DayVarType, VarType} ->
            Opened = var:get_var(Role, day, DayVarType, 0),
            case spectral_box_data:get_acc_reward(BaseId) of
                #{max_num := MaxNum} when Opened >= MaxNum ->
                    {false, lang:get("今日次数已用完")};
                _ ->
                    Loss = format:val_to_loss(NeedItem,
                                              #{item_base_id_auto_buy => 1,
                                                auto_scene =>
                                                    lang:get("进行抽奖")}),
                    case role_gain:do_notice(Loss, Role) of
                        {ok, NRole2} ->
                            NRoleItem = do_item_effect(NeedItem, NRole2),
                            NRole3 = var:acc_var(NRoleItem, other, VarType),
                            case rand_reward(NRole3, BaseId, VarType) of
                                0 -> {false, lang:get("这个宝箱没啥抽了")};
                                RewardId ->
                                    case unit_mgr:remove({45, UnitId}) of
                                        ok ->
                                            NRole4 = var:set_var(NRole3,
                                                                 other,
                                                                 2068,
                                                                 {BaseId,
                                                                  RewardId}),
                                            NRole5 = acc_reward(NRole4,
                                                                BaseId,
                                                                VarType),
                                            NRole6 = var:acc_var(NRole5,
                                                                 day,
                                                                 DayVarType),
                                            Timer = #timer{id =
                                                               spectral_box_check_reward,
                                                           timeout = 10000,
                                                           times = 1,
                                                           m = spectral_box,
                                                           f = apply_role,
                                                           a = [check_reward]},
                                            NRole7 = role_timer:set(Timer,
                                                                    NRole6),
                                            push(NRole7, 18200),
                                            spectral_box !
                                                {clear_one, {45, UnitId}},
                                            Msg =
                                                notice:format(lang:get("成功开启了一个~ts，祝您好运！"),
                                                              [{unit_1,
                                                                BaseId}]),
                                            {ok, NRole7, RewardId, Msg};
                                        _ -> {false, lang:get("单位不能抽取")}
                                    end
                            end;
                        {false, #loss{msg = Msg}} -> {false, Msg};
                        {false, _} -> {false, lang:get("您没有开启宝箱的钥匙")}
                    end
            end;
        {false, Reason} -> {false, Reason}
    end.

