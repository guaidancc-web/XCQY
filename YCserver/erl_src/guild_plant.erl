grow(G = #guild{plants = Plants, map_id = MapId,
                members = Members}) ->
    Now = date:unixtime(),
    Fun = fun (#guild_plant{phase = Phase1, sowed = Sowed1},
               #guild_plant{phase = Phase2, sowed = Sowed2}) ->
                  if Phase1 < Phase2 -> true;
                     Phase1 =:= Phase2 andalso Sowed1 > Sowed2 -> true;
                     true -> false
                  end
          end,
    Sorted = lists:sort(Fun, Plants),
    Plants1 = do_grow(Sorted,
                      #{plants => [], num => 0, now => Now, map_id => MapId,
                        members => Members}),
    G#guild{plants = Plants1}.

