divorce(Role = #role{m_skill = Skills}) ->
    NewRole = Role#role{m_skill =
                            Skills#m_skill{skill_couple = []}},
    push(NewRole),
    NewRole.

push(#role{link = Link,
           m_skill = #m_skill{skill_couple = CoupleSkills}}) ->
    role:link_send(Link, 10822, {CoupleSkills}).

apply_study(Role = #role{m_skill =
                             Skills = #m_skill{skill_couple = CoupleSkill}},
            SkillId, Intimacy) ->
    case check_has_active(CoupleSkill, SkillId) of
        true -> {ok, ok};
        false ->
            NewCoupleSkills = [SkillId | CoupleSkill],
            NewRole = Role#role{m_skill =
                                    Skills#m_skill{skill_couple =
                                                       NewCoupleSkills}},
            calc_and_push(NewRole, SkillId, Intimacy),
            {ok, ok, NewRole}
    end.

calc_lev(Role, Skills) ->
    Intimacy = get_lover_intimacy(Role),
    [skill_data:get_couple_lev(SkillId, Intimacy)
     || SkillId <- Skills].

get_couple_skills(Role = #role{m_skill =
                                   #m_skill{skill_couple = CoupleSkills}}) ->
    calc_lev(Role, CoupleSkills).

get_not_memtxt() -> lang:get("学习夫妻技能需要与另一半组队前来").

check_has_active([SkillId | _Rest], SkillId) -> true;
check_has_active([_ | Rest], SkillId) ->
    check_has_active(Rest, SkillId);
check_has_active([], _SkillId) -> false.

check_active_condition(#role{id = RoleId,
                             m_skill = #m_skill{skill_couple = CoupleSkills}},
                       LoverId, SkillId) ->
    case skill_data:get_couple({SkillId, 1}) of
        #{love_var := NeedLoveVal, intimacy := NeedIntimacy,
          depend_skill := DependSkill} ->
            Intimacy = friend:get_intimacy(RoleId, LoverId),
            case Intimacy < NeedIntimacy of
                true ->
                    RetMsg = notice:format(lang:get("该技能需要达到~w亲密度才能激活该技能"),
                                           [NeedIntimacy]),
                    {false, RetMsg};
                false ->
                    case lists:member(DependSkill, CoupleSkills) of
                        false when DependSkill =/= 0 ->
                            SkillName = case skill_data:get_couple({DependSkill,
                                                                    1})
                                            of
                                            #{name := Name} -> Name;
                                            _ -> lang:get("前置技能")
                                        end,
                            Msg = notice:format(lang:get("请先学习~ts"),
                                                [{string_2, 5, SkillName}]),
                            {false, Msg};
                        _ -> {true, format:val_to_loss([{90018, NeedLoveVal}])}
                    end
            end;
        false ->
            logger:error("读取夫妻技能配置错误~w",
                         [{SkillId, 1}],
                         couple_skill,
                         134),
            {false, lang:get("获取技能配置错误")}
    end.

calc_and_push(#role{link = Link}, SkillId, Intimacy) ->
    SkillLev = skill_data:get_couple_lev(SkillId, Intimacy),
    role:link_send(Link, 10820, SkillLev).

get_lover_intimacy(#role{id = RoleId}) ->
    case wedding:lover(RoleId) of
        {ok, #lover{lover_id = LoverId}} ->
            friend:get_intimacy(RoleId, LoverId);
        _ -> 0
    end.

