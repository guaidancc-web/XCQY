                               {ok, Role2} -> Role2;
                               {false, _R} -> Role
                           end;
                       _ -> Role
                   end,
    NRole = case QD of
                #quest_data{rewards_commit = [], honor = 0}
                    when Finish =:= 1 ->
                    case Push of
