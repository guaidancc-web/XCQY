                    logger:error("~w", [_Err], camp_score_exchange, 298),
                    role:send_buff_clean(),
                    {ok, Role}
            end;
        _ ->
            logger:error("配置出错,不能兑换银币",
                         [],
                         camp_score_exchange,
                         303),
            {ok, Role}
    end;
