calc_aptitude({BaseHpApt,
               BasePhyApt,
               BasePdefApt,
               BaseMagApt,
               BaseAspdApt},
              #child_attr{study_str = StudyStr, study_con = StudyCon,
                          study_agi = StudyAgi, study_end = StudyEnd,
                          study_mag = StudyMag}) ->
    {HpRatio1, HpRatio2} =
        child_data:get_apt_ratio(StudyCon),
    {PhyRatio1, PhyRatio2} =
        child_data:get_apt_ratio(StudyStr),
    {PdefRatio1, PdefRatio2} =
        child_data:get_apt_ratio(StudyEnd),
    {MagRatio1, MagRatio2} =
        child_data:get_apt_ratio(StudyMag),
    {AspdRatio1, AspdRatio2} =
        child_data:get_apt_ratio(StudyAgi),
    HpRatio = util:rand(HpRatio1, HpRatio2),
    PhyRatio = util:rand(PhyRatio1, PhyRatio2),
    PdefRatio = util:rand(PdefRatio1, PdefRatio2),
    MagRatio = util:rand(MagRatio1, MagRatio2),
    AspdRatio = util:rand(AspdRatio1, AspdRatio2),
    HpApt = round(BaseHpApt * HpRatio / 1000),
    PhyApt = round(BasePhyApt * PhyRatio / 1000),
    PdefApt = round(BasePdefApt * PdefRatio / 1000),
    MagApt = round(BaseMagApt * MagRatio / 1000),
    AspdApt = round(BaseAspdApt * AspdRatio / 1000),
    {HpApt, PhyApt, PdefApt, MagApt, AspdApt}.

