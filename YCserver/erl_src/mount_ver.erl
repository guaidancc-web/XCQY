convert_field(Data, []) -> {ok, Data};
convert_field(Data, [Field | Rest]) ->
    case convert_field(Data, Field) of
        {ok, NewData} -> convert_field(NewData, Rest);
        _ -> {false, lang:get("坐骑数据加载出错")}
    end;
convert_field(Data = #m_mount{mounts = Mounts},
              mounts) ->
    case convert_mount_info(Mounts) of
        {ok, NewMounts} ->
            {ok, Data#m_mount{mounts = NewMounts}};
        {false, Reason} -> {false, Reason};
        _Err ->
            logger:error("错误的数据转化:~w", [_Err], mount_ver, 102),
            {false, lang:get("错误的数据转化")}
    end;
convert_field(_Data, _Field) ->
    {false,
     lang:get("未知的坐骑数据转化:~w, 数据:~w"),
     [_Field, _Data]}.

convert_mount_info(Mounts) ->
    convert_mount_info(Mounts, []).

convert_mount_info([], NewMounts) -> {ok, NewMounts};
convert_mount_info([Data | Rest], NewMounts) ->
    case convert_mount_data(Data) of
        {ok, NewMount} ->
            convert_mount_info(Rest, [NewMount | NewMounts]);
        _Else -> _Else
    end.

