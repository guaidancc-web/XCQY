reward_times_item_get(_Id, 0) ->
    {false, lang:get("今天不是结缘纪念日哦~没有礼品拿{face_1, 22}")};
reward_times_item_get(Id, Time) ->
    case wedding_data:get_memorial_day(Id) of
        {Day, ItemId} when Day =/= 365 ->
            Day1 = date:day_diff(Time, date:unixtime()),
            case Day1 >= Day of
                true -> {1, ItemId};
                _ -> {0, ItemId}
            end;
        {Day, ItemId} when Day =:= 365 ->
            Years = anniversary(Time),
            {Years, ItemId};
        _ -> {false, lang:get("今天不是结缘纪念日哦~没有礼品拿{face_1, 22}")}
    end.

anniversary(Time) ->
    {{Y1, M1, D1}, _} = date:seconds_to_datetime(Time),
    {{Y2, M2, D2}, _} =
        date:seconds_to_datetime(date:unixtime()),
    if M2 > M1 -> Y2 - Y1;
       M2 =:= M1 andalso D2 >= D1 -> Y2 - Y1;
       true -> max(0, Y2 - Y1 - 1)
    end.

get_reward_cb(Role = #role{m_wedding =
                               #m_wedding{reward = Reward}},
              Id, Time) ->
    {Times, List} = reward_times_get(Reward, Id),
    case reward_times_item_get(Id, Time) of
        {RewardTimes, ItemId} when is_integer(RewardTimes) ->
            case Times < RewardTimes of
                true ->
                    {ok, Role2, _Id, _Times} = get_reward3(Role,
                                                           Id,
                                                           Times + 1,
                                                           List,
                                                           ItemId),
                    {ok, ok, Role2};
                _ -> {ok, false}
            end;
        _ -> {ok, false}
    end.

get_reward3(Role = #role{m_wedding = MWedding}, Id,
            Times, List, ItemId) ->
    Role1 = Role#role{m_wedding =
                          MWedding#m_wedding{reward = [{Id, Times} | List]}},
    G = format:val_to_gain([{ItemId, 0, 1}]),
    case role_gain:do_notice(G, Role1) of
        {ok, Role2} -> {ok, Role2, Id, Times};
        _ ->
            mail:send(Role,
                      lang:get("结缘纪念礼包"),
                      lang:get("背包已满"),
                      [{ItemId, 0, 1}]),
            {ok, Role1, Id, Times}
    end.

reward_times_get(List, Id) ->
    case lists:keytake(Id, 1, List) of
        {value, {_, Times}, List1} -> {Times, List1};
        _ -> {0, List}
    end.

