check_in_rank([#fighter{origin_id = OriginId, lev = Lev,
                        m_lev_break = MLevBreak}
               | T]) ->
    NewLev = case MLevBreak of
                 #m_lev_break{times = Times} -> Times * 6 + Lev;
                 _ -> Lev
             end,
    Key = case NewLev >= 116 of
              true -> 116;
              _ when NewLev >= 106 -> 106;
              _ when NewLev >= 101 -> 101;
              _ when NewLev >= 90 -> 90;
              _ when NewLev >= 80 -> 80;
              _ -> 70
          end,
    case ets:lookup(tournament_rank, {Key, last}) of
        [{_, #tournament_profile{rank_point = BasePoint}}] ->
            case ets:lookup(tournament_profile, OriginId) of
                [#tournament_profile{rank_point = RankPoint}]
                    when RankPoint >= BasePoint ->
                    case RankPoint >= BasePoint of
                        true -> true;
                        _ -> check_in_rank(T)
                    end;
                _ -> check_in_rank(T)
            end;
        _ -> check_in_rank(T)
    end;
check_in_rank([_H | T]) ->
    logger:error("武道会录像出问题数据：~w", [_H], tournament, 1010),
    check_in_rank(T).

group_by_platform([], Groups) -> Groups;
group_by_platform([#fighter{origin_id = Id = {_, P, Z}}
                   | T],
                  Groups) ->
    K = c_big_world:get_zone_mapping(P, Z),
    Groups1 = case lists:keyfind(K, 1, Groups) of
                  {K, L} -> lists:keyreplace(K, 1, Groups, {K, [Id | L]});
                  _ -> [{K, [Id]} | Groups]
              end,
    group_by_platform(T, Groups1);
group_by_platform([Pf = #tournament_profile{id =
                                                {_, P, Z}}
                   | T],
                  Groups) ->
    K = c_big_world:get_zone_mapping(P, Z),
    Groups1 = case lists:keyfind(K, 1, Groups) of
                  {K, L} -> lists:keyreplace(K, 1, Groups, {K, [Pf | L]});
                  _ -> [{K, [Pf]} | Groups]
              end,
    group_by_platform(T, Groups1).

cast_record(#{round := Round, winner := Winner,
              loser := Loser, record := Record,
              match_id := MatchId}) ->
    Ids = [Id
           || #fighter{origin_id = Id = {_, _, _}}
                  <- Winner ++ Loser],
    IsMarvel = is_marvel(Round, Winner, Loser),
    CastM = #{record => Record, is_marvel => IsMarvel,
              combat_type => 40, match_id => MatchId, cross => false},
    case Ids of
        [{_, Platfrom, ZoneId} | _] ->
            logger:debug("武道会保存录像，是否精彩：~w",
                         [IsMarvel],
                         tournament,
                         1038),
            big_world:cast(Platfrom,
                           ZoneId,
                           combat_record,
                           save,
                           [CastM#{ids => Ids, cross => true,
                                   pz => {Platfrom, ZoneId}}]),
            {Platfrom, ZoneId};
        _ -> {"", 0}
    end.

second_timeout(AgendaId, idle, Timeout) ->
    Now = date:unixtime(),
    case agenda_data:get(AgendaId) of
        #{args := [H | T]} ->
            case date:week_next_diff([H | T], Now, {22, 15, 0}) of
                Tt when Tt < Timeout -> Tt;
                _ -> Timeout
            end;
        _ ->
            case date:next_diff({22, 15, 0}) of
                Tt when Tt < Timeout -> Tt;
                _ -> Timeout
            end
    end;
second_timeout(_, _StateName, Timeout) -> Timeout.

check_banned() ->
    L = ets:tab2list(tournament_profile),
    Tomorrow = date:unixtime() + 172800,
    Changed = do_check_banned(L, Tomorrow, []),
    logger:debug("禁赛列表 ~w", [Changed], tournament, 1075),
    RepotedGroups = group_by_platform(Changed, []),
    cast_banned(RepotedGroups),
    ets:insert(tournament_profile, Changed),
    dets:insert(tournament_profile, Changed),
    NewL = ets:tab2list(tournament_profile),
    Cleaned = clean_reported_info(NewL, []),
    CleanGroups = group_by_platform(Cleaned, []),
    sync_profile(CleanGroups),
    ets:insert(tournament_profile, Cleaned),
    dets:insert(tournament_profile, Cleaned).

do_check_banned([], _, ReportPunish) -> ReportPunish;
do_check_banned([P = #tournament_profile{reported =
                                             Reported,
                                         rank_point = RankPoint}
                 | T],
                Tomorrow, ReportPunish)
    when Reported =/= 0 ->
    case handle_reported(P) of
        true ->
            DescPoint = min(RankPoint rem 100, 25),
            NewRankPoint = max(RankPoint - DescPoint, 0),
            NewP = P#tournament_profile{banned_date = Tomorrow,
                                        rank_point = NewRankPoint},
            NewReportPunish = [NewP | ReportPunish],
            do_check_banned(T, Tomorrow, NewReportPunish);
        _ -> do_check_banned(T, Tomorrow, ReportPunish)
    end;
do_check_banned([_ | T], Tomorrow, ReportPunish) ->
    do_check_banned(T, Tomorrow, ReportPunish).

