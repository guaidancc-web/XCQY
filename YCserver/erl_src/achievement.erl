get_val_from_prev(1, Progs,
                  #quest_data{progress = PreProgs})
    when length(Progs) =:= length(PreProgs) ->
    do_get_val_from_prev(Progs, PreProgs, []);
get_val_from_prev(_ValFromPrev, Progs, _) -> Progs.

do_get_val_from_prev([], [], Progs) ->
    lists:reverse(Progs);
do_get_val_from_prev([Prog | T1],
                     [#quest_progress{target_val = TarVal} | T2], Progs) ->
    do_get_val_from_prev(T1,
                         T2,
                         [Prog#quest_progress{value = TarVal} | Progs]).

do_reward(Role = #role{m_achievement =
                           #m_achievement{doing = DoL, finish = FinL}},
          Id) ->
    Flag = lists:keyfind(Id, 1, FinL),
    case lists:keyfind(Id, #quest.id, DoL) of
        false when Flag =/= false -> {false, lang:get("奖励已领取")};
        false -> {false, lang:get("成就任务不存在")};
        #quest{finish = 0} ->
            {false, util:fbin(lang:get("成就任务未完成:~w"), [Id])};
        Q = #quest{finish = 1, finish_time = FTime} ->
            case achievement_data:get(Id) of
                #quest_data{rewards_commit = Rewards0, honor = Honor} ->
                    Rewards = [{I, 0, N} || {I, N} <- Rewards0],
                    Rewards2 = [{I, Bind, N} || {I, Bind, N} <- Rewards0],
                    GL = format:val_to_gain(Rewards ++ Rewards2),
                    case role_gain:do_notice(GL, Role, lang:get("领取成就")) of
                        {false, #gain{msg = Msg}} -> {false, Msg};
                        {ok,
                         Role1 = #role{m_achievement =
                                           MAchi = #m_achievement{doing =
                                                                      DoL1}}} ->
                            sys_conn:pack_send(10220, {[Q#quest{finish = 2}]}),
                            NewDoL = lists:keydelete(Id, #quest.id, DoL1),
                            Role3 = case Honor > 0 of
                                        true ->
                                            case honor:add_and_use(Role1,
                                                                   Honor,
                                                                   push)
                                                of
                                                {ok, Role2} -> Role2;
                                                _ -> Role1
                                            end;
                                        _ -> Role1
                                    end,
                            NewFTime = case FTime of
                                           0 -> date:unixtime();
                                           _ -> FTime
                                       end,
                            NewRole = Role3#role{m_achievement =
                                                     MAchi#m_achievement{doing =
                                                                             NewDoL,
                                                                         finish
                                                                             =
                                                                             [{Id,
                                                                               NewFTime}
                                                                              | FinL]}},
                            {ok, NewRole}
                    end;
                _ -> {false, lang:get("成就基础数据不存在")}
            end
    end.

do_load_progress([], _, Progress) -> Progress;
do_load_progress([P = #quest_progress{label = Label}
                  | T],
                 Prog, Progress) ->
    case lists:keyfind(Label, #quest_progress.label, Prog)
        of
        #quest_progress{target_val = TarVal} ->
            do_load_progress(T,
                             Prog,
                             [P#quest_progress{target_val = TarVal}
                              | Progress]);
        _ -> do_load_progress(T, Prog, [P | Progress])
    end.

calc_point([], Point) -> Point;
