load_data() ->
    ask_tab = ets:new(ask_tab,
                      [set, named_table, public, {keypos, #ask_question.id}]),
    {ok, ask_tab} = dets:open_file(ask_tab,
                                   [{file, "dets/ask.dets"},
                                    {keypos, #ask_question.id}]),
    FunAsk = fun (AskQuestion, Acc) ->
                     case ask_ver:do(AskQuestion) of
                         {ok, NewAskQuestion} -> [NewAskQuestion | Acc];
                         {false, Msg} -> {error, Msg}
                     end
             end,
    case dets:foldl(FunAsk, [], ask_tab) of
        AskList when is_list(AskList) ->
            dets:delete_all_objects(ask_tab),
            ok = dets:insert(ask_tab, AskList),
            true = ets:insert(ask_tab, AskList),
            ok;
        AskErr ->
            logger:error("答题数据载入错误:~w", [AskErr], ask_mgr, 250),
            exit(abnormal)
    end,
    ask_state_tab = ets:new(ask_state_tab,
                            [set,
                             named_table,
                             public,
                             {keypos, #ask_state_store.label}]),
    {ok, ask_state_tab} = dets:open_file(ask_state_tab,
                                         [{file, "dets/ask_state.dets"},
                                          {keypos, #ask_state_store.label}]),
    ask_state_tab = dets:to_ets(ask_state_tab,
                                ask_state_tab),
    case lookup(ask_state_tab, store) of
        [#ask_state_store{next_ask_id = NextAskId,
                          free_ask_ids = FreeIds}] ->
            {ok,
             #ask_state{next_ask_id = NextAskId,
                        free_ask_ids = FreeIds}};
        _ -> ok
    end.

server_question_init(AskFunType, Answerers, NextAskId,
                     #ask_state{platform = Pltm, zone_id = ZoneId}) ->
    NewAskId = if is_integer(NextAskId) ->
                      {Pltm, ZoneId, NextAskId};
                  true -> NextAskId
               end,
    Selected = case AskFunType of
                   1 ->
                       Questions = question_data:teacher_list(),
                       util:rand_list_n(Questions, 3);
                   _ -> []
               end,
    case Selected of
        [QId | _] ->
            Now = date:unixtime(),
            AskQuestion = #ask_question{id = NewAskId, sid = 1,
                                        qid = QId, answerers = Answerers,
                                        fun_type = AskFunType,
                                        questions = Selected, start_time = Now},
            save(ask_tab, AskQuestion),
            {ok, AskQuestion};
        _ -> {false, lang:get("已经没有题目了")}
    end.

server_commit_answer(AskId, Sid, State) ->
    case lookup(ask_tab, AskId) of
        [AskQuestion = #ask_question{sid = Sid,
                                     fun_type = 1}] ->
            case quest_teacher:answer_timeout(AskQuestion) of
                {ok, MFA, NewAskQuestion} ->
                    save(ask_tab, NewAskQuestion),
                    async_local_answerer(NewAskQuestion, MFA, State),
                    remove;
                _ -> remove
            end;
        _ -> remove
    end.

server_commit_answer(AskId, Sid, Option, SelfId,
                     SelfPid, State) ->
    case lookup_ask_question(AskId) of
        {ok,
         AskQuestion = #ask_question{sid = Sid, opts = Opts}} ->
            case lists:keyfind(SelfId, 1, Opts) of
                false ->
                    Now = date:unixtime(),
                    handle_commit_answer(AskQuestion,
                                         Sid,
                                         Option,
                                         Now,
                                         SelfId,
                                         SelfPid,
                                         State);
                _ -> {false, lang:get("无需重复提交答案")}
            end;
        _ -> {false, lang:get("没有找到对应的答题数据")}
    end.

handle_commit_answer(AskQuestion =
                         #ask_question{fun_type = 1, q_start_time = QStartTime,
                                       id = _Id},
                     _Sid, Option, Now, SelfId, SelfPid, State) ->
    case QStartTime + 20 + 5 < Now of
        true ->
            logger:debug("答题进程处理答案：Id:~w, Sid:~w, Option:~w, Who:~w",
                         [_Id, _Sid, Option, SelfId],
                         ask_mgr,
                         321),
            case catch quest_teacher:answer_timeout(AskQuestion,
                                                    SelfId,
                                                    SelfPid,
                                                    Now)
                of
                {ok, MFA, NewAskQuestion} ->
                    save(ask_tab, NewAskQuestion),
                    async_local_answerer(NewAskQuestion, MFA, State),
                    NoticeMFA = {notice, send, [1, lang:get("选择超时")]},
                    async_local_answerer(NewAskQuestion, NoticeMFA, State),
                    ok;
                {false, Msg} -> {false, Msg};
                _ -> {false, lang:get("答题超时")}
            end;
        false ->
            logger:debug("答题进程处理答案：Id:~w, Sid:~w, Option:~w, Who:~w",
                         [_Id, _Sid, Option, SelfId],
                         ask_mgr,
                         333),
            case catch quest_teacher:handle_answer(AskQuestion,
                                                   Option,
                                                   SelfId,
                                                   SelfPid,
                                                   Now)
                of
                {ok, NewAskQuestion} ->
                    ask:push_answer_status(SelfId, NewAskQuestion),
                    save(ask_tab, NewAskQuestion),
                    ok;
                {ok, MFA, NewAskQuestion} ->
                    save(ask_tab, NewAskQuestion),
                    async_local_answerer(NewAskQuestion, MFA, State),
                    ok;
                {false, Msg} -> {false, Msg};
                _ -> {false, lang:get("提交答案失败")}
            end
    end;
handle_commit_answer(_AskQuestion, _Sid, _Option, _Now,
                     _SelfId, _SelfPid, _State) ->
    {false, lang:get("无法处理提交的答案")}.

server_get_question_info(AskId, _State) ->
    case lookup(ask_tab, AskId) of
        [AskQuestion = #ask_question{q_start_time = 0}] ->
            Now = date:unixtime(),
            NewAskQuestion = AskQuestion#ask_question{q_start_time =
                                                          Now},
            save(ask_tab, NewAskQuestion),
            {ok, NewAskQuestion};
        _ -> false
    end.

server_gain_question_reward(AskId, SelfId, _State) ->
    case lookup(ask_tab, AskId) of
        [AskQuestion = #ask_question{answer_list =
                                         AnswerList}] ->
            case ask:get_pre_answer(AskQuestion) of
                {ok,
                 Answer = #ask_answer{sid = PreSid,
                                      draw_list = DrawList}} ->
                    case lists:keyfind(PreSid, #ask_answer.sid, AnswerList)
                        of
                        Answer = #ask_answer{draw_list = DrawList} ->
                            NewDrawList = case lists:member(SelfId, DrawList) of
                                              true -> [SelfId];
                                              false -> [SelfId | DrawList]
                                          end,
                            NewAnswer = Answer#ask_answer{draw_list =
                                                              NewDrawList},
                            NewAnswerList = lists:keystore(PreSid,
                                                           #ask_answer.sid,
                                                           AnswerList,
                                                           NewAnswer),
                            NewAskQuestion =
                                AskQuestion#ask_question{answer_list =
                                                             NewAnswerList},
                            save(ask_tab, NewAskQuestion),
                            ok;
                        _ -> false
                    end;
                _ -> false
            end;
        _ -> false
    end.

async_local_answerer(#ask_question{answerers =
                                       Answerers},
                     MFA, State) ->
    async_local_answerer(Answerers, MFA, State);
async_local_answerer([], _MFA, _State) -> ok;
async_local_answerer([#ask_answerer{rid = Rid} | Rest],
                     MFA, State) ->
    case role_query:local_pid(by_id, Rid) of
        {ok, AnswererPid} ->
            catch role:apply(async, AnswererPid, MFA);
        _ -> skip
    end,
    async_local_answerer(Rest, MFA, State).

tick({answer_timeout, Mid, Sid}, State) ->
    server_commit_answer(Mid, Sid, State),
    remove;
tick(_, _) -> remove.

pop_next_id(State = #ask_state{next_ask_id =
                                   NextRecordId,
                               free_ask_ids = FreeIds}) ->
    {NextId, NewFreeIds, NewNextRecordId} =
        pop_next_id(FreeIds, NextRecordId),
    NewState = State#ask_state{next_ask_id =
                                   NewNextRecordId,
                               free_ask_ids = NewFreeIds},
    {ok, NextId, NewState}.

pop_next_id([], NextId) -> {NextId, [], NextId + 1};
pop_next_id([Id | Rest], NextId) -> {Id, Rest, NextId}.

free_id(State = #ask_state{free_ask_ids = FreeIds},
        Id) ->
    {ok,
     State#ask_state{free_ask_ids =
                         [Id | lists:delete(Id, FreeIds)]}};
free_id(Unknow, _Id) ->
    logger:error("未知的资源结构:~w", [Unknow], ask_mgr, 416),
    {ok, Unknow}.

sync_state(#ask_state{next_ask_id = NextAskId,
                      free_ask_ids = FreeIds}) ->
    Store = #ask_state_store{label = store,
                             next_ask_id = NextAskId, free_ask_ids = FreeIds},
    save(ask_state_tab, Store),
    ok.

