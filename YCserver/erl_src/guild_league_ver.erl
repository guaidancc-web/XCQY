do_rank_list([], L) -> {ok, lists:reverse(L)};
do_rank_list([S | T], Rank) ->
    case do_summary(S) of
        {ok, S1 = #guild_league_summary{}} ->
            do_rank_list(T, [S1 | Rank]);
        Else -> Else
    end.

