handle_info(spectral_box_create,
            State = #state{boxes = OldBoxesList, ref = OldRef}) ->
    case erlang:is_reference(OldRef) of
        true -> erlang:cancel_timer(OldRef);
        _ -> ok
    end,
    logger:debug("刷新宝箱", [], spectral_box, 228),
    unit_mgr:remove(OldBoxesList),
    erlang:put(spectral_box_map_list, []),
    BoxList = create_spectral_box(),
    TimeOut = get_timeout(),
    Ref = erlang:send_after(TimeOut * 1000,
                            self(),
                            spectral_box_create),
    NewState = State#state{boxes = BoxList, ref = Ref},
    {noreply, NewState};
handle_info({clear_one, UnitId},
            State = #state{boxes = OldBoxesList}) ->
    BoxList = lists:delete(UnitId, OldBoxesList),
    case erlang:get(spectral_box_map_list) of
        MapL = [_ | _] ->
            erlang:put(spectral_box_map_list,
                       lists:keydelete(UnitId, 1, MapL));
        _ -> erlang:put(spectral_box_map_list, [])
    end,
    {noreply, State#state{boxes = BoxList}};
handle_info(clear_all,
            State = #state{boxes = OldBoxesList}) ->
    unit_mgr:remove(OldBoxesList),
    erlang:put(spectral_box_map_list, []),
    {noreply, State#state{boxes = []}};
