-spec update_statue(pos_integer(), pos_integer()) -> ok.

update_statue(DunId, Floor) ->
    case get(dun_id) of
        DunId ->
            case dungeon_data:get_dun_lord({DunId, Floor}) of
                #dungeon_lord_data{is_lord = 0} -> ignore;
                #dungeon_lord_data{} ->
                    case ets:lookup(dungeon_lord, {DunId, Floor}) of
                        [#dungeon_lord{lords = Lords}] ->
                            do_update_statue(Lords, 1, DunId, Floor);
                        _ -> ignore
                    end;
                _ -> ok
            end;
        _ -> ok
    end.

