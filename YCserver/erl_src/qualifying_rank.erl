    NewNum = min(Num, 10),
    do_get_rank(Role, Type, Idx, NewNum).

do_get_rank(#role{pid = RolePid}, 2, Idx, Num) ->
    gen_server:cast(qualifying_rank,
                    {get_rank, RolePid, 2, Idx, Num}),
    ok;
do_get_rank(Role = #role{id = RoleId}, 1, Idx, Num) ->
    FriendRoles = friend:list_role(RoleId),
    FriendMark = friend_role_to_qualifying_mark(FriendRoles,
                                                []),
    SortFriendMark = util:keys_sort(keys(), FriendMark),
    Len = length(SortFriendMark),
    {PushIdx, PushRank} = case Len > 0 of
                              true ->
                                  GetIdx = case Idx > Len of
                                               true -> Len;
                                               false -> Idx
                                           end,
                                  {GetIdx,
                                   lists:sublist(SortFriendMark, GetIdx, Num)};
                              false -> {0, []}
                          end,
    role:link_send(Role,
                   13508,
                   {1, PushIdx, Len, PushRank}),
    ok.

