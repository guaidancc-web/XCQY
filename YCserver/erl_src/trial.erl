combat_over(Role = #role{m_trial =
                             Mtrial = #m_trial{order = Order, mode = Mode,
                                               round = AllRound,
                                               max_order_easy = MaxOrderEasy,
                                               max_order_hard = MaxOrderHard,
                                               direct_order = DirectOrder,
