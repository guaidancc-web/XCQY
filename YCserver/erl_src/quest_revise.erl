-spec do(#role{}) -> #role{}.

do(Role) ->
    MarriageRole = quest_marriage:revise(Role),
    CoupleRole = quest_couple:revise(MarriageRole),
    TeacherRole = quest_teacher:revise(CoupleRole),
    NewRole = TeacherRole,
    do_revise(NewRole).

do_revise(Role = #role{m_quest =
                           Mquest = #m_quest{quest = Quests}}) ->
    Now = date:unixtime(),
    AcceptTimeQuest = revise_accept_time(Quests, []),
    Quests0 = [Q
               || Q = #quest{end_time = EndT} <- AcceptTimeQuest,
                  EndT =:= 0 orelse EndT > Now],
    NewQuests = do_do(Role, quest, Quests0, []),
    DoRole = Role#role{m_quest =
                           Mquest#m_quest{quest = NewQuests}},
    PracRole = quest_prac:revise(DoRole),
    NewRole = PracRole,
    check_event([], NewRole).

do_list(Role, Label, Quests) ->
    do_do(Role, Label, Quests, []).

-spec check_quest_status(#role{}, #quest{}) -> #quest{}.

check_quest_status(Role,
                   Quest = #quest{progress = Progs}) ->
    check_status(Role, Quest, Progs).

check_event([], Role) -> Role;
check_event([I | T], Role) ->
    NRole = check_event(I, Role),
    check_event(T, NRole);
check_event({Event, SecType},
            Role = #role{s_event = NowEvent,
                         m_quest = Mquest = #m_quest{quest = QL}}) ->
    case lists:keyfind(SecType, #quest.sec_type, QL) of
        false when Event =:= NowEvent -> Role#role{s_event = 0};
        #quest{id = QuestId} when Event =/= NowEvent ->
            Role#role{m_quest =
                          Mquest#m_quest{quest =
                                             lists:keydelete(QuestId,
                                                             #quest.id,
                                                             QL)}};
        _ -> Role
    end.

do_do(_Role, _Label, [], Quests) -> Quests;
do_do(Role, Label = quest,
      [Quest = #quest{id = Id, finish = Finish,
                      progress = Progs1}
       | T],
      Quests) ->
    case quest_data:get(Id) of
        #quest_data{progress = Progs2} when Finish =:= 0 ->
            case camp_progs(lists:keysort(#quest_progress.id,
                                          Progs1),
                            Progs2,
                            [])
                of
                {ok, NewProgs} ->
                    NewQuest = check_status(Role, Quest, NewProgs),
                    do_do(Role, Label, T, [NewQuest | Quests]);
                false -> do_do(Role, Label, T, Quests)
            end;
        {error, data_not_exists} ->
            do_do(Role, Label, T, Quests);
        _ -> do_do(Role, Label, T, [Quest | Quests])
    end;
do_do(Role, Label = achievement,
      [Quest = #quest{id = Id, finish = Finish,
                      progress = Progs1, finish_time = FTime}
       | T],
      Quests) ->
    case achievement_data:get(Id) of
        #quest_data{progress = Progs2} when Finish =:= 0 ->
            case camp_progs(lists:keysort(#quest_progress.id,
                                          Progs1),
                            Progs2,
                            [])
                of
                {ok, NewProgs} ->
                    NewQuest = case check_status(Role, Quest, NewProgs) of
                                   Quest1 = #quest{finish = 1,
                                                   finish_time = 0} ->
                                       Quest1#quest{finish_time =
                                                        date:unixtime()};
                                   Quest1 -> Quest1
                               end,
                    do_do(Role, Label, T, [NewQuest | Quests]);
                false -> do_do(Role, Label, T, Quests)
            end;
        #quest_data{} when Finish =:= 1 andalso FTime =:= 0 ->
            do_do(Role,
                  Label,
                  T,
                  [Quest#quest{finish_time = date:unixtime()} | Quests]);
        #quest_data{} ->
            do_do(Role, Label, T, [Quest | Quests]);
        _ -> do_do(Role, Label, T, Quests)
    end;
do_do(Role, Label = goal,
      [Quest = #quest{id = Id, finish = Finish,
                      progress = Progs1}
       | T],
      Quests) ->
    case goal_data:get(Id) of
