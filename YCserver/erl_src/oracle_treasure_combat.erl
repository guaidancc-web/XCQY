combat_over(#combat{type = 70, winner = Winner,
                    loser = Loser,
                    start_args = #combat_start_args{ext_args = ExtArgs}}) ->
    Wave = get(oracle_treasure_wave),
    UseTime = get(oracle_treasure_wave_use_time),
    case Wave > 1 of
        true ->
            WinnerRole = [F
                          || F = #fighter{type = 1} <- Winner ++ Loser],
            case lists:keyfind(unit_id, 1, ExtArgs) of
                {_, BaseId} ->
                    OfferMates =
                        oracle_treasure_mgr:conver_offer_mate(WinnerRole, []),
                    logger:debug("结算龙王挑战战斗结算:~w",
                                 [OfferMates],
                                 oracle_treasure_combat,
                                 153),
                    LeaderId = case lists:keyfind(leader_id, 1, ExtArgs) of
                                   {_, _LeaderId} -> _LeaderId;
                                   _ -> {0, "", 0}
                               end,
                    AllMateId = [MateId
                                 || #oracle_treasure_offer_mate{id = MateId}
                                        <- OfferMates],
                    SortAllMateId = lists:keysort(1, AllMateId),
                    SptTeam = #oracle_treasure_team{leader_id = LeaderId,
                                                    team_mates = OfferMates,
                                                    wave = Wave - 1,
                                                    use_time = UseTime,
                                                    all_mate_id =
                                                        SortAllMateId},
                    [role_trigger:async_fire(RoleId,
                                             #evt_oracle_treasure_boss{})
                     || #oracle_treasure_offer_mate{id = RoleId}
                            <- OfferMates],
                    oracle_treasure_mgr:cast({combat_over,
                                              BaseId,
                                              SptTeam});
                _ ->
                    logger:error("结算龙王挑战战斗错误，错误的战斗开始参数:~w",
                                 [ExtArgs],
                                 oracle_treasure_combat,
                                 165),
                    ignore
            end;
        _ -> ignore
    end;
combat_over(_) -> ok.

combat_over(Role = #role{id = RoleId,
                         m_oracle_treasure =
                             Mst = #m_oracle_treasure{wave_reward =
                                                          WaveReward}},
            WinOrLose, _ExitArgs, #{wave := Wave}) ->
    CrossWave = Wave - 1,
    logger:debug("~w进行龙王试炼战斗结算:~w, 经历~w波",
                 [RoleId, WaveReward, CrossWave],
                 oracle_treasure_combat,
                 178),
    ResetRole = Role#role{m_oracle_treasure =
                              Mst#m_oracle_treasure{wave_reward = []}},
    oracle_treasure_role:push(ResetRole),
    CombatOverMsg =
        notice:format(lang:get("您和队友披荆斩棘，一路上打败了~ts，以下是您收集到的战利品:"),
                      [{string_2,
                        5,
                        util:flist(lang:get("~w波敌人"), [CrossWave])}]),
    Flag = case WinOrLose of
               win -> 1;
               loss -> 0;
               _ -> 0
           end,
    CombatOverData = {Flag, CombatOverMsg, WaveReward},
    push_combat_over(ResetRole, CombatOverData),
    UnbindRewardList = [{Assets, 0, Val}
                        || {Assets, Val} <- WaveReward],
    case oracle_treasure_data:get_wave_info(CrossWave) of
        #{honor_id := HonorId} ->
            case honor_mgr:lookup(oracle_treasure_honor_boss) of
                #honor_info{list = HonorList} ->
                    case lists:member({RoleId, HonorId}, HonorList) of
                        true -> ignore;
                        _ ->
                            honor_mgr:add(oracle_treasure_honor_boss,
                                          [{RoleId, HonorId}],
                                          date:unixtime2() +
                                              date:week_next_diff([5],
                                                                  12 * 3600))
                    end;
                _ -> ignore
            end;
        _ -> ignore
    end,
    Msg = case CrossWave of
              0 -> lang:get("通关失败，寻找强力队友通关更多阶段吧！");
              _ when CrossWave < 5 ->
                  notice:format(lang:get("恭喜您通关第~ts阶段，寻找强力队友通关更多阶段吧！"),
                                [{string_2, 1, CrossWave}]);
              _ -> lang:get("恭喜您完成龙王的试炼，结算时可获得大量奖励！")
          end,
    notice:send(Role, 3, Msg),
    Gain = format:val_to_gain(UnbindRewardList),
    case is_list(Gain) andalso length(Gain) > 0 of
        true ->
            case role_gain:do(Gain, ResetRole) of
                {ok, GainRole} -> GainRole;
                _ ->
                    Title = lang:get("龙王试炼"),
                    Content = lang:get("由于你的背包已满，您龙王试炼的奖励通过邮件发送,请查收:"),
                    mail:send(RoleId,
                              #{title => Title, content => Content,
                                items => UnbindRewardList}),
                    ResetRole
            end;
        false -> ResetRole
    end.

