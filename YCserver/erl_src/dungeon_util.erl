    ValList = [A || A = {_, _} <- calc_gain(Role, DunId)],
    UnitGains = calc_unit_exp(Role, DunId),
    [{DunId, do_acc_unit_rewards(UnitGains, ValList)}
     | list_gains(T, Role)].

calc_unit_exp(Role, DunId) ->
    case dungeon_data:get(DunId) of
        #dungeon_base{unit_list = L} ->
            calc_unit_exp(L, Role, []);
        _ -> []
    end.

calc_unit_exp([], _Role, L) -> L;
calc_unit_exp([{[UnitBaseId]} | T], Role, L) ->
    case unit_data:get(UnitBaseId) of
        #unit_data{gain = Gain} ->
            NL = do_calc_unit_exp(Gain, Role, L),
            calc_unit_exp(T, Role, NL);
        _ -> calc_unit_exp(T, Role, L)
    end.

do_calc_unit_exp([], _, L) -> L;
do_calc_unit_exp([{Model, Type = 90010} | T],
                 Role = #role{lev = Lev}, L) ->
    case levup_data:get_exp({Model, Lev}) of
        #{exp := Exp} ->
            case lists:keyfind(Type, 1, L) of
                {Type, V} ->
                    do_calc_unit_exp(T,
                                     Role,
                                     lists:keyreplace(Type,
                                                      1,
                                                      L,
                                                      {Type, V + Exp}));
                _ -> do_calc_unit_exp(T, Role, [{Type, Exp} | L])
            end;
        _ -> do_calc_unit_exp(T, Role, L)
    end;
do_calc_unit_exp([{Model, Type = 90005} | T], Role,
                 L) ->
    case pet:get_war_pet(Role) of
        {ok, #pet{lev = PetLev}} ->
            case levup_data:get_exp({Model, PetLev}) of
                #{pet_exp := Exp} ->
                    case lists:keyfind(Type, 1, L) of
                        {Type, V} ->
                            do_calc_unit_exp(T,
                                             Role,
                                             lists:keyreplace(Type,
                                                              1,
                                                              L,
                                                              {Type, V + Exp}));
                        _ -> do_calc_unit_exp(T, Role, [{Type, Exp} | L])
                    end;
                _ -> do_calc_unit_exp(T, Role, L)
            end;
        _ -> do_calc_unit_exp(T, Role, L)
    end;
do_calc_unit_exp([_ | T], Role, L) ->
    do_calc_unit_exp(T, Role, L).

calc_normal_gain(Role = #role{lev = Lev,
                              m_dungeon =
                                  #m_dungeon{unit_rewards = UnitRewards}},
                 DunId) ->
    LevOver = case dungeon_data:get(DunId) of
                  #dungeon_base{lev_max = LevMax}
                      when LevMax > 0 andalso Lev > LevMax ->
                      true;
                  _ -> false
              end,
    DungeonPass = get_pass(Role),
    Total = lists:sum([min(3, Done)
                       || {_, Done} <- DungeonPass, is_integer(Done)]),
    TotalLimit = dungeon_data:get_day_limit(Lev),
    case lists:keyfind(DunId, 1, DungeonPass) of
        _ when LevOver ->
            Msg = lang:get("当前低级副本，无法获得结算奖励"),
            notice:send(Role, 3, Msg),
            {[], Role};
        _ when Total >= TotalLimit andalso UnitRewards =:= [] ->
            Msg = lang:get("今日挑战次数已用尽，无法获得结算奖励"),
            notice:send(Role, 3, Msg),
            {[], Role};
        {DunId, N} when N >= 3 andalso UnitRewards =:= [] ->
            Msg = lang:get("今日挑战次数已用尽，无法获得结算奖励"),
            notice:send(Role, 3, Msg),
            {[], Role};
        _ ->
            ValList = calc_gain(Role, DunId),
            GainList = format:val_to_gain(ValList),
            Role2 = case GainList of
                        [_ | _] ->
                            case role_gain:do_notice(GainList, Role) of
                                {ok, Role1} -> Role1;
                                {false, #gain{reason = bag_full}} ->
                                    Title = lang:get("副本结算"),
                                    Content = lang:get("副本结算时，背包已满"),
                                    mail:send(Role,
                                              #{title => Title,
                                                content => Content,
                                                items => ValList}),
                                    notice:send(Role,
                                                3,
                                                lang:get("背包已满，奖励已通过邮件发放")),
                                    Role;
                                {false, _} -> Role
                            end;
                        _ -> Role
                    end,
            Flag = var:get_var(Role2, other, 2155, {0, 0}),
            case Flag of
                {DunId, 1} ->
                    Role3 = var:set_var(Role2, other, 2155, {0, 0}),
                    NewRole = role_trigger:fire(#evt_dungeon_pass{id =
                                                                      DunId},
                                                Role3),
                    {ValList, NewRole};
                _ -> {[], Role}
            end
    end.

update_pass(Role = #role{lev = Lev}, DunId) ->
    case dungeon_data:get(DunId) of
        #dungeon_base{lev_max = LevMax}
            when LevMax > 0 andalso Lev > LevMax ->
            Role;
        #dungeon_base{type = 2} ->
            {Label, Key} = {day_five, 104},
            DungeonPass = get_pass(Role),
            case lists:keyfind(DunId, 1, DungeonPass) of
                {_DunId, N} when N >= 3 ->
                    notice:pop(Role, 2, lang:get("今日副本次数不足，无法获得结算奖励")),
                    NewDungeonPass = lists:keyreplace(DunId,
                                                      1,
                                                      DungeonPass,
                                                      {DunId, N + 1}),
                    var:set_var(Role, Label, Key, NewDungeonPass);
                {DunId, N} ->
                    NewDungeonPass = lists:keyreplace(DunId,
                                                      1,
                                                      DungeonPass,
                                                      {DunId, N + 1}),
                    var:set_var(Role, Label, Key, NewDungeonPass);
                _ ->
                    NewDungeonPass = [{DunId, 1} | DungeonPass],
                    var:set_var(Role, Label, Key, NewDungeonPass)
            end;
        _ -> Role
    end.

