apply_evt(#evt_pay{sn = _Sn, gold = Gold,
                   source = Source},
          Role = #role{m_camp_recharge =
                           MCampRecharge = #m_camp_recharge{recharges =
                                                                Recharges}}) ->
    case check_camp() of
        1 ->
            case Source of
                0 ->
                    {CampID, StartTime, _} = get_camp(),
                    CurDays = date:day_diff(StartTime, date:unixtime()) + 1,
                    Recharge = #camp_recharge{point = Point} =
                                   get_cur_camp_recharge(Role),
                    NPoint = round(Point + Gold),
                    NRecharge = Recharge#camp_recharge{point = NPoint},
                    NRecharges = lists_ext:multikeystore([{CurDays,
                                                           #camp_recharge.days},
                                                          {CampID,
                                                           #camp_recharge.camp_id}],
                                                         Recharges,
                                                         NRecharge),
                    NRole = Role#role{m_camp_recharge =
                                          MCampRecharge#m_camp_recharge{recharges
                                                                            =
                                                                            NRecharges}},
                    push(NRole),
                    {ok, NRole};
                _ -> ok
            end;
        0 -> ok
    end;
apply_evt(_, _) -> ok.

push(Role) ->
    {_, StartTime, _} = get_camp(),
    CurDays = date:day_diff(StartTime, date:unixtime()) + 1,
    push(Role, CurDays).

push(Role = #role{pid = PID}, Days) ->
    case check_camp() of
        1 ->
            RandomItems = get_cur_items(Role, Days),
            BoxList = get_box_list(Role, Days),
            RandomCost = case
                             camp_recharge_data:get_random_cost(Days)
                             of
                             List when is_list(List) -> List;
                             _ -> []
                         end,
            #camp_recharge{point = Point, rd_times = Times} =
                get_days_camp_recharge(Role, Days),
            role:pack_send(PID,
                           17883,
                           {Days,
                            Point,
                            Times,
                            RandomItems,
                            BoxList,
                            RandomCost});
        _ -> ignore
    end,
    ok.

