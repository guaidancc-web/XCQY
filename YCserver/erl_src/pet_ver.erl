do(MPet = #m_pet{ver = 2}) ->
    case parse_field(MPet, [pets]) of
        {error, Reason} -> {error, Reason};
        {ok, NewMPet} -> {ok, NewMPet}
    end;
do(_MPet) -> {error, lang:get("宠物数据版本不正确")}.

do_store(undefined) -> do_store(#m_pet_store{});
do_store(MPetStore = #m_pet_store{ver = 1}) ->
    case parse_field(MPetStore, [pets]) of
        {error, Reason} -> {error, Reason};
        {ok, NewMPetStore} -> {ok, NewMPetStore}
    end;
do_store(_MPet) -> {error, lang:get("宠物仓库数据版本不正确")}.

parse_field(MPet, []) -> {ok, MPet};
parse_field(MPet, [Field | T]) ->
    case do_parse_field(Field, MPet) of
        {error, Reason} -> {error, Reason};
        {ok, NewMPet} -> parse_field(NewMPet, T)
    end.

do_parse_field(pets,
               MPetStore = #m_pet_store{pets = Pets}) ->
    case do_pets(Pets, []) of
        {error, Reason} -> {error, Reason};
        {ok, NewPets} ->
            {ok, MPetStore#m_pet_store{pets = NewPets}}
    end;
do_parse_field(pets, MPet = #m_pet{pets = Pets}) ->
    case do_pets(Pets, []) of
        {error, Reason} -> {error, Reason};
        {ok, NewPets} -> {ok, MPet#m_pet{pets = NewPets}}
    end.

-spec do_pets([tuple()], [#pet{}]) -> {ok, [#pet{}]} |
                                      {error, Reason :: string()}.

do_pets([], Pets) -> {ok, lists:reverse(Pets)};
do_pets([I | T], Pets) ->
    case do_pet(I) of
        {ok, Pet} -> do_pets(T, [Pet | Pets]);
        {error, Reason} -> {error, Reason}
    end.

