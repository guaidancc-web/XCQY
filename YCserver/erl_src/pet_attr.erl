batch_calc(Pets, Role) ->
    SortPets = lists:keysort(#pet.spirit_attached, Pets),
    do_batch_calc(SortPets, Role, []).

do_batch_calc([], Role = #role{m_pet = Mpet}, Pets) ->
    Role#role{m_pet = Mpet#m_pet{pets = Pets}};
do_batch_calc([Pet | T], Role, Pets) ->
    {ok,
     NewPet = #pet{id = PetId},
     NRole = #role{m_pet = Mpet = #m_pet{pets = NPets}}} =
        calc(Pet, Role, false),
    NewRole = NRole#role{m_pet =
                             Mpet#m_pet{pets =
                                            lists:keyreplace(PetId,
                                                             #pet.id,
                                                             NPets,
                                                             NewPet)}},
    do_batch_calc(T, NewRole, [NewPet | Pets]).

batch_calc_store(Pets, Role) ->
    do_batch_calc_store(Pets, Role, []).

do_batch_calc_store([],
                    Role = #role{m_pet_store = MpetStore}, Pets) ->
    Role#role{m_pet_store =
                  MpetStore#m_pet_store{pets = Pets}};
do_batch_calc_store([Pet | T], Role, Pets) ->
    {ok, NewPet, NewRole} = calc(Pet, Role, false),
    do_batch_calc_store(T, NewRole, [NewPet | Pets]).

calc_fc(#role{m_pet = #m_pet{pets = Pets}}) ->
    case util:keys_sort([#pet.talent], Pets) of
        PetList = [_ | _] -> do_calc_fc(PetList, 3, 0);
        _ -> 0
    end.

do_calc_fc([], _, Fc) -> Fc;
do_calc_fc(_, Num, Fc) when Num =< 0 -> Fc;
do_calc_fc([#pet{talent = Talent} | T], Num, Fc) ->
    do_calc_fc(T, Num - 1, Talent + Fc);
do_calc_fc([_ | T], Num, Fc) ->
    do_calc_fc(T, Num - 1, Fc).

-spec calc(Pet :: #pet{}, Role :: #role{}) -> {ok,
                                               #pet{},
                                               #role{}}.

calc(Pet, Role) -> calc(Pet, Role, true).

calc(Pet = #pet{attr = #attr{}, hp = Hp, mp = Mp,
                hp_max = HpMax, mp_max = MpMax},
     Role = #role{}, NeedAttached) ->
    InitCalc = #attr_calc{attr = #attr{},
                          attr_no_ratio = #attr{speed = 0},
                          ratio = #attr{speed = 0},
                          attr_no_fc = #attr{speed = 0},
                          ratio_no_fc = #attr{speed = 0}},
    Pet2 = pet_stone:do_calc_stone_attr(Pet),
    AttrCalc1 = do_calc(base, InitCalc, Pet2, Role),
    AttrCalc2 = do_calc([point,
                         stone,
                         skill,
                         possess,
                         skill_prac,
                         handbook,
                         buff,
                         guild_element,
                         mount,
                         spirit,
                         unreal,
                         talisman],
                        AttrCalc1,
                        Pet2,
                        Role),
    NewAttrCalc = AttrCalc2,
    PointAttrCalc = calc_pet_point(Pet2, NewAttrCalc),
    HpPer = Hp / HpMax,
    MpPer = Mp / MpMax,
    NewAttr = #attr{hp_max = NewHpMax, mp_max = NewMpMax} =
                  merge_attr(Pet, PointAttrCalc),
    NewHp = util:check_range(round(HpPer * NewHpMax),
                             1,
                             NewHpMax),
    NewMp = util:check_range(round(MpPer * NewMpMax),
                             1,
                             NewMpMax),
    Pet3 = Pet2#pet{hp = NewHp, mp = NewMp,
                    hp_max = NewHpMax, mp_max = NewMpMax, attr = NewAttr},
    {HandbookNum, StarHandBookNum, HandBookAttr} =
        handbook_attr:calc_handbook_show(Pet3, Role),
    NewPet = calc_talent(normal,
                         Pet3#pet{handbook_attr = HandBookAttr,
                                  handbook_num = HandbookNum,
                                  star_handbook_num = StarHandBookNum}),
    NewRole = case NeedAttached of
                  true -> pet_spirit:calc_attached(NewPet, Role);
                  _ -> Role
              end,
    {ok, NewPet, NewRole};
calc(Pet, Role, NeedAttached) ->
    calc(Pet#pet{attr = #attr{}}, Role, NeedAttached).

calc_talent(Pet) -> calc_talent(recalc, Pet).

calc_talent(normal, Pet) ->
    AptitudeTalent = calc_aptitude_talent(Pet),
    SkillTalent = calc_skill_talent(Pet),
    GrowthTalent = calc_growth_talent(Pet),
    Talent = AptitudeTalent + SkillTalent + GrowthTalent,
    Pet#pet{talent = round(Talent / 3)};
calc_talent(recalc, Pet) ->
    Pet1 = Pet,
    AptitudeTalent = calc_aptitude_talent(Pet1),
    SkillTalent = calc_skill_talent(Pet1),
    GrowthTalent = calc_growth_talent(Pet1),
    Talent = AptitudeTalent + SkillTalent + GrowthTalent,
    Pet1#pet{talent = round(Talent / 3)}.

calc_aptitude_talent(#pet{pet_attr =
                              #pet_attr{hp_aptitude = HpA, phy_aptitude = PhyA,
                                        pdef_aptitude = PdefA,
                                        magic_aptitude = MagicA,
                                        aspd_aptitude = AspdA}}) ->
    round(HpA + PhyA + PdefA + MagicA + AspdA).

calc_skill_talent(#pet{skills = Skills}) ->
    Fun = fun (#pet_skill{step = Step}, Point) ->
                  case Step of
                      1 -> 300 + Point;
                      2 -> 600 + Point;
                      3 -> 690 + Point;
                      4 -> 690 + Point;
                      _ -> Point
                  end
          end,
    lists:foldl(Fun, 0, Skills).

calc_growth_talent(#pet{growth = Growth}) ->
    erlang:max(0, (Growth - 1000) / 2) * 3.

levup(Pet, Role) -> levup(Pet, Role, 0).

levup(Pet = #pet{lev = Lev}, #role{lev = RoleLev},
      Limit)
    when Lev >= RoleLev + 5 + Limit ->
    Pet#pet{exp = 0};
levup(Pet = #pet{base_id = 20013, lev = Lev}, _Role,
      _Limit)
    when Lev >= 30 ->
    Pet#pet{exp = 0};
levup(Pet = #pet{lev = Lev, base_id = BaseId, exp = Exp,
                 pet_attr = PetAttr},
      _Role, _Limit) ->
    case pet_data:get_exp(Lev) of
        MaxExp when MaxExp > 0 ->
            case Exp >= MaxExp of
                true ->
                    NextMaxExp = pet_data:get_exp(Lev + 1),
                    NewPetAttr = auto_point(PetAttr, BaseId, Lev + 1),
                    Pet#pet{lev = Lev + 1, exp = Exp - MaxExp,
                            max_exp = NextMaxExp, pet_attr = NewPetAttr};
                false -> Pet
            end;
        _ -> Pet
    end.

auto_point(PetAttr = #pet_attr{pre_str = Prestr,
                               pre_con = Precon, pre_mag = Premag,
                               pre_agi = Preagi, pre_end = PreEnd, p_str = Pstr,
                               p_con = Pcon, p_mag = Pmag, p_agi = Pagi,
                               p_end = Pend, point = Point},
           BaseId, PetLev) ->
    case Prestr + Precon + Premag + Preagi + PreEnd =:= 5 of
        true ->
            PetAttr#pet_attr{p_str = Pstr + Prestr + 1,
                             p_con = Pcon + Precon + 1,
                             p_mag = Pmag + Premag + 1,
                             p_agi = Pagi + Preagi + 1,
                             p_end = Pend + PreEnd + 1};
        false ->
            case pet_data:set_point(BaseId) of
                {Prestr1, Precon1, Premag1, Preagi1, PreEnd1}
                    when Prestr1 + Precon1 + Premag1 + Preagi1 + PreEnd1 =:=
                             5
                             andalso PetLev =< 20 ->
                    PetAttr#pet_attr{p_str = Pstr + Prestr1 + 1,
                                     p_con = Pcon + Precon1 + 1,
                                     p_mag = Pmag + Premag1 + 1,
                                     p_agi = Pagi + Preagi1 + 1,
                                     p_end = Pend + PreEnd1 + 1};
                _ ->
                    PetAttr#pet_attr{point = Point + 5, p_str = Pstr + 1,
                                     p_con = Pcon + 1, p_mag = Pmag + 1,
                                     p_agi = Pagi + 1, p_end = Pend + 1}
            end
    end.

merge_attr(_Pet,
           _InitCalc = #attr_calc{attr = Attr,
                                  attr_no_ratio = AttrNoRatio,
                                  ratio = AttrRatio, attr_no_fc = AttrNoFc,
                                  ratio_no_fc = AttrRatioNoFc}) ->
    Attr1 = attr:do_math_ratio(Attr,
                               attr:do_math_add(AttrRatio, AttrRatioNoFc)),
    Attr2 = attr:do_math_add(Attr1, AttrNoRatio),
    Attr3 = attr:do_math_add(Attr2, AttrNoFc),
    NewAttr = attr:round_attr(Attr3),
    NewAttr.

do_calc([], Ac, _Pet, _Role) -> Ac;
do_calc([Label | T], Ac, Pet, Role) ->
    NewAc = do_calc(Label, Ac, Pet, Role),
    do_calc(T, NewAc, Pet, Role);
do_calc(base, Ac = #attr_calc{attr = AttrVal},
        #pet{base_id = BaseId, lev = Lev, pet_attr = PetAttr},
        _Role) ->
    Attr = pet_data:get_base_attr(Lev),
    BaseRatio = pet_data:get_base_ratio(BaseId),
    AptiRatio = pet_data:get_apti_ratio(Lev),
    Attr1 = calc_base(Attr, BaseRatio, PetAttr, AptiRatio),
    Attr2 = attr:do_math_add(Attr1, AttrVal),
    Ac#attr_calc{attr = Attr2};
do_calc(skill, Ac = #attr_calc{}, Pet, _Role) ->
    NewAc = pet_skill:calc_attr(Ac, Pet),
    NewAc;
do_calc(stone, Ac = #attr_calc{}, Pet, _Role) ->
    NewAc = pet_stone:calc_attr(Ac, Pet),
    NewAc;
do_calc(point, Ac = #attr_calc{},
        #pet{pet_attr =
                 #pet_attr{p_str = Str, p_con = Con, p_mag = Mag,
                           p_agi = Agi, p_end = End}},
        _Role) ->
    Attr = attr_type:to_attr(base,
                             [{101, Str},
                              {102, Con},
                              {103, Mag},
                              {104, Agi},
                              {105, End}]),
    case attr_type:do_attr(Attr, Ac) of
        {false, Reason} ->
            logger:error("宠物加点计算出错[~w,~w,~w,~w,~w]:[~w]",
                         [Str, Con, Mag, Agi, End, Reason],
                         pet_attr,
                         221),
            Ac;
        {ok, NewAc} -> NewAc
    end;
do_calc(skill_prac, Ac, _Pet, Role) ->
    skill_prac_attr:calc_pet(Ac, Role);
do_calc(handbook, Ac, Pet, Role) ->
    handbook_attr:calc_pet(Ac, Pet, Role);
do_calc(buff, Ac, _Pet, Role) ->
    buff_attr:calc_pet(Ac, Role);
do_calc(guild_element, Ac, _Pet, Role) ->
    guild_role:calc_pet(Ac, Role);
do_calc(mount, Ac, _Pet, Role) ->
    MountAttr = mount_attr:calc_pet(Ac, Role),
    MountAttr;
do_calc(spirit, Ac, Pet, Role) ->
    SpiritAttr = pet_spirit:calc(Ac, Pet, Role),
    SpiritAttr;
do_calc(unreal, Ac, _Pet = #pet{unreal = UnReal},
        _Role) ->
    do_calc_unreal(Ac, UnReal);
do_calc(talisman, Ac, _Pet, Role) ->
    talisman_attr:calc_pet(Ac, Role);
do_calc(_, Ac, _Pet, _Role) -> Ac.

calc_pet_point(#pet{lev = Lev, growth = Growth},
               InitCalc = #attr_calc{attr = Attr}) ->
    #attr{strength = Str1, constitution = Con1,
          magic = Mag1, agility = Agi1, endurance = End1} =
        Attr,
    Lstr = pet_data:get_point_attr({101, Lev}),
    Lcon = pet_data:get_point_attr({102, Lev}),
    Lmag = pet_data:get_point_attr({103, Lev}),
    Lagi = pet_data:get_point_attr({104, Lev}),
    Lend = pet_data:get_point_attr({105, Lev}),
    V1 = attr_type:to_attr(base,
                           calc_point_attr(Lstr,
                                           Lcon,
                                           Lmag,
                                           Lagi,
                                           Lend,
                                           Str1,
                                           Con1,
                                           Mag1,
                                           Agi1,
                                           End1,
                                           Growth)),
    case attr_type:do_attr(V1, InitCalc) of
        {false, Reason} ->
            logger:error("宠物点属性换算出错[~w]:[~w]",
                         [V1, Reason],
                         pet_attr,
                         269),
            InitCalc;
        {ok, NewAc} -> NewAc
    end.

calc_point_attr(Lstr, Lcon, Lmag, Lagi, Lend, Str, Con,
                Mag, Agi, End, Growth) ->
    L1 = do_calc_point(Lstr, Str, Growth),
    L2 = do_calc_point(Lcon, Con, Growth),
    L3 = do_calc_point(Lmag, Mag, Growth),
    L4 = do_calc_point(Lagi, Agi, Growth),
    L5 = do_calc_point(Lend, End, Growth),
    L1 ++ L2 ++ L3 ++ L4 ++ L5.

do_calc_point(_L, 0, _) -> [];
do_calc_point(L, Val, Growth) ->
    [{Name, round(V * Val * Growth / 100000)}
     || {Name, V} <- L].

calc_base(Attr = #attr{hp_max = HpMax, mp_max = MpMax,
                       phy_dmg = PhyDmg, magic_dmg = MagicDmg,
                       phy_def = PhyDef, magic_def = MagicDef,
                       atk_speed = AtkSpeed},
          {RatioHpMax,
           RatioMpMax,
           RatioPhy,
           RatioMagic,
           RatioPdef,
           RatioMdef,
           RatioAspd},
          #pet_attr{hp_aptitude = HpA, phy_aptitude = PhyA,
                    pdef_aptitude = PdefA, magic_aptitude = MagicA,
                    aspd_aptitude = AspdA},
          {AptiHp,
           AptiMp,
           AptiPhy,
           AptiPdef,
           AptiMagic,
           AptiMdef,
           AptiAspd}) ->
    Attr#attr{hp_max =
                  round(HpMax * RatioHpMax / 100 + HpA * AptiHp / 1000),
              mp_max =
                  round(MpMax * RatioMpMax / 100 +
                            MagicA * AptiMp / 1000),
              phy_dmg =
                  round(PhyDmg * RatioPhy / 100 + PhyA * AptiPhy / 1000),
              magic_dmg =
                  round(MagicDmg * RatioMagic / 100 +
                            MagicA * AptiMagic / 1000),
              phy_def =
                  round(PhyDef * RatioPdef / 100 +
                            PdefA * AptiPdef / 1000),
              magic_def =
                  round(MagicDef * RatioMdef / 100 +
                            MagicA * AptiMdef / 1000),
              atk_speed =
                  round(AtkSpeed * RatioAspd / 100 +
                            AspdA * AptiAspd / 1000)};
calc_base(Attr, _BaseRatio, _PetAttr, _AptiRatio) ->
    logger:error("错误的宠物属性计算[BaseRatio:~w][AptiRatio:~w]",
                 [_BaseRatio, _AptiRatio],
                 pet_attr,
                 337),
    Attr.

do_calc_unreal(Ac, []) -> Ac;
do_calc_unreal(Ac,
               [#pet_unreal{item_id = ItemId} | T]) ->
    Ac2 = case pet_data:get_unreal(ItemId) of
              #pet_unreal_data{attr = AttrList} ->
                  AttrList1 = attr_type:to_attr(fixed, AttrList),
                  case attr_type:do_attr(AttrList1, Ac) of
                      {false, Reason} ->
                          logger:error("宠物幻化属性计算失败:~w",
                                       [Reason],
                                       pet_attr,
                                       349),
                          Ac;
                      {ok, NewAc} -> NewAc
                  end;
              _ -> Ac
          end,
    do_calc_unreal(Ac2, T).

extra_attr(#role{m_pet = #m_pet{pets = Pets}} = Role,
           PetID) ->
    case lists:keyfind(PetID, #pet.id, Pets) of
        Pet = #pet{} ->
            InitCalc = #attr_calc{attr = #attr{},
                                  attr_no_ratio = #attr{speed = 0},
                                  ratio = #attr{speed = 0},
                                  attr_no_fc = #attr{speed = 0},
                                  ratio_no_fc = #attr{speed = 0}},
            AttrCalc2 = do_calc(talisman, InitCalc, Pet, Role),
            NewAttrCalc = AttrCalc2,
            PointAttrCalc = calc_pet_point(Pet, NewAttrCalc),
            TalismanAttr = merge_attr(Pet, PointAttrCalc),
            role:pack_send(Role,
                           10567,
                           {PetID, [{1, TalismanAttr}]});
        _ ->
            logger:error("不存在的宠物，弄个假的忽略下他吧 ：Role: ~p ~nPetID: ~p",
                         [Role#role.id, PetID],
                         pet_attr,
                         370),
            role:pack_send(Role, 10567, {PetID, [{1, #attr{}}]})
    end,
    ok.

