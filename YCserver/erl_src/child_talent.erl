add_talent(Role = #role{id = RoleId}, ChildId,
           Skills) ->
    case child_util:find_child(Role, ChildId, [3]) of
        {true,
         Child = #child{talent_skills = TalentSkills,
                        name = ChildName}} ->
            case do_add_talent(Role,
                               Skills,
                               TalentSkills,
                               ChildName)
                of
                {ok, NewTalentSkills} ->
                    NewChild = Child#child{talent_skills = NewTalentSkills},
                    NewRole = child:update_kids(Role, NewChild),
                    case child_util:update_child(NewRole, NewChild) of
                        true ->
                            child_util:push(NewRole, 18607, NewChild),
                            NewRole1 = child_util:evt_child(NewRole, NewChild),
                            child_util:notice_code(RoleId,
                                                   NewChild,
                                                   18607,
                                                   {[NewChild]}),
                            child_util:notice_update(RoleId, NewChild),
                            log:child(NewRole1, "天赋战斗加经验", Child, NewChild),
                            {ok, NewRole1};
                        {false, Reason} -> {false, Reason}
                    end;
                _ -> {ok, Role}
            end;
        _ -> {ok, Role}
    end.

do_add_talent(_Role, [], TalentSkills, _) ->
    {ok, TalentSkills};
do_add_talent(Role, [Id | T], TalentSkills,
              ChildName) ->
    case lists:keyfind(Id,
                       #child_talent_skill.id,
                       TalentSkills)
        of
        Sk = #child_talent_skill{exp = Exp, lev = Lev} ->
            case skill_data:get_child_talent({Id, Lev}) of
                #{max_lev := Lev} ->
                    do_add_talent(Role, T, TalentSkills, ChildName);
                #{max_exp := MaxExp} when Exp >= MaxExp ->
                    do_add_talent(Role, T, TalentSkills, ChildName);
                #{max_exp := MaxExp} ->
                    SkillName = case skill_data:get_child_talent(Id) of
                                    #{name := _SkillName} -> _SkillName;
                                    _ -> lang:get("")
                                end,
                    Msg =
                        notice:format(lang:get("~ts的天赋技能~ts熟练度+1{face_1,56}"),
                                      [{string_2, 1, ChildName},
                                       {string_2, 1, SkillName}]),
                    notice:send(Role, 3, Msg),
                    do_add_talent(Role,
                                  T,
                                  lists:keyreplace(Id,
                                                   #child_talent_skill.id,
                                                   TalentSkills,
                                                   Sk#child_talent_skill{exp =
                                                                             min(MaxExp,
                                                                                 Exp
                                                                                     +
                                                                                     1)}),
                                  ChildName);
                _ -> do_add_talent(Role, T, TalentSkills, ChildName)
            end;
        _ -> do_add_talent(Role, T, TalentSkills, ChildName)
    end.

