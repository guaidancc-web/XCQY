    NewVer = Ver + 1,
    Fun1 = fun ({mount,
                 _MountVer,
                 _Index,
                 _MountBaseId,
                 _TransformationId,
                 _Lev,
                 _SkillPoint,
                 _FailTimes,
                 _UpgradeLev,
                 _LiveStatus,
