get_box(_, RoleId, Pid) ->
    Max = 3,
    case get({get_box, RoleId}) of
        Val when is_integer(Val) ->
            NewVal = Val + 1,
            put({get_box, RoleId}, NewVal),
            case NewVal >= Max of
                true ->
                    role:apply(async,
                               Pid,
                               {dungeon,
                                role_exit_apply,
                                [notice:format(lang:get("已拾取~ts个宝箱，被~ts抛了出来{face_1,22}"),
                                               [{string_2, 5, Max},
                                                {string_2,
                                                 5,
                                                 lang:get("冒险秘境")}])]});
                _ -> ignore
            end;
        _ -> put({get_box, RoleId}, 1)
    end,
    ok.

