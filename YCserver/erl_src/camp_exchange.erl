reward(Role = #role{m_campaign =
                        #m_campaign{camp_exchange =
                                        OldCampEx = #camp_exchange{camp_id =
                                                                       OldCampId}}},
       ELev, Id) ->
    Now = date:unixtime(),
    {Result, Day2} = case get_camp() of
                         {OldCampId, St, ET} when Now >= St andalso Now =< ET ->
                             Day = date:day_diff(St, Now),
                             {{ok, OldCampEx}, Day};
                         {CampId, St, ET} when Now >= St andalso Now =< ET ->
                             Day = date:day_diff(St, Now),
                             {{ok, #camp_exchange{camp_id = CampId}}, Day};
                         _E ->
                             Day = 0,
                             logger:debug(": ~w", [_E], camp_exchange, 182),
                             {{false, lang:get("不在活动期间")}, Day}
                     end,
    case Result of
        {ok, #camp_exchange{lev = OldELev}}
            when ELev > OldELev + 1 ->
            {false, lang:get("批次条件不足，不能兑换该物品")};
        {ok,
         CampEx = #camp_exchange{list = List,
                                 camp_id = CampId1}} ->
            DayList = var:get_var(Role, other, {606, CampId1}, []),
            OldNum2 = case lists:keyfind(Id, 1, List) of
                          {_, OldNum} -> OldNum;
                          _ -> 0
                      end,
            DayNum = case lists:keyfind(Id, 1, DayList) of
                         {_, TIdNum} -> TIdNum;
                         _ -> 0
                     end,
            case camp_exchange_data:get({ELev, Id}) of
                #camp_exchange_data{min_day = MinDay, max_day = MaxDay}
                    when Day2 < MinDay orelse Day2 > MaxDay ->
                    {false, lang:get("该礼包已过期")};
                Cfg = #camp_exchange_data{camp_max = 0, pre_id = 0,
                                          pre_num = 0} ->
                    do_reward(Role,
                              CampEx,
                              OldNum2,
                              Cfg,
                              #{day_list => DayList, day_num => DayNum});
                #camp_exchange_data{camp_max = Max}
                    when Max > 0 andalso DayNum >= Max ->
                    {false, lang:get("该物品兑换已满")};
                Cfg = #camp_exchange_data{pre_id = 0, pre_num = 0} ->
                    do_reward(Role,
                              CampEx,
                              OldNum2,
                              Cfg,
                              #{day_list => DayList, day_num => DayNum});
                Cfg = #camp_exchange_data{pre_id = PreId,
                                          pre_num = PreNum} ->
                    case lists:keyfind(PreId, 1, List) of
                        {_, TIdNum2} when TIdNum2 >= PreNum ->
                            do_reward(Role,
                                      CampEx,
                                      OldNum2,
                                      Cfg,
                                      #{day_list => DayList,
                                        day_num => DayNum});
                        _ -> {false, lang:get("前置条件不足")}
                    end;
                _ -> {false, lang:get("没有找到配置")}
            end;
        {false, Reason} -> {false, Reason}
    end.

do_reward(Role = #role{classes = Classes, sex = Sex,
                       lev = Lev,
                       m_lev_break = #m_lev_break{times = LevBreak}},
          CampEx = #camp_exchange{list = List, lev = ELev,
                                  num = OldNum, camp_id = CampId},
          Num,
          #camp_exchange_data{id = Id, lev = CLev,
                              item_list = ItemList, min_lev = MinLev,
                              max_lev = MaxLev, sex = ISex, classes = IClasses,
                              min_lev_break = MinLevBreak,
                              max_lev_break = MaxLevBreak, cost = Cost},
          #{day_list := DayList, day_num := DayNum}) ->
    ItemList2 = [{ItemId, Bind, Number}
                 || {ItemId, Bind, Number, _Eff} <- ItemList],
    case OldNum >= Cost of
        true ->
            Gain = format:val_to_gain(ItemList2),
            case (MinLev == 0 andalso MaxLev == 0 orelse
                      Lev >= MinLev andalso Lev =< MaxLev)
                     andalso
                     (ISex == 2 orelse Sex == ISex) andalso
                         (IClasses == 0 orelse IClasses == Classes) andalso
                             (MinLevBreak == 0 andalso MaxLevBreak == 0 orelse
                                  LevBreak >= MinLevBreak andalso
                                      LevBreak =< MaxLevBreak)
                of
                true ->
                    case role_gain:do_notice(Gain, Role, lang:get("礼券兑换"))
                        of
                        {ok,
                         NRole = #role{m_campaign = MCamp = #m_campaign{}}} ->
                            NewList = lists:keystore(Id,
                                                     1,
                                                     List,
                                                     {Id, Num + 1}),
                            NewDayList = lists:keystore(Id,
                                                        1,
                                                        DayList,
                                                        {Id, DayNum + 1}),
                            NewELev = max(ELev, CLev),
                            NewCampEx = CampEx#camp_exchange{list = NewList,
                                                             lev = NewELev,
                                                             num =
                                                                 OldNum - Cost},
                            NewMCamp = MCamp#m_campaign{camp_exchange =
                                                            NewCampEx},
                            NRole2 = NRole#role{m_campaign = NewMCamp},
                            NewRole = var:set_var(NRole2,
                                                  other,
                                                  {606, CampId},
                                                  NewDayList),
                            logger:debug("======================:~w",
                                         [{NewDayList, NewList}],
                                         camp_exchange,
                                         244),
                            push(NewRole),
                            {ok, NewRole};
                        {false, #loss{}} -> {false, lang:get("礼券不足，无法兑换")};
                        {false, _} -> {false, lang:get("背包空间不足")}
                    end;
                _ -> {false, lang:get("该道具对你无用")}
            end;
        _ -> {false, lang:get("礼券不足，不能兑换")}
    end.

