do_point({m_attr_point,
          Point,
          ExtPoint,
          Strength,
          Constitution,
          Magic,
          Agility,
          Endurance,
          PreStr,
          PreCon,
          PreMag,
          PreAgi,
          PreEnd},
         _Lev) ->
    Ver = 1,
    FirstFree = 0,
    do_point({m_attr_point,
              Ver,
              Point,
              ExtPoint,
              Strength,
              Constitution,
              Magic,
              Agility,
              Endurance,
              PreStr,
              PreCon,
              PreMag,
              PreAgi,
              PreEnd,
              FirstFree},
             _Lev);
do_point({m_attr_point,
          Ver = 1,
          _Point,
          ExtPoint,
          Strength,
          Constitution,
          Magic,
          Agility,
          Endurance,
          PreStr,
          PreCon,
          PreMag,
          PreAgi,
          PreEnd,
          FirstFree},
         Lev) ->
    NewVer = Ver + 1,
    DefaultPlanData = {attr_point_plan,
                       1,
                       "",
                       Strength - Lev,
                       Constitution - Lev,
                       Magic - Lev,
                       Agility - Lev,
                       Endurance - Lev,
                       PreStr,
                       PreCon,
                       PreMag,
                       PreAgi,
                       PreEnd},
    ChangePlanTimes = 0,
    do_point({m_attr_point,
              NewVer,
              ExtPoint,
              FirstFree,
              1,
              [DefaultPlanData],
              ChangePlanTimes},
             Lev);
do_point(Mattr = #m_attr_point{}, _) -> {ok, Mattr};
do_point(_Err, _) ->
    logger:error("加点版本错误:~w", [_Err], attr_ver, 46),
    {false, "角色加点版本转换失败"}.

