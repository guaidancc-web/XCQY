                                                  of
                                                  {TrupId, Num}
                                                      when Num + 1 =:=
                                                               ExchangeNum ->
                                                      {lists:keyreplace(TrupId,
                                                                        1,
                                                                        OwnedItems,
                                                                        {TrupId,
                                                                         Num +
                                                                             1}),
                                                       lists:keystore(GroupId,
                                                                      1,
                                                                      NewExOrder,
                                                                      {GroupId,
                                                                       OrderId})};
                                                  {TrupId, Num}
                                                      when Num + 1 <
                                                               ExchangeNum ->
                                                      {lists:keyreplace(TrupId,
                                                                        1,
                                                                        OwnedItems,
                                                                        {TrupId,
                                                                         Num +
                                                                             1}),
                                                       NewExOrder};
                                                  {TrupId, Num}
                                                      when Num + 1 >
                                                               ExchangeNum ->
                                                      {OwnedItems, NewExOrder};
                                                  _ when ExchangeNum =:= 1 ->
                                                      {[{TrupId, 1}
                                                        | OwnedItems],
                                                       lists:keystore(GroupId,
                                                                      1,
                                                                      NewExOrder,
                                                                      {GroupId,
                                                                       OrderId})};
                                                  _ ->
                                                      {[{TrupId, 1}
                                                        | OwnedItems],
                                                       NewExOrder}
                                              end,
                    case NOwnedItems of
                        OwnedItems -> {false, lang:get("已达兑换上限")};
                        _ ->
                            Loss = format:val_to_loss([{90066, Cost}]),
                            Gain = format:val_to_gain([{ItemId,
                                                        Bind,
