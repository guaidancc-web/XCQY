exchange_honor_cb(#role{id = {RoleId, Platform, Zone},
                        sex = Sex,
                        m_wedding =
                            Wedding = #m_wedding{honor_ids = HonorIds}} =
                      Role,
                  Id) ->
    logger:debug("兑换称号,另一方处理 ~w~n",
                 [Id],
