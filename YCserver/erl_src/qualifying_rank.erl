merge_role_mark(RankMarks, []) -> RankMarks;
merge_role_mark(RankMarks,
                [Mark = #qualifying_role_mark{id = RoleId} | T]) ->
    NewRankMarks = lists:keystore(RoleId,
                                  #qualifying_role_mark.id,
                                  RankMarks,
                                  Mark),
    merge_role_mark(NewRankMarks, T).

friend_role_to_qualifying_mark([], QualifyingMark) ->
    QualifyingMark;
friend_role_to_qualifying_mark([#friend_role{id =
                                                 RoleId,
                                             name = Name, lev = Lev, sex = Sex,
                                             classes = Classes,
                                             qualifying =
                                                 #m_qualifying{rank_point =
                                                                   RankPoint,
                                                               season_combat_count
                                                                   =
                                                                   SeasonCombatCount,
                                                               season_win_count
                                                                   =
                                                                   SeasonWinCount}}
                                | T],
                               QualifyingMark) ->
    RankLev = qualifying_data:point_to_lev(RankPoint),
    Mark = #qualifying_role_mark{id = RoleId, name = Name,
                                 rank_point = RankPoint, rank_lev = RankLev,
                                 lev = Lev, sex = Sex, classes = Classes,
                                 season_combat_count = SeasonCombatCount,
                                 season_win_count = SeasonWinCount},
    friend_role_to_qualifying_mark(T,
                                   [Mark | QualifyingMark]).

to_rank_rc([], _Now, RankRcList) ->
    lists:reverse(RankRcList);
to_rank_rc([#qualifying_role_mark{id =
                                      {RoleId, Platform, ZoneId},
                                  name = Name, sex = Sex, classes = Classes,
                                  rank_point = RankPoint, rank_lev = RankLev,
                                  lev = Lev}
            | T],
           Now, RankRcList) ->
    RankRc = #rank_rc{id = {RoleId, Platform, ZoneId},
                      role_id = RoleId, platform = Platform, zone_id = ZoneId,
                      name = Name, sex = Sex, classes = Classes, lev = Lev,
                      time = Now, val1 = RankPoint, val2 = RankLev},
    to_rank_rc(T, Now, [RankRc | RankRcList]).

