sow(Role = #role{m_guild = #m_guild{pid = GPid},
                 s_event = 2, pid = Pid},
    X, Y) ->
    Done = var:get_var(Role, day_five, 138, 0),
    HasQuest = quest_guild:can_plant(Role),
    case lists:member({X, Y},
                      quest_guild_data:get_plant_pos())
        of
        _ when Done >= 1 andalso HasQuest =/= true ->
            {false, lang:get("今天种花次数已用完")};
        true ->
            BaseId = phase_to_unit(0),
            Plant = make_plant(Role, {BaseId, X, Y}),
            case guild:apply(sync,
                             GPid,
                             {guild_plant, apply_guild, [{sow, Plant, Pid}]})
                of
                ok ->
                    Role1 = var:acc_var(Role, day_five, 138),
                    {ok, Role1};
                Else -> Else
            end;
        _ -> {false, lang:get("这个地方不能种花哦")}
    end;
sow(#role{}, _, _) -> {false, lang:get("不能种植")}.

