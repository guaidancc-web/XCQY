    do_calc_all(X,
                Y,
                {OL1, OL2, OL3, OL4, OL5},
                L1,
                L2,
                T3,
                OL4,
                OL5);
do_calc_all(X, Y, {OL1, OL2, OL3, OL4, OL5}, L1, L2, L3,
            [_ | T4], []) ->
    do_calc_all(X,
                Y,
                {OL1, OL2, OL3, OL4, OL5},
                L1,
                L2,
                L3,
                T4,
                OL5);
do_calc_all(X, Y, {OL1, OL2, OL3, OL4, OL5}, [H1 | T1],
            [H2 | T2], [H3 | T3], [H4 | T4], [H5 | T5]) ->
    case {H1, H2, H3, H4, H5} of
        {{X1, Y1}, {X2, Y2}, {X3, Y3}, {X4, Y4}, {X5, Y5}}
            when X1 + X2 + X3 + X4 + X5 =:= X andalso
                     Y1 + Y2 + Y3 + Y4 + Y5 =:= Y ->
            {true, {H1, H2, H3, H4, H5}};
        _ ->
            do_calc_all(X,
                        Y,
                        {OL1, OL2, OL3, OL4, OL5},
                        [H1 | T1],
                        [H2 | T2],
                        [H3 | T3],
                        [H4 | T4],
                        T5)
    end.

calc_study(Z) -> calc_study(Z, {0, 0}, []).

calc_study(_Z, {X, _}, Result) when X >= 50 ->
    lists:reverse(Result);
calc_study(Z, {X, Y}, Result) ->
    Z1 = 2 * X + 5 * Y,
    if Z1 =:= Z ->
           calc_study(Z, {X + 1, 0}, [{X, Y} | Result]);
       Z1 > Z ->
           case Y =:= 0 of
               true -> lists:reverse(Result);
               _ -> calc_study(Z, {X + 1, 0}, Result)
           end;
       true -> calc_study(Z, {X, Y + 1}, Result)
    end.

