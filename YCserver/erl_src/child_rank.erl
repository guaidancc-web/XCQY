init() ->
    dets:open_file(child_rank,
                   [{file, "./dets/child_rank.dets"},
                    {keypos, #child_rank.type},
                    {type, set}]),
    ets:new(child_rank,
            [set, named_table, public, {keypos, #child_rank.type}]),
    dets:to_ets(child_rank, child_rank).

fetch(Type) ->
    case ets:lookup(child_rank, Type) of
        [Rank = #child_rank{}] -> Rank;
        _ -> false
    end.

in(Child = #child{stage = 3}) ->
    Rc = to_rc(Child),
    child:apply(async, {child_rank, apply_in, [Rc]});
in(_) -> ok.

best_in(L) ->
    case [C || C = #child{stage = 3} <- L] of
        [H | T] ->
            case util:keys_sort([#child.talent], [H | T]) of
                [Best | _] -> in(Best);
                _ -> ok
            end;
        _ -> ok
    end.

get_order(Role = #role{id = Id}, Type = 55) ->
    Custody = child:get_custody(Role),
    case fetch(1) of
        #child_rank{list = L} ->
            {Idx, Val} = do_get_order(L, Id, Custody),
            {Type, Idx, Val};
        _ -> {Type, 0, 0}
    end.

apply_in(Child = #child_rank_rc{}) -> do_in([1], Child);
apply_in(_) -> ok.

do_in([], _) -> ok;
do_in([Type = 1 | T],
      Rc = #child_rank_rc{id = Id, custody = Custody,
                          val1 = Talent}) ->
    case fetch(Type) of
        Rank = #child_rank{list = L} ->
            NL = case lists:keyfind(Custody,
                                    #child_rank_rc.custody,
                                    L)
                     of
                     #child_rank_rc{id = Id} ->
                         lists:keyreplace(Id, #child_rank_rc.id, L, Rc);
                     #child_rank_rc{val1 = Val1} when Val1 >= Talent -> L;
                     _ ->
                         L1 = lists:keydelete(Custody,
                                              #child_rank_rc.custody,
                                              L),
                         lists:keystore(Id, #child_rank_rc.id, L1, Rc)
                 end,
            NL1 = util:keys_sort(sorting_keys(Type), NL),
            NL2 = add_order(NL1, 1),
            update(Rank#child_rank{list = NL2});
        _ -> update(#child_rank{type = Type, list = [Rc]})
    end,
    do_in(T, Rc).

update(Rank = #child_rank{}) ->
    ets:insert(child_rank, Rank),
    dets:insert(child_rank, Rank);
update(_Err) ->
    logger:error("无效数据 ~w", [_Err], child_rank, 109),
    ok.

add_order([], _) -> [];
add_order(_, Order) when Order > 100 -> [];
add_order([Rc | T], Order) ->
    [Rc#child_rank_rc{rank = Order} | add_order(T,
                                                Order + 1)].

sorting_keys(1) ->
    [#child_rank_rc.val2, #child_rank_rc.val1];
sorting_keys(_) ->
    [#child_rank_rc.val2, #child_rank_rc.val1].

to_rc(#child{id = Id, custody = Custody,
             base_id = BaseId, sex = Sex, classes = Classes,
             classes_type = ClassesType, parents = Parents,
             talent = Talent, lev = Lev, name = Name}) ->
    {FatherName, FatherClasses, MotherName, MotherClasses} =
        case Custody of
            {_, _} ->
                case Parents of
                    [#child_parent{sex = 1, name = FName,
                                   classes = FClasses},
                     #child_parent{name = Mname, classes = MClasses}
                     | _] ->
                        {FName, FClasses, Mname, MClasses};
                    [#child_parent{name = Mname, classes = MClasses},
                     #child_parent{name = FName, classes = FClasses}
                     | _] ->
                        {FName, FClasses, Mname, MClasses};
                    [#child_parent{sex = 1, name = FName,
                                   classes = FClasses}] ->
                        {FName, FClasses, "", 0};
                    [#child_parent{name = Mname, classes = MClasses}] ->
                        {"", 0, Mname, MClasses};
                    _ -> {"", 0, "", 0}
                end;
            _ ->
                case lists:keyfind(Custody, #child_parent.id, Parents)
                    of
                    #child_parent{sex = 1, name = FName,
                                  classes = FClasses} ->
                        {FName, FClasses, "", 0};
                    #child_parent{name = Mname, classes = MClasses} ->
                        {"", 0, Mname, MClasses};
                    _ -> {"", 0, "", 0}
                end
        end,
    #child_rank_rc{id = Id, custody = Custody,
                   base_id = BaseId, sex = Sex, classes = Classes,
                   classes_type = ClassesType, name = Name,
                   father_name = FatherName,
                   father_classes = FatherClasses,
                   mother_name = MotherName,
                   mother_classes = MotherClasses, val1 = Talent,
                   val2 = Lev, time = date:unixtime()}.

do_get_order([], _, _) -> {0, 0};
do_get_order([#child_rank_rc{custody = Id, rank = Rank,
                             val1 = Val1}
              | _],
             Id, _) ->
    {Rank, Val1};
do_get_order([#child_rank_rc{custody = Id, rank = Rank,
                             val1 = Val1}
              | _],
             _, Id) ->
    {Rank, Val1};
do_get_order([_ | T], Id, Custody) ->
    do_get_order(T, Id, Custody).

