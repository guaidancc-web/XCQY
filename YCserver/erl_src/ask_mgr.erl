                         undefined -> 0;
                         TmpZoneId -> TmpZoneId
                     end,
            logger:info("[~w] 启动完成", [ask_mgr], ask_mgr, 146),
            {ok,
             State#ask_state{platform = Pltm, zone_id = ZoneId}};
