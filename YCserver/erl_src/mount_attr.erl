calc(Ac = #attr_calc{}, Role) ->
    Attr = calc_mount(Role),
    MountAttr = attr_type:to_attr(fixed, Attr),
    case attr_type:do_attr(MountAttr, Ac) of
        {false, Reason} ->
            logger:error("坐骑属性计算失败:~w", [Reason], mount_attr, 40),
            Ac;
        {ok, NewAc} -> NewAc
    end.

calc_skill_prac(Role = #role{}) ->
    MountSkill = mount:get_mount_skills(Role),
    AllSkillPrac = do_calc_skill_prac(MountSkill, []),
    NewRole = skill_prac:upgrade(Role, 3, AllSkillPrac, 1),
    NewRole.

do_calc_skill_prac([], List) -> List;
do_calc_skill_prac([#mount_skill{skill_id = SkillId,
                                 skill_lev = SkillLev}
                    | T],
                   List) ->
    case skill_data:get_mount({SkillId, SkillLev}) of
        #{effect_type := 1,
          skill_prac := SkillPrac = [_ | _]} ->
            Fun = fun ({SklId, SklLev}, AllList) ->
                          NewSklLev = case lists:keyfind(SklId, 1, AllList) of
                                          {_, OldSklLev} -> OldSklLev + SklLev;
                                          _ -> SklLev
                                      end,
                          lists:keystore(SklId, 1, AllList, {SklId, NewSklLev})
                  end,
            NewList = lists:foldl(Fun, List, SkillPrac),
            do_calc_skill_prac(T, NewList);
        _Err -> do_calc_skill_prac(T, List)
    end;
do_calc_skill_prac([_ | T], List) ->
    do_calc_skill_prac(T, List).

calc_mount(Role = #role{pid = Pid, classes = Classes,
                        s_ride = RideStatus,
                        m_mount =
                            #m_mount{ride_mount = RideMount, mounts = Mounts,
                                     appearance_list = AppearanceList}}) ->
    SpeedAttr = case lists:keyfind(RideMount,
                                   #mount.index,
                                   Mounts)
                    of
                    #mount{live_status = 3, spirit = Spirit,
                           mount_base_id = MountBaseId,
                           transformation_id = TransformationId,
                           decorate_list = DecorateList}
                        when Spirit >= 10 ->
                        case RideStatus =:= 1 of
                            true ->
                                case lists:keyfind(2,
                                                   #mount_decorate.decorate_index,
                                                   DecorateList)
                                    of
                                    #mount_decorate{decorate_base_id =
                                                        DecorateBaseId} ->
                                        case
                                            mount_data:get_decorate(DecorateBaseId)
                                            of
                                            #{attr := DecorateAttr} ->
                                                BaseSpeedAttr = case
                                                                    TransformationId
                                                                        =:= 0
                                                                    of
                                                                    true ->
                                                                        mount_data:get_speed_attr(MountBaseId);
                                                                    false ->
                                                                        mount_data:get_speed_attr(TransformationId)
                                                                end,
                                                BaseSpeedAttr ++ DecorateAttr;
                                            _ -> []
                                        end;
                                    _ -> []
                                end;
                            false ->
                                BaseSpeedAttr = case TransformationId =:= 0 of
                                                    true ->
                                                        mount_data:get_speed_attr(MountBaseId);
                                                    false ->
                                                        mount_data:get_speed_attr(TransformationId)
                                                end,
                                DecorateSpeedAttr = case lists:keyfind(2,
                                                                       #mount_decorate.decorate_index,
                                                                       DecorateList)
                                                        of
                                                        #mount_decorate{decorate_base_id
                                                                            =
                                                                            DecorateBaseId} ->
                                                            case
                                                                mount_data:get_decorate(DecorateBaseId)
                                                                of
                                                                #{attr :=
                                                                      DecorateAttr} ->
                                                                    DecorateAttr;
                                                                _ -> []
                                                            end;
                                                        _ -> []
                                                    end,
                                BaseSpeedAttr ++ DecorateSpeedAttr
                        end;
                    _ -> []
                end,
    logger:debug("坐骑速度属性:~w", [SpeedAttr], mount_attr, 118),
    RoleMounts = get_mounts_attr_add_role(Role),
    BaseAttr = calc_mount_base_attr(Classes, RoleMounts),
    logger:debug("坐骑基础属性 ~w  全部属性 ~w",
                 [BaseAttr, calc_mount_base_attr(Classes, Mounts)],
                 mount_attr,
                 122),
    CollectAttr = calc_mount_collect_attr(Classes,
                                          AppearanceList),
    role_trigger:async_fire(Pid, #evt_mount_attr{}),
    SpeedAttr ++ CollectAttr ++ BaseAttr.

calc_mount_base_attr(Classes, Mounts) ->
    calc_mount_base_attr(Classes, Mounts, []).

calc_mount_base_attr(_Classes, [], BaseAttr) ->
    BaseAttr;
calc_mount_base_attr(Classes,
                     [#mount{live_status = 3, growth = Growth, index = Index,
                             lev = Lev, upgrade_lev = UpLev, spirit = Spirit}
                      | Rest],
                     BaseAttr) ->
    case Spirit >= 10 of
        true ->
            BaseAttrCfg = mount_data:get_base_attr({Index,
                                                    Classes,
                                                    Lev}),
            GrowthAttrAdd = mount_data:get_growth_add(Growth),
            NewBaseAttr = mount_merger_attr(BaseAttrCfg,
                                            GrowthAttrAdd),
            UpgradeAttr = mount_data:get_upgrade_attr({Index,
                                                       Classes,
                                                       UpLev}),
            CalcAttr = UpgradeAttr ++ NewBaseAttr ++ BaseAttr,
            calc_mount_base_attr(Classes, Rest, CalcAttr);
        false -> calc_mount_base_attr(Classes, Rest, BaseAttr)
    end;
calc_mount_base_attr(Classes, [_ | Rest], BaseAttr) ->
    calc_mount_base_attr(Classes, Rest, BaseAttr).

batch_calc_pet(Role = #role{m_mount =
                                #m_mount{mounts = Mounts},
                            m_pet = MPet = #m_pet{pets = Pets}}) ->
    ChildRole = child_attr:batch_calc(Role),
    child_attr:push_client_childs(ChildRole),
    NewPets = [Pet#pet{mount_skills = []} || Pet <- Pets],
    Fun = fun (Index, FunRole) ->
                  batch_calc_pet(FunRole, Index)
          end,
    lists:foldr(Fun,
                ChildRole#role{m_pet = MPet#m_pet{pets = NewPets}},
                [MI || #mount{index = MI} <- Mounts]).

batch_calc_pet(Role = #role{m_mount =
                                #m_mount{mounts = Mounts}},
               Index) ->
    case lists:keyfind(Index, #mount.index, Mounts) of
        #mount{manger_pets = ManagerPets} = Mount ->
            PetMountSkills = get_pet_mount_skills(Mount),
            logger:debug("第~w只坐骑 契约宠物技能:~w",
                         [Index, PetMountSkills],
                         mount_attr,
                         165),
            batch_calc_mount_skill(Role,
                                   PetMountSkills,
                                   ManagerPets);
        _ -> Role
    end.

batch_calc_mount_skill(Role, _Skills, []) -> Role;
batch_calc_mount_skill(Role, Skills, [PetId | Rest]) ->
    NewRole = calc_mount_skill(Role, Skills, PetId),
    batch_calc_mount_skill(NewRole, Skills, Rest).

calc_mount_skill(Role = #role{m_pet =
                                  MPet = #m_pet{pets = Pets}},
                 Skills, PetId) ->
    case lists:keyfind(PetId, #pet.id, Pets) of
        Pet = #pet{mount_skills = OldSkills} ->
            {ok, NewPet, Role1} = pet_attr:calc(Pet#pet{mount_skills
                                                            =
                                                            OldSkills ++
                                                                Skills},
                                                Role),
            NewPets = lists:keyreplace(PetId,
                                       #pet.id,
                                       Pets,
                                       NewPet),
            NewRole = Role1#role{m_pet =
                                     MPet#m_pet{pets = NewPets}},
            pet:push_10503(NewRole, NewPet),
            NewRole;
        false -> Role
    end.

get_pet_mount_skills(#mount{skill_list = Skills,
                            spirit = Spirit}) ->
    case Spirit >= 100 of
        true ->
            Fun = fun (#mount_skill{skill_id = SkillId,
                                    skill_lev = SkillLev}) ->
                          case skill_data:get_mount({SkillId, SkillLev}) of
                              #{effect_type := 2} -> true;
                              _ -> false
                          end
                  end,
            lists:filter(Fun, Skills);
        false -> []
    end.

mount_merger_attr(BaseAttr, GrowthAttrAdd) ->
    mount_merger_attr(BaseAttr, GrowthAttrAdd, []).

mount_merger_attr([], _GrowthAttrAdd, NewBaseAttr) ->
    NewBaseAttr;
mount_merger_attr([{AttrType, Val} | Rest],
                  GrowthAttrAdd, NewBaseAttr) ->
    case lists:keyfind(AttrType, 1, GrowthAttrAdd) of
        {_, Percent} ->
            NewVal = util:ceil(Val * Percent / 1000),
            mount_merger_attr(Rest,
                              GrowthAttrAdd,
                              [{AttrType, NewVal} | NewBaseAttr]);
        _ ->
            mount_merger_attr(Rest,
                              GrowthAttrAdd,
                              [{AttrType, Val} | NewBaseAttr])
    end.

calc_mount_collect_score(#role{classes = Classes,
                               m_mount =
                                   #m_mount{appearance_list =
                                                AppearanceList}}) ->
    calc_appearance_score(AppearanceList, Classes, 0).

calc_mount_collect_attr(Classes, AppearanceList) ->
    calc_mount_collect_attr(Classes, AppearanceList, []).

calc_mount_collect_attr(_Classes, [], AppearanceAttr) ->
    AppearanceAttr;
calc_mount_collect_attr(Classes,
                        [{AppearanceId, Expire} | Rest], AppearanceAttr) ->
    logger:debug("计算坐骑暗属性:~w",
                 [{AppearanceId, Expire}],
                 mount_attr,
                 243),
    Now = date:unixtime(),
    case Expire > Now orelse Expire =:= 0 of
        true ->
            AttrCfg = mount_data:get_appearance_attr({AppearanceId,
                                                      Classes}),
            CommonClassAttrCfg =
                mount_data:get_appearance_attr({AppearanceId, 0}),
            calc_mount_collect_attr(Classes,
                                    Rest,
                                    AttrCfg ++
                                        CommonClassAttrCfg ++ AppearanceAttr);
        _ ->
            calc_mount_collect_attr(Classes, Rest, AppearanceAttr)
    end.

calc_mount_score(#mount{live_status = 3, index = Index,
                        growth = Growth, lev = Lev, skill_list = SkillList}) ->
    GrowthVal = mount_data:get_growth_val({Index, Growth}),
    AttrScore = round(2 * math:pow(GrowthVal / 1250, 2) *
                          (50 + Lev * 10)),
    SkillScore = calc_mount_skill_score(SkillList),
    AttrScore + SkillScore;
calc_mount_score(#mount{}) -> 0;
calc_mount_score(#role{classes = Classes,
                       m_mount =
                           #m_mount{mounts = Mounts,
                                    appearance_list = AppearanceList}}) ->
    MounsScore = calc_mount_score(Mounts, 0),
    AppearanceScore = calc_appearance_score(AppearanceList,
                                            Classes,
                                            0),
    MounsScore + AppearanceScore.

calc_mount_score([], Score) -> Score;
calc_mount_score([#mount{score = MountScore} | Rest],
                 Score) ->
    calc_mount_score(Rest, MountScore + Score);
calc_mount_score([_ | Rest], Score) ->
    calc_mount_score(Rest, Score).

calc_mount_skill_score(#role{m_mount =
                                 #m_mount{mounts = Mounts}}) ->
    calc_mount_skill_score(Mounts, 0);
calc_mount_skill_score(SkillList) ->
    calc_mount_skill_score(SkillList, 0).

calc_mount_skill_score([], SkillScore) -> SkillScore;
calc_mount_skill_score([#mount_skill{skill_id = SklId,
                                     skill_lev = SklLev}
                        | Rest],
                       SkillScore) ->
    case skill_data:get_mount({SklId, SklLev}) of
        #{score := Score} ->
            calc_mount_skill_score(Rest, Score + SkillScore);
        _ -> calc_mount_skill_score(Rest, SkillScore)
    end;
calc_mount_skill_score([#mount{live_status = 3,
                               skill_list = SkillList}
                        | T],
                       Score) ->
    Score1 = calc_mount_skill_score(SkillList, 0),
    calc_mount_skill_score(T, Score + Score1);
calc_mount_skill_score([_ | T], Score) ->
    calc_mount_skill_score(T, Score).

calc_mount_lev_score(#role{m_mount =
                               #m_mount{mounts = Mounts}}) ->
    MounsScore = calc_mount_lev_score(Mounts, 0),
    MounsScore.

calc_mount_lev_score([], Score) -> Score;
calc_mount_lev_score([#mount{live_status = 3,
                             index = Index, growth = Growth, lev = Lev}
                      | T],
                     Score) ->
    GrowthVal = mount_data:get_growth_val({Index, Growth}),
    AttrScore = round(2 * math:pow(GrowthVal / 1250, 2) *
                          (50 + Lev * 10)),
    calc_mount_lev_score(T, Score + AttrScore);
calc_mount_lev_score([_ | Rest], Score) ->
    calc_mount_lev_score(Rest, Score).

calc_mount_growth_score(Role) ->
    MountScore = calc_mount_score(Role),
    LevScore = calc_mount_lev_score(Role),
    SkillScore = calc_mount_skill_score(Role),
    MountScore - LevScore - SkillScore.

calc_mount_score_client(#role{m_mount =
                                  #m_mount{mounts = Mounts}},
                        Index) ->
    case lists:keyfind(Index, #mount.index, Mounts) of
        #mount{score = Score} -> round(Score * 5);
        _ -> 0
    end.

