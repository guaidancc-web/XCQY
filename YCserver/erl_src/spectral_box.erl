rand_reward(Role = #role{lev = Lev}, BaseId, VarType) ->
    case VarType =:= 0 of
        true -> 0;
        _ ->
            TurnTimes = var:get_var(Role, other, VarType, 0),
            LogList = var:get_var(Role, day, 141, []),
            RankList = spectral_box_data:type_id(BaseId),
            FilterList = filter_reward(RankList,
                                       Lev,
                                       TurnTimes,
                                       LogList),
            case util:rand_list(FilterList, 2) of
                {Id, _Ratio} -> Id;
                _ ->
                    logger:error("鸿福宝箱随机配置错误：~w",
                                 [FilterList],
                                 spectral_box,
                                 389),
                    0
            end
    end.

filter_reward([], _, _, _) -> [];
filter_reward([#{id := Id, weigth := Ratio,
                 must_no := MustNo, max_num := Max, lev_min := LevMin,
                 lev_max := LevMax}
               | T],
              Lev, TurnTimes, LogList)
    when TurnTimes >= MustNo ->
    case lists:keyfind(Id, 1, LogList) of
        _
            when LevMin =/= 0 andalso Lev < LevMin orelse
                     LevMax =/= 0 andalso Lev > LevMax ->
            filter_reward(T, Lev, TurnTimes, LogList);
        {_, N} when Max =/= 0 andalso N >= Max ->
            filter_reward(T, Lev, TurnTimes, LogList);
        _ ->
            [{Id, Ratio} | filter_reward(T,
                                         Lev,
                                         TurnTimes,
                                         LogList)]
    end;
filter_reward([_ | T], Lev, TurnTimes, LogList) ->
    filter_reward(T, Lev, TurnTimes, LogList).

